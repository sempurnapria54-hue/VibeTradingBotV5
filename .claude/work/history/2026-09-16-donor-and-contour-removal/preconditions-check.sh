#!/usr/bin/env bash
# Проверка реестра гейтящих предусловий CODE против тест-плана контура.
#
# Оси проверки — каждая поднимает дефект до кода возврата; каждая доказана
# падающей пробой (стандарт «падающая проба по каждой объявленной оси» —
# .claude/processes/roadmap-step-execution.md §«То же — у команды,
# объявленной проверкой»; пробы — code-preconditions.md §«Сверка реестра
# с планом — исполнимой проверкой»):
#   1) слот-сверка — множество пар «пункт × кейс» реестра == множеству пар,
#      объявленных гейт-заголовками плана ("**ГЕЙТИТ `CODE`** (предусловия п. N …)");
#      плановая сторона разбирает формы «п. N», «пп. N и M», «пп. N, M и K» —
#      номера принимаются только в списке, открытом маркером «п.»/«пп.»;
#   2) разведённость слота — в одной строке реестра ровно один кейс
#      (иначе статус наблюдения нельзя назначить покейсно);
#   3) носители прогона — клейм колонки «Носитель прогона» СТРОКИ РЕЕСТРА
#      (слота, а не кейса) сверяется с фактикой кейса (греп кейса по каталогу
#      код-тестов). Клеймов столько же, сколько строк, а тест-метод у кейса
#      один: слияние строк одного кейса в общий клейм пропускало строку, не
#      именующую носителя. Строка, объявившая код-тест и не назвавшая его
#      формой <Класс>LiveTest[.<метод>], — ДЕФЕКТ: такой клейм не измеряется;
#      расхождение в обе стороны — дефект: носитель объявлен, но не найден,
#      либо носитель существует, а колонка говорит «нет».
#      НОСИТЕЛЕМ СЧИТАЕТСЯ ТОЛЬКО ИСПОЛНИМАЯ СТРОКА: комментарии
#      ВЫЧИЩАЮТСЯ ИЗ СТРОК до грепа — trailing-`//`, однострочный
#      `/*...*/`, открывающий `/*` до конца строки и продолжения javadoc
#      с ведущей `*`. Прежний фильтр отбрасывал только строки,
#      НАЧИНАЮЩИЕСЯ с маркера, и не видел однострочного javadoc и
#      trailing-комментария (F-1 DOCS_CHECK_33); упоминание кейса в
#      комментарии засчитывалось носителем и давало ложное покрытие.
#      Граница формы объявлена: код после закрытия `/*...*/` на той же
#      строке вычищается вместе с комментарием (ложный красный,
#      консервативно — как и строковый литерал с `//`); продолжения
#      блок-комментария БЕЗ ведущей `*` не вычищаются — единственная
#      непокрытая форма с направлением ложного покрытия.
#      Коллекция из оси ВЫВЕДЕНА: она не аппрув-артефакт и не исполнитель
#      прогона (.claude/decisions/collection-not-approval-artifact.md),
#      поэтому клейм о ней измерял бы третью запись того же знания.
#      Кейс ищется КАК ИДЕНТИФИКАТОР, а не как регулярка: точка экранируется,
#      границы стоят с ОБЕИХ сторон — «M17.5» не совпадает ни с «M1755», ни
#      с «M17.55»; «AG6.1» — ни с «AG6X1» (левая), ни с «AG6.1b» (правая).
#      Обе границы доказаны своими пробами (code-preconditions.md §«Сверка
#      реестра с планом — исполнимой проверкой»). Дефект латентный: на
#      действительном состоянии формы шаблона дают одно и то же, но носитель
#      мог подтвердиться ЧУЖИМ кейсом. Входной набор — идентификаторы вида
#      <буквы><цифры>.<цифры> из колонки «Кейс»; имена с буквенным хвостом
#      («M16.neg» и его под-кейсы) в реестр не входят и этой границей не
#      затрагиваются.
#
# Колонки берутся ПО ИМЕНАМ шапки таблицы («Пункт»/«№», «Кейс», «Носитель
# прогона»), не по позиции: смена формы таблицы обязана ронять проверку
# громко, а не менять смысл вывода молча.
#
# Использование:
#   bash tools/preconditions-check.sh [<plan.md> <code-preconditions.md> <src-test-dir>]
# Без аргументов — умолчания для контура OKX (шаг 7 фазы 1).
# Код возврата: 0 — сошлось по всем осям; 1 — расхождение/дефект любой оси;
# 2 — ПРОВЕРКА НЕ ПРОВОДИЛАСЬ: вход не разобран (нет файла/каталога, не
# разобрана шапка таблицы или гейт-заголовки плана). Код общий со всеми
# проверочными командами корпуса — «не измерялось» отделено от «дефектов
# нет» (.claude/processes/roadmap-step-execution.md §«Измерительная команда
# отказывается, когда мерить нечего»).
#
# ЧЕГО У ЭТОЙ КОМАНДЫ ПОКА НЕТ: батарея её осей живёт ВНЕ команды —
# разделом .claude/tests/source-api/okx/code-preconditions.md §«Сверка
# реестра с планом — исполнимой проверкой». Это остаток прежней конструкции,
# и он назван, а не замаскирован: перенос батареи внутрь — задача
# .claude/work/backlog.md §«Батарея осей проверки предусловий — внутрь
# команды».

set -u
PLAN="${1:-.claude/tests/source-api/okx/plan.md}"
REG="${2:-.claude/tests/source-api/okx/code-preconditions.md}"
TESTS="${3:-donor/src/test/java/com/example/tradingbot/integration/sourceapi/okx/}"

for f in "$PLAN" "$REG"; do
  [ -f "$f" ] || { echo "ОШИБКА: нет файла $f" >&2; exit 2; }
done
[ -d "$TESTS" ] || { echo "ОШИБКА: нет каталога код-тестов $TESTS" >&2; exit 2; }

rc=0
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

# --- ось 1, плановая сторона: пары «кейс пункт» из гейт-заголовков
grep '^### .*ГЕЙТИТ' "$PLAN" \
| sed -E 's/^### ([A-Za-z0-9.]+).*ГЕЙТИТ[^(]*\((.*)\) *$/\1 :: \2/' \
| awk -F' :: ' '{
    tail=$2; gsub(/пп\./,"п.",tail)
    n=split(tail,t,/[ ,;:()]+/); inlist=0
    for(i=1;i<=n;i++){
      if(t[i]=="п.")                   { inlist=1; continue }
      if(inlist && t[i] ~ /^[0-9]+$/)  { print $1" "t[i]; continue }
      if(inlist && t[i]=="и")          { continue }
      inlist=0
    }
  }' \
| sort -u > "$tmp/plan-pairs"

[ -s "$tmp/plan-pairs" ] || { echo "ОШИБКА: в плане не разобран ни один гейт-заголовок — форма заголовков изменилась" >&2; exit 2; }

# --- охрана ПОЗАГОЛОВОЧНАЯ: каждый гейт-заголовок обязан дать хотя бы одну
# пару. Проверка «разобран хоть один» (выше) молчит, когда потерян ОДИН из
# многих: заголовок с непредусмотренной формой хвоста — «(предусловие 18)»
# без маркера «п.» — либо с канонической формой без пробела — «(п.18)» —
# просто не даёт пар, и гейт по нему не срабатывает. Порог ошибки поэтому
# не смена конвенции, а опечатка в пробеле.
grep '^### .*ГЕЙТИТ' "$PLAN" | sed -E 's/^### ([A-Za-z0-9.]+).*/\1/' | sort -u > "$tmp/plan-cases"
cut -d' ' -f1 "$tmp/plan-pairs" | sort -u > "$tmp/parsed-cases"
if ! comm -23 "$tmp/plan-cases" "$tmp/parsed-cases" > "$tmp/lost" || [ -s "$tmp/lost" ]; then
  if [ -s "$tmp/lost" ]; then
    while read -r c; do
      echo "ДЕФЕКТ: гейт-заголовок кейса $c не дал ни одной пары «пункт × кейс» — хвост заголовка не разобран" >&2
    done < "$tmp/lost"
    exit 1
  fi
fi

# --- реестр: пары «кейс пункт» (оси 1-2) и клеймы носителей (ось 3).
# Без пайпа: код выхода awk обязан доехать до rc (дефект оси 2 — exit 4).
awk -F'|' '
  function trim(s){gsub(/^[ \t]+|[ \t]+$/,"",s); return s}
  /^\|/ && (p==0 || c==0 || m==0) {
    for (i=2;i<=NF;i++){ h=trim($i); if (h=="Пункт"||h=="№") p=i; if (h=="Кейс") c=i; if (h=="Носитель прогона") m=i }
    if (p&&c&&m) next
  }
  /^\| *[0-9]+ *\|/ {
    if (!p||!c||!m) { print "ОШИБКА: шапка таблицы реестра не разобрана (нужны колонки «Пункт»/«№», «Кейс», «Носитель прогона»)" > "/dev/stderr"; exit 2 }
    nn=trim($p); k=$c; gsub(/`/,"",k); v=$m
    ct=(v ~ /код-тест/) ? 1 : 0
    carrier=v; gsub(/`/,"",carrier); gsub(/\t/," ",carrier)
    cnt=0; split("",ids)
    while (match(k,/[A-Za-z]+[0-9]+\.[0-9]+/)) { cnt++; ids[cnt]=substr(k,RSTART,RLENGTH); k=substr(k,RSTART+RLENGTH) }
    if (cnt==0) { print "ДЕФЕКТ: пункт "nn" — кейс не назван" > "/dev/stderr"; bad=1; next }
    if (cnt>1)  { print "ДЕФЕКТ: пункт "nn" — в одной строке "cnt" кейса ("ids[1]", "ids[2]"…): слот не разведён, статус наблюдения нельзя назначить покейсно" > "/dev/stderr"; bad=1 }
    for (j=1;j<=cnt;j++) { print ids[j]" "nn > PAIRS; print ids[j]"\t"nn"\t"ct"\t"carrier > CLAIMS }
  }
  END { if (bad) exit 4 }
' PAIRS="$tmp/reg-raw" CLAIMS="$tmp/claims-raw" "$REG"
awk_rc=$?
case "$awk_rc" in
  0) : ;;
  4) rc=1 ;;
  *) exit 2 ;;
esac

[ -s "$tmp/reg-raw" ] || { echo "ОШИБКА: из таблицы реестра не извлечено ни одной пары" >&2; exit 2; }
sort -u "$tmp/reg-raw" > "$tmp/reg-pairs"

if ! diff "$tmp/plan-pairs" "$tmp/reg-pairs" > "$tmp/d"; then
  echo "ДЕФЕКТ: множества слотов «пункт × кейс» расходятся (< только в плане, > только в реестре):"
  cat "$tmp/d"
  rc=1
fi

# --- ось 3: клейм колонки «Носитель прогона» против фактики.
# Клейм читается ПОСТРОЧНО (по слоту), фактика — ПО КЕЙСУ: тест-метод у кейса
# один, сколько бы строк реестра на него ни ссылалось, а клеймов столько же,
# сколько строк. Прежняя редакция сливала строки одного кейса в один клейм
# (максимум по признаку «код-тест», конкатенация текстов носителя), поэтому
# строка, НЕ ИМЕНУЮЩАЯ носителя разбираемой формой, проходила зелёной на
# соседней строке того же кейса — и ложный клейм строки не мерился ничем.
sort "$tmp/claims-raw" > "$tmp/claims"

echo "--- носители прогона (слот: фактика кейса; клейм строки)"
while IFS=$'\t' read -r c nn ct carrier; do
  # идентификатор, не регулярка: точка экранируется, по краям — границы
  cre="(^|[^0-9A-Za-z.])${c//./\\.}([^0-9A-Za-z.]|\\.[^0-9A-Za-z]|\\.$|$)"
  # Фактика по кейсу — ИСПОЛНИМАЯ строка: комментарии вычищаются ИЗ строки
  # до грепа (trailing-//, однострочный /*...*/, открывающий /* до конца
  # строки, продолжения javadoc с ведущей *), а не отбрасыванием строк,
  # НАЧИНАЮЩИХСЯ с маркера — прежний фильтр не видел однострочного javadoc
  # и trailing-комментария (F-1 DOCS_CHECK_33). Граница формы объявлена:
  # код после закрытия многострочного /*...*/ на той же строке вычищается
  # вместе с комментарием — полноценный парсер Java в bash не строится.
  t=$(for f in $(grep -rlE -- "$cre" "$TESTS" 2>/dev/null); do
        sed -e 's@//.*$@@' -e 's@/\*.*\*/@@g' -e 's@/\*.*$@@' \
            -e 's@^[[:space:]]*\*.*@@' "$f" \
          | grep -qE -- "$cre" && echo "$f"
      done | sort -u | wc -l | tr -d ' ')
  # Клейм колонки проверяется ПОИМЁННО: названный класс и названный метод
  # обязаны существовать. Прежняя редакция грепала идентификатор КЕЙСА, то
  # есть не читала колонку вовсе: подмена имени класса на несуществующий
  # проверку не роняла, и падающей пробы у оси не было.
  miss=""
  refs=$(printf '%s\n' "$carrier" | grep -oE '[A-Z][A-Za-z0-9]*LiveTest(\.[A-Za-z0-9_]+)?')
  for ref in $refs; do
    cls="${ref%%.*}"; mth="${ref#"$cls"}"; mth="${mth#.}"
    [ -f "$TESTS/$cls.java" ] || { miss="$miss класс $cls"; continue; }
    if [ -n "$mth" ] && ! grep -qE "[^A-Za-z0-9_]$mth *\(" "$TESTS/$cls.java"; then
      miss="$miss метод $cls.$mth"
    fi
  done
  printf 'п.%-3s %-8s исполнимых файлов=%s; строка реестра: код-тест=%s\n' \
    "$nn" "$c" "$t" "$([ "$ct" -eq 1 ] && echo да || echo нет)"
  if [ "$ct" -eq 1 ] && [ "$t" -eq 0 ]; then echo "ДЕФЕКТ: слот п. $nn × $c — реестр объявляет код-тест, исполнимой строки с кейсом в $TESTS нет" >&2; rc=1; fi
  if [ "$ct" -eq 0 ] && [ "$t" -gt 0 ]; then echo "ДЕФЕКТ: слот п. $nn × $c — код-тест существует ($t файл(ов)), колонка «Носитель прогона» его не называет" >&2; rc=1; fi
  # Клейм, который нечем измерить, — тоже дефект: строка объявляет код-тест и
  # не именует его разбираемой формой, поэтому поимённая сверка по ней не идёт.
  if [ "$ct" -eq 1 ] && [ -z "$refs" ]; then
    echo "ДЕФЕКТ: слот п. $nn × $c — колонка объявляет код-тест, но не именует носителя разбираемой формой <Класс>LiveTest[.<метод>]: клейм не измеряется" >&2
    rc=1
  fi
  if [ -n "$miss" ]; then echo "ДЕФЕКТ: слот п. $nn × $c — колонка называет носителя, которого нет:$miss" >&2; rc=1; fi
done < "$tmp/claims"

if [ $rc -eq 0 ]; then echo "СОШЛОСЬ: слоты реестра == гейт-пометки плана; носители соответствуют клейму реестра"; fi
exit $rc
