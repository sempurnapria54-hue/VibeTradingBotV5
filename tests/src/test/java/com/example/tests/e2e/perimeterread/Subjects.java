package com.example.tests.e2e.perimeterread;

import java.util.UUID;

/**
 * Субъекты предъявителя у тропы периметра — свежие у каждого класса.
 *
 * <p><b>Тенанта тропы заводит контекст субъекта</b>, и владелец членств
 * помнит субъекта, пока жива его база. Классы, делящие стенд, с
 * одноимёнными субъектами получили бы тенанта прежнего класса вместе с его
 * счётом, сделкой и строками журнала — и ассерты о радиусе тенанта мерили бы
 * чужое. Свежий субъект — свежий тенант, а тенант — первая половина пары
 * ходов (.claude/skills/test-code.md §«Уровень 3 — сквозной набор»).
 */
final class Subjects {

    private Subjects() {
    }

    /**
     * Свежий субъект роли.
     *
     * @param role роль субъекта в классе ({@code subject-s1} и т. п.)
     * @return субъект, которого стенд ещё не видел
     */
    static String fresh(String role) {
        return role + "-" + UUID.randomUUID().toString().substring(0, 8);
    }
}
