package com.example.connector.okx.credentials;

import com.example.tradingbot.domain.model.core.exchange_account.ExchangeAccount;
import lombok.ToString;
import lombok.Value;

/**
 * Ключи биржевого счёта и контур, к которому они принадлежат.
 *
 * <p><b>Ключ и контур — одна истина, поэтому и лежат вместе.</b>
 * Демо-ключ на боевой площадке отвергается площадкой, боевой на
 * демо-контуре — тоже; разведи их по двум носителям, и они разойдутся
 * молча (docs/architecture/platform.md §«Контур площадки — атрибут счёта,
 * допустимость — атрибут окружения»).
 *
 * <p><b>Живут только в памяти вызова.</b> Коннектор их не хранит: базы у
 * него нет по построению.
 *
 * <p><b>Текстовое представление секрета не несёт, и это НЕ повтор запрета
 * логировать.</b> Запрет адресован пишущему лог
 * (.claude/rules/codestyle.md §Логирование), а он ошибается: достаточно
 * одного {@code log.debug("креды {}", credentials)} — либо сообщения
 * отказа, куда объект попал целиком, — и секрет в журнале. Сгенерированный
 * {@code toString()} печатал бы все поля, то есть делал бы такую ошибку
 * дешёвой. Здесь он оставляет только контур: диагностика от этого не
 * страдает — по контуру и счёту вызов опознаётся, а ключ в журнале не
 * нужен никогда.
 */
@Value
@ToString(onlyExplicitlyIncluded = true)
public class ExchangeCredentials {

    /** API-ключ счёта. */
    String apiKey;

    /** Секрет ключа — HMAC-подпись запроса. */
    String secret;

    /** Passphrase ключа. */
    String passphrase;

    /**
     * Контур, к которому ключи принадлежат. Определяет заголовок
     * демо-контура у площадки — то есть форма выражения контура в
     * запросе, а не сам выбор контура: выбор сделан при регистрации
     * счёта.
     */
    @ToString.Include
    ExchangeAccount.Contour contour;

    /** Ключи принадлежат демо-контуру площадки. */
    public Boolean isDemo() {
        return ExchangeAccount.Contour.DEMO.equals(contour);
    }
}
