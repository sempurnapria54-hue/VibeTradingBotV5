-- Имя таблицы outbox во множественном числе.
--
-- Конвенция схемы: имена таблиц — во множественном числе
-- (.claude/rules/codestyle.md §«Схема БД»). Строка таблицы — событие,
-- ожидающее публикации, поэтому множественная форма имени — outbox_events,
-- а не outboxes: она называет содержимое, а не механизм.
--
-- Отдельной миграцией, а не правкой V1: V1 применена, и её контрольную
-- сумму Flyway держит по всему файлу — правка уронила бы старт у того, кто
-- миграций не трогал (.claude/rules/codestyle.md §«Применённая миграция
-- неизменяема — включая комментарии»).
--
-- Имена индекса и ограничения при переименовании таблицы Postgres не
-- трогает: они остаются в единственном числе и по конвенции такими и
-- должны быть (FK-колонки и имена constraint'ов/индексов — в единственном).

alter table outbox rename to outbox_events;
