-- Последнее наблюдение признака — носитель СЕРИИ гистерезиса на
-- наблюдательной строке отчёта (docs/components/AnomalyJob.md §«Такт и
-- гистерезис»).
--
-- Дедуп и подтверждение прежде читали одно поле — время создания стоящей
-- строки — и потому не различали «признак держится подряд» и «признак
-- замечен, пропал и вернулся в пределах окна». Колонка их разводит: дедуп
-- по-прежнему идёт по окну от времени создания, подтверждение читает момент
-- последнего наблюдения, а полный проход, не наблюдавший признака, его
-- гасит.
--
-- Пусто — серии нет: строку не наблюдал детектор с гистерезисом либо серию
-- прервал полный проход без признака.
--
-- Проект до прод-рубежа: таблица пуста, бэкфилла не требуется
-- (.claude/rules/pre-launch-schema-changes.md).

alter table anomaly_reports add column last_observed_at timestamptz;

comment on column anomaly_reports.last_observed_at is
    'Момент последнего наблюдения признака детектором; пусто — серии нет';

-- Конец полного прохода гасит серии счёта, которых проход не наблюдал.
-- Непустых значений у счёта единицы, а строк журнала — сколько накопилось:
-- без частичного индекса гашение сканировало бы журнал счёта каждым тиком.
create index ix_anomaly_report_series
    on anomaly_reports (exchange_account_id, last_observed_at)
    where last_observed_at is not null;
