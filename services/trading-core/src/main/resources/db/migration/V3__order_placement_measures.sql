-- Два измерителя ноги на момент постановки (шаг 7 фазы 2, компонент
-- «исполнители площадки: постановка и снятие»).
--
-- docs/models/domain/core/Order.md называет их полями модели —
-- liquidationDistanceRatio и bookDepthAtPlacement, — а базовая миграция
-- ядра пришла из донора, где их нет вовсе. Расхождение поймано при
-- кодировании писателя: исполнитель создания ноги обязан их проставить, а
-- колонок под них не было.
--
-- Правится НОВОЙ миграцией, а не редакцией V1: базовая уже накатана на
-- живую базу стенда, и её контрольная сумма неизменяема
-- (.claude/rules/codestyle.md §«Применённая миграция неизменяема»).
--
-- Колонки NULLABLE, и это не послабление: пустота у измерителя —
-- САМОСТОЯТЕЛЬНОЕ значение «не измеряли». В инвариант «шесть или ни
-- одного» они не входят именно потому, что их операнды наблюдаются не
-- всегда: цены ликвидации у открывающего входа ещё нет, свежих рыночных
-- данных в контексте могло не быть.

alter table orders add column liquidation_distance_ratio numeric(36, 18);
alter table orders add column book_depth_at_placement numeric(36, 18);

comment on column orders.liquidation_distance_ratio is
    'Наблюдаемый запас до ликвидации на момент постановки; пусто — цена ликвидации не наблюдалась';
comment on column orders.book_depth_at_placement is
    'Наблюдаемая ёмкость стакана на момент постановки; пусто — свежих рыночных данных не было';
