package com.example.tradingcore.api.model;

import io.swagger.v3.oas.annotations.media.Schema;
import jakarta.validation.constraints.DecimalMin;
import jakarta.validation.constraints.Positive;
import java.math.BigDecimal;
import lombok.Getter;
import lombok.Setter;

/**
 * Назначение чисел риск-аппетита тенанта
 * (docs/rules/risk-policy.md §«Числа назначает держатель»).
 *
 * <p><b>Ни одно поле не обязательно, и это не послабление.</b> Пустое
 * значение здесь означает «число не назначено» — то есть ОТКАЗ
 * risk-creating действия, а не ноль и не умолчание: машина эти числа из
 * концепции не выводит. Валидация «назначь всё» сделала бы недостижимым
 * законное состояние «часть чисел уже назначена, часть ещё нет».
 *
 * <p><b>Назначение — снимок целиком:</b> непереданное поле стирает
 * прежнее число. Частичная правка сделала бы «не прислал» неотличимым от
 * «снял».
 *
 * <p><b>Область определения проверяется, ВЕЛИЧИНА — нет.</b> Сколько
 * именно рисковать, назначает держатель, и потолка сверху здесь не стои́т
 * (docs/rules/risk-policy.md §«Числа назначает держатель»). Но процент
 * базы, множитель растяжения и счётчик сделок неположительными не бывают
 * по смыслу самих величин: неположительное число — не «жёсткий
 * риск-аппетит», а значение вне области определения, и через
 * поверхность оно доходило бы прямо в риск-гейт. Проверка — на границе,
 * где негодный вход и отвергают.
 */
@Getter
@Setter
public class RiskAppetiteApiRequest {

    @DecimalMin(value = "0", inclusive = false,
            message = "Процент базы риска положителен: ноль и меньше области определения не принадлежат")
    @Schema(description = "Потолок одновременного риска на сделку, процент базы риска."
            + " Пусто — число не назначено, и risk-creating действие отвергается")
    private BigDecimal globalSimultaneousRiskPerDealPercent;

    @DecimalMin(value = "0", inclusive = false,
            message = "Множитель растяжения положителен: ноль и меньше области определения не принадлежат")
    @Schema(description = "Множитель катастрофического потолка над потолком одновременного риска."
            + " Пусто — число не назначено")
    private BigDecimal globalCatastrophicRiskPerDealMultiplier;

    @Positive(message = "Предел серии убытков положителен: непозитивный предел не читается ничем")
    @Schema(description = "Предел подряд идущих убыточных сделок, после которого поднимается"
            + " мягкая ступень счёта. Пусто — число не назначено")
    private Integer globalConsecutiveLossLimit;
}
