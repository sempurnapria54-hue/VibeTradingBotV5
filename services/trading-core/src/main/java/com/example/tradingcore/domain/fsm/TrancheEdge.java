package com.example.tradingcore.domain.fsm;

import com.example.tradingbot.domain.model.aggregate.deal.DealTranche;
import lombok.Value;

/**
 * Одобренное статусное ребро транша, ждущее применения: сам транш, его
 * целевой статус и — на терминале — его причина закрытия.
 *
 * <p><b>Рёбра траншей едут ВМЕСТЕ с переходом сделки, а не пишутся
 * каскадом на месте.</b> Порядок прохода — «диспетчеризация команд, затем
 * применение перехода» (docs/components/DealOrchestratorJob.md §«Цикл
 * прохода»): записанный до дисптачера, статус транша пережил бы отказ
 * собственной команды и разошёлся бы с фактами площадки.
 *
 * <p><b>Причина едет вместе со статусом</b>, потому что писатель у них
 * один и транзакция одна (docs/lifecycles/DealTranche.md §«Писатель
 * причины закрытия транша — обработчик терминального ребра»).
 *
 * <p>Живёт только в памяти прохода — читателя за сериализацией нет.
 */
@Value
public class TrancheEdge {

    /** Транш, чьё ребро одобрено. */
    DealTranche tranche;

    /** Целевой статус транша. */
    DealTranche.Status status;

    /** Причина закрытия; непуста только вместе с терминалом. */
    DealTranche.CloseReason closeReason;
}
