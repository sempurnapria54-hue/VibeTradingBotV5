package com.example.tradingcore.domain.safety;

import com.example.tradingbot.domain.model.Auditable;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

/**
 * Журналируемый объект расследования и обработки происшествия: фиксирует
 * расхождение локального и биржевого состояния либо нарушение
 * риск-политики, его обработку реактивной ступенью и снимки состояния до и
 * после снятия риска.
 *
 * <p><b>Не валидатор и не команда — аудит-журнал</b>
 * (docs/models/domain/other/AnomalyReport.md,
 * docs/lifecycles/AnomalyReport.md).
 *
 * <p><b>Радиус отчёта — биржевой СЧЁТ, а не площадка:</b> происшествие
 * одного тенанта не описывает состояние другого
 * (docs/architecture/tenant-and-exchange.md §«Торговая строка называет
 * счёт, и радиусы читаются от него»).
 */
@Getter
@Setter
@NoArgsConstructor
public class AnomalyReport extends Auditable {

    /** Внутренний идентификатор отчёта. */
    private Long id;

    /** Межсервисный идентификатор отчёта. */
    private String internalId;

    /** Биржевой счёт, на котором наблюдено происшествие. */
    private Long exchangeAccountId;

    /** Инструмент происшествия; пусто, если однозначно не определён. */
    private Long instrumentId;

    /**
     * Сущность-предмет — четвёртая величина ключа дедупа у отчёта БЕЗ
     * блокировки: его состояние держится на сущности, а не на объекте
     * радиуса. Пусто у отчёта с блокировкой: у того состояние и есть
     * стоящая ступень объекта радиуса
     * (docs/models/domain/other/AnomalyReport.md §«У отчёта без блокировки
     * в ключ входит ещё одна величина — сущность, о которой он»).
     */
    private String subjectExternalId;

    /** Радиус происшествия: инструмент либо счёт. Снимает неоднозначность пустого инструмента. */
    private HoldScope scope;

    /** Статус обработки. */
    private Status status;

    /** Критичность: критична аномалия или нет. Силу реакции ступени не выражает. */
    private Severity severity;

    /**
     * Машинно-читаемый код происшествия. Значение приходит от
     * тропы-производителя; закрытого реестра кодов нет, дом каждого
     * значения — дом его тропы.
     */
    private String code;

    /** Текст непредвиденной ошибки обработки; заполняется при {@code ERROR}. */
    private String message;

    /** Снимок локального состояния до обработки. */
    private String internalBefore;

    /** Снимок внешнего состояния до обработки. */
    private String externalBefore;

    /** Снимок локального состояния после обработки. */
    private String internalAfter;

    /** Снимок внешнего состояния после обработки. */
    private String externalAfter;

    /** Статус обработки происшествия реактивным контуром. */
    public enum Status {

        /** Происшествие зафиксировано, снимки состояния собраны. */
        CREATED,

        /** Обработка идёт. */
        IN_PROGRESS,

        /** Снятие риска выполнено и подтверждено. */
        KILL_SWITCH_EXECUTED,

        /** Обработка завершена; терминален. */
        COMPLETED,

        /** Непредвиденная ошибка обработки; текст записан в отчёт. */
        ERROR
    }

    /**
     * Критичность происшествия. Отвечает ровно на один вопрос — критична
     * аномалия или нет; состав реакции задаёт ступень.
     */
    public enum Severity {

        /** Критичная: торговля по радиусу остаётся запрещённой до ручного разбора. */
        CRITICAL,

        /** Некритичная: после снятия риска торговля может быть снова разрешена. */
        NON_CRITICAL
    }
}
