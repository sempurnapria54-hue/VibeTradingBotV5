package com.example.tradingcore.domain.command.strategy;

/**
 * Исход гейта предусловия действия. Спрашивается <b>прежде</b>, чем
 * заведена строка исполнения: действие, чьё предусловие не выполнено,
 * исполнения не начинает — строка не заводится, бюджет попыток не
 * расходуется (docs/components/StrategyActionExecutor.md §«Готовность
 * отвечается ДО строки исполнения»).
 *
 * <p><b>Умолчание — {@code READY}.</b> У действия, которое ничего не
 * снимает и ничьего покрытия не забирает, предусловия сверх условия шага
 * нет, а условие шага проверил обработчик.
 */
public enum ActionReadiness {

    /** Предусловий сверх условия шага нет либо они выполнены. */
    READY,

    /**
     * Предусловие не выполнено, надобность жива. Пакет шага
     * <b>останавливается</b>: обгонять отложенное действие значило бы
     * менять объявленный порядок пакета.
     */
    DEFERRED,

    /**
     * Предмета у действия больше нет. Пакет берёт следующее — ждать
     * нечего.
     */
    IRRELEVANT
}
