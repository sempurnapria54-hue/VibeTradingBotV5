package com.example.tradingcore.domain.safety;

/**
 * Ступень реакции. Ось разведения одна — <b>судьба принятого риска</b>, и
 * она общая у обеих лестниц (docs/rules/instrument-hold.md,
 * docs/rules/exchange-hold.md). Второй оси в модели нет: тип исключения
 * резолвит РАДИУС реакции, ступень — только эту ось.
 */
public enum HoldRung {

    /**
     * Мягкая: принятый риск ОСТАЁТСЯ жить под своей защитой, запрещается
     * только новый и ослабление стоящей защиты.
     */
    SOFT,

    /**
     * Жёсткая: принятый риск СНИМАЕТСЯ, активные сделки радиуса уходят в
     * ошибочное состояние.
     */
    HARD
}
