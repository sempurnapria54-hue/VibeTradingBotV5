package com.example.tradingcore.domain.command.resolve;

import com.example.tradingbot.domain.model.core.order.AttachedAlgoOrder;
import com.example.tradingbot.domain.model.core.order.Order;
import com.example.tradingbot.domain.resolve.ProtectionHistoryLeg;
import java.math.BigDecimal;
import lombok.Builder;
import lombok.Value;

/**
 * Набор фактов, по которому выводится состояние встроенной защиты:
 * полноценного статуса источник ей не отдаёт, и статус приходится
 * ВЫВОДИТЬ. Runtime-объект прохода, не хранимая сущность и провода не
 * пересекает; дом матрицы — docs/lifecycles/Order.md, форма и примеры —
 * docs/spec/order-lifecycle.json.
 */
@Value
@Builder
public class AttachedProtectionFacts {

    /**
     * ПРЕДЪЯВЛЕННАЯ защита — либо элементом в теле добытого родителя, либо
     * самостоятельной условной заявкой цикла добычи. Пусто — не
     * предъявлена. Место, откуда она пришла, живости не решает: решает
     * факт предъявления.
     */
    AttachedAlgoOrder observed;

    /** Локальный статус РОДИТЕЛЬСКОЙ заявки — операнд класса состояния родителя. */
    Order.Status parentStatus;

    /**
     * Статус, который площадка показала у родителя ЭТОЙ добычей, — доменный
     * статус его снапшота. Пусто — снапшот родителя этой добычей не получен
     * (запись за горизонтом выдачи). Читается только у родителя в
     * {@code ERROR}: пометка ошибки — наше safety-состояние, и судьбу защиты
     * несёт наблюдённый терминал площадки, а не она
     * (docs/spec/order-lifecycle.json, {@code attachedParentStatus}).
     */
    Order.Status parentObservedStatus;

    /**
     * Наблюдённая живость РОДИТЕЛЯ на площадке — та же величина, что у
     * самой ноги ({@code Order.externalLive}). Читается классом родителя
     * только у родителя в {@code ERROR} без наблюдённого статуса: ложь там
     * значит, что полный цикл добычи родителя не нашёл, и класс читается
     * терминальным по наливу; пусто — площадка о родителе не показала
     * ничего, и класс проблемный (docs/spec/order-lifecycle.json, операнд
     * {@code parentExternalLive}, величина {@code attachedParentClass}).
     */
    Boolean parentExternalLive;

    /**
     * Накопленный налив РОДИТЕЛЯ. Дискриминатор терминального класса: на
     * терминале с наливом источник разворачивает защиту в самостоятельную
     * живую заявку ровно на налитый объём, при нулевом — снимает вместе с
     * родителем. Активации налив не доказывает — её доказывает только
     * найденная запись ({@link #standaloneRecordFound}). ПУСТО достижимо и
     * нулём НЕ ПОДМЕНЯЕТСЯ — подмена увела бы недобытый факт в «снята
     * вместе с родителем», то есть пометила бы снятой возможно живую
     * защиту.
     */
    BigDecimal parentAccumulatedFillSize;

    /**
     * Защита предъявлена САМОСТОЯТЕЛЬНОЙ записью цикла добычи. Такая
     * запись — единственное доказательство материализации
     * (docs/spec/order-lifecycle.json, {@code attachedBecomesActive}), и
     * недобытость налива родителя её не гасит.
     */
    Boolean standaloneRecordFound;

    /**
     * Терминал родителя наблюдён ДО этой добычи: его локальный статус до неё
     * уже был терминальным, а у родителя в {@code ERROR} прежняя добыча уже
     * показала его нежилым (docs/spec/order-lifecycle.json, операнд
     * {@code parentTerminalObservedBefore}). Ложь — терминал впервые показала
     * ЭТА добыча, и пустой разбор цикла на ней мерит задержку постановки
     * защиты площадкой, а не её судьбу. Читается до записи добычи, поэтому
     * ложь гаснет сама: добыча, впервые увидевшая терминал, его и записывает.
     */
    Boolean parentTerminalObservedBefore;

    /**
     * Экспозиция ТРАНША, чью защиту ищет цикл. Обе стороны предиката
     * второй ступени траншевые: инвариант покрытия потраншевый целиком, а
     * «живая позиция» — факт уровня сделки, и на транше без собственной
     * экспозиции её держит СОСЕДНИЙ транш.
     */
    BigDecimal trancheExposure;

    /** Отдельная основная защита ТОГО ЖЕ транша существует. */
    Boolean standaloneProtectionExists;

    /**
     * Нога разбора истории, нашедшая запись; пусто — ни одна не дала.
     * Читается ТОЛЬКО на ветви разбора: на ветви потерянного покрытия
     * история не опрашивается вовсе.
     */
    ProtectionHistoryLeg historyLegFound;

    /**
     * Стоящее НАШЕ намерение снятия — непустая причина закрытия,
     * записанная командой снятия до наблюдения факта. Причина write-once,
     * поэтому намерение наблюдением не перезаписывается. Закрывает ветвь
     * потерянного покрытия: защиту, которую сняли мы, пропавшей не читают.
     */
    Boolean cancelIntentStanding;
}
