package com.example.tradingcore.domain.command;

/**
 * Классификация неожиданных runtime-ошибок исполнения: они не
 * превращаются ни в ошибку расчёта, ни в результат риск-проверки.
 * Задаёт повторяемость. Дом правила —
 * docs/rules/runtime-error-classification.md.
 *
 * <p><b>Отказ соседа по ярусу значением здесь не представлен, и это не
 * пропуск:</b> его реакция — пропуск прохода целиком, то есть строка
 * исполнения не заводится и учитывать нечего. Значение под него завело бы
 * код, которого не бывает ни на одной строке.
 */
public enum RuntimeErrorCode {

    /** Баг приложения: неожиданное состояние, отказ маппинга. Неповторяем. */
    INTERNAL_ERROR,

    /** Сбой взаимодействия с площадкой: таймаут, обрыв, отказ API. Повторяем. */
    EXCHANGE_ERROR,

    /** Нарушение инварианта, не должное дойти до runtime. Неповторяем. */
    VALIDATION_ERROR
}
