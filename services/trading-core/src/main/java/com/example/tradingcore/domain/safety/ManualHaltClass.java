package com.example.tradingcore.domain.safety;

/**
 * Класс ручного вмешательства — <b>имя поверхности</b>, а не ступень
 * системы (docs/rules/manual-halt.md §«Параметры вызова — существующие
 * поля сигнала»).
 *
 * <p><b>Собственного перечня ступеней ручное управление не заводит.</b>
 * Ступень выражена {@link HoldRung} с двумя значениями — ось одна, судьба
 * принятого риска; этот перечень существует потому, что <b>мягкая
 * ступень называется по-разному на двух радиусах</b>, и держателю разница
 * видна. Отображение однозначно: мягкая инструмента и мягкая счёта дают
 * {@code HoldRung.SOFT}, полный класс на обоих радиусах —
 * {@code HoldRung.HARD}.
 *
 * <p><b>Цена решения названа:</b> держатель обязан знать, что мягкая
 * ступень на счёте называется {@code FREEZE}, а на инструменте —
 * {@code SOFT}. Собственный двузначный перечень эту разницу спрятал бы,
 * но не изменил бы ни одного исхода — те же четыре пары, те же ступени.
 */
public enum ManualHaltClass {

    /** Мягкий запрет входов по паре «счёт, инструмент». Только радиус пары. */
    SOFT,

    /** Мягкая ступень биржевого счёта: счёт выпадает из выборки входа. Только радиус счёта. */
    FREEZE,

    /** Полный класс: жёсткая ступень со снятием живого риска. Оба радиуса. */
    FULL
}
