package com.example.tradingcore.domain.deal;

/**
 * Ребро, присваивавшее причину выхода из штатного ведения, не применилось:
 * транзакция «ребро + факт» откатилась целиком.
 *
 * <p><b>Отдельный тип нужен ради ОДНОГО решения вызывающего — не
 * перехватывать такую сделку в ошибку.</b> Общий перехватчик прохода
 * уводит сделку в {@code ERROR} <b>без</b> причины
 * ({@code DealOrchestratorJob}), а рёбра присвоения причины применяются
 * только из {@code ACTIVE} и {@code EXIT_PENDING}: перехваченная сделка
 * причины уже не получит НИКОГДА, хотя причина была вычислена и ход был
 * начат. Клейма таймлайна «почему сделка перестала вестись штатно» другого
 * носителя не имеет (docs/lifecycles/Deal.md §«Причина выхода из штатного
 * ведения»).
 *
 * <p><b>Откат при этом ничего не теряет — он возвращает сделку в
 * состояние, из которого ребро применимо.</b> Поэтому исход здесь —
 * пропустить сделку в этом проходе, а не пометить её ошибкой.
 *
 * <p><b>Довод повторимости у двух локусов РАЗНЫЙ, и безусловным он не
 * бывает.</b> На ребре энфорсмента ступени ({@code enforceHardRung}) шаг
 * стои́т <b>первым</b> в проходе: его операнды прочитаны в начале тика, до
 * него проход ничего не коммитил, и откат возвращает состояние целиком. На
 * статусном ребре прохода ({@code applyPassEdge}) до отказа успели
 * закоммититься чужие ходы — рёбра траншей своей транзакцией и уже
 * исполненные команды перехода, — и откат возвращает <b>строку сделки</b>,
 * но не вход FSM. Повторимость там держится не на нетронутом состоянии, а
 * на природе причин, которые до этого локуса доезжают: устаревание рыночных
 * данных и удалённое определение стратегии суть условия <b>среды</b>, и
 * пока условие стои́т, следующий проход выводит ту же причину заново. Цена
 * частичного применения названа у дома порядка прохода
 * (docs/components/DealOrchestratorJob.md §«Цикл прохода», шаг «применение
 * перехода»).
 *
 * <p><b>Названная цена.</b> Отказ, воспроизводящийся каждым проходом
 * (неразрешимая идентичность радиуса), даёт сделку, стоящую в прежнем
 * статусе с записью в лог на каждом тике: durable-пометки у такого
 * состояния нет. Это дешевле обратного — молчаливой потери причины, — и
 * наблюдаемо: ход не производится, а лог бьётся каждым тиком.
 */
public class DealShutdownEdgeException extends RuntimeException {

    public DealShutdownEdgeException(Long dealId, RuntimeException cause) {
        super("Deal shutdown edge failed dealId=" + dealId, cause);
    }
}
