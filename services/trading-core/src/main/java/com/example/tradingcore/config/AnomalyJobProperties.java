package com.example.tradingcore.config;

import java.time.Duration;
import lombok.Getter;
import lombok.Setter;
import org.springframework.boot.context.properties.ConfigurationProperties;
import org.springframework.stereotype.Component;

/**
 * Настройки прохода проактивной детекции
 * (docs/components/AnomalyJob.md).
 *
 * <p><b>Числа здесь — калибровка НАБЛЮДЕНИЯ, а не риск-аппетит:</b> их
 * ошибка меряется парой «ложное срабатывание против пропуска», а не
 * размером потери (.claude/processes/question-delegation.md §«Число:
 * риск-аппетит против калибровки наблюдения»). Отгружаются провизорными;
 * якорь калибровки — первый период прогонов контура.
 */
@Getter
@Setter
@Component
@ConfigurationProperties(prefix = "anomaly-job")
public class AnomalyJobProperties {

    /** Проход проактивной детекции включён. */
    private Boolean enabled = Boolean.TRUE;

    /**
     * Сколько подряд идущих <b>ненаблюдённых</b> проходов поднимают мягкую
     * счётную ступень.
     *
     * <p>Направление названо: единица сделала бы одиночный упор в лимит
     * частоты основанием остановки набора со <b>снятием вручную</b>, а
     * пропуск при трёх стоит трёх минут ненаблюдаемости при работающей
     * биржевой защите.
     */
    private Integer blindPassLimit = 3;

    /**
     * Минимальный возраст последнего наблюдения серии, при котором она
     * читается ПОДТВЕРЖДЕНИЕМ признака.
     *
     * <p><b>Верхняя граница окна подтверждения обязательна.</b> Без неё
     * подтверждением служит наблюдение того же или смежного прохода
     * секундами раньше: ручной триггер поверх планового тика,
     * рестарт с немедленным тиком и дрейф расписания дают пару проходов в
     * секундах друг от друга, а гонка чтения, против которой гистерезис
     * заведён, живёт ТАКТ. Такая пара её не переживает и «подтвердит»
     * транзиторное расхождение жёсткой ступенью.
     */
    private Duration confirmationMinAge = Duration.ofSeconds(30);

    /**
     * Размер страницы обхода контура — инструментов площадки за одно
     * чтение проекции.
     *
     * <p><b>Предела выборки он не задаёт:</b> проход читает страницы до
     * последней, и контур остаётся всем каталогом площадки при любом его
     * размере. Неполноту прохода даёт только отказ чтения, а не размер
     * каталога. Величина — плата памятью и числом запросов за проход, а не
     * калибровка наблюдения: её ошибка исход прохода не меняет.
     */
    private Integer contourPageSize = 500;
}
