package com.example.tradingcore.domain.command;

/**
 * Статус исполнения действия. Значения и переходы —
 * docs/lifecycles/DealActionState.md.
 */
public enum DealActionStateStatus {

    /** Исполнение выбрано, команды ещё не было: цель пуста. */
    PLANNED,

    /** Локальная сущность создана, цель заполнена. */
    CREATED,

    /** Отправлено на биржу, факт не подтверждён: подтверждение приёма истиной не является. */
    SUBMITTED,

    /** Доведено, факты подтверждены. Жёстко терминален. */
    COMPLETED,

    /** Звено упало на повторяемой ошибке, ждёт следующей попытки. */
    RETRY_PENDING,

    /** Бюджет исчерпан либо ошибка неповторяема. */
    FAILED,

    /** Исполнение стало неактуальным. */
    SKIPPED
}
