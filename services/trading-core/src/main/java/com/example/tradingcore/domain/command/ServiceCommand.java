package com.example.tradingcore.domain.command;

import lombok.Builder;
import lombok.Value;

/**
 * Атомарная команда над runtime-сущностью.
 *
 * <p><b>Не хранимая сущность и не durable-очередь:</b> ожидающие команды
 * в базе не лежат, после рестарта нужная выводится из фактов заново
 * (docs/rules/command-lifecycle.md). Отвечает «какую простую операцию
 * выполнить»; исполнитель — «как технически»; машина состояний — «зачем
 * сейчас».
 *
 * <p><b>Анкер учёта один</b> — строка исполнения, и она же анкер повторов
 * и цели. У команд ног действий стратегии это стратегийное исполнение, у
 * звеньев системных действий — системное. Пусто ровно у дочисток:
 * отмены и закрытие позиции эмитируются напрямую, без анкера, — и бюджета
 * отказов у них поэтому нет
 * (docs/components/models/ServiceCommand.md).
 */
@Value
@Builder
public class ServiceCommand {

    /** Тип атомарной операции. */
    ServiceCommandType type;

    /** Сделка, в рамках которой команда исполняется. */
    Long dealId;

    /** Строка исполнения — анкер идемпотентности, повторов и цели; пусто у дочистки. */
    Long dealActionStateId;

    /** Параметры выполнения. */
    ServiceCommandPayload payload;
}
