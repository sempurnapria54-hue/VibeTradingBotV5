package com.example.tradingcore.domain.command;

/**
 * Последняя ошибка повторяемой операции: исходный код, сообщение и
 * классификация.
 *
 * <p>Хранится ОБЪЕКТОМ в навесе строки исполнения, а не тремя скалярными
 * колонками: тройка описывает один факт, и разнести её значило бы завести
 * три носителя одной истины (docs/components/RetryPolicyService.md).
 *
 * <p><b>Запись, а не {@code @Value}, и это следствие навеса.</b> Значение
 * пересекает границу сериализации, то есть у него есть ЧИТАТЕЛЬ; запись
 * сериализатор собирает по канонической форме, ничего сверх неё не
 * требуя, тогда как неизменяемый класс без пустого конструктора
 * собирается лишь при удачном стечении обстоятельств — зарегистрированном
 * модуле имён параметров и флаге компиляции. Отказ пришёл бы на тропе
 * ПОВТОРА, то есть ровно тогда, когда что-то уже пошло не так
 * (.claude/rules/codestyle.md §«Неизменяемое значение, пересекающее
 * сериализацию»).
 *
 * @param code    исходный код ошибки — например, код ответа площадки
 * @param message сообщение для человека
 * @param type    классификация ошибки, задающая повторяемость
 */
public record RetryError(String code, String message, RuntimeErrorCode type) {
}
