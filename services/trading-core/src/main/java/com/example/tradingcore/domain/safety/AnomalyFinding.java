package com.example.tradingcore.domain.safety;

import com.example.tradingbot.domain.model.core.instrument.Instrument;
import java.util.Map;
import java.util.Objects;
import lombok.Builder;
import lombok.Value;

/**
 * Наблюдение одного детектора: что найдено, на каком объекте и какой
 * ступенью на это отвечает лестница.
 *
 * <p><b>Ступень и радиус приходят СЮДА уже выведенными.</b> Детектор их
 * не назначает: они выводятся тремя ратифицированными осями, и дом
 * реакции у каждого кода уже существует (docs/components/AnomalyJob.md
 * §«Что ищет»). Находка — параметр вызова реакции, а не решение о ней.
 *
 * <p>Живёт только в памяти прохода — читателя за сериализацией нет.
 */
@Value
@Builder
public class AnomalyFinding {

    /** Радиус — выбирает исполнителя статуса. */
    HoldScope scope;

    /** Ступень — судьба принятого риска. */
    HoldRung rung;

    /** Машинный код причины; попадает в отчёт и в ключ его дедупа. */
    String code;

    /**
     * Инструмент радиуса; пуст у счётных детекторов. У счётного детектора,
     * нашедшего признак ПО инструменту (чужая заявка), он тоже пуст:
     * радиус реакции счётный, а биржевое имя инструмента едет в
     * наблюдённых строках ({@link #externalObservation}).
     */
    Instrument instrument;

    /**
     * Сущность-предмет — четвёртая величина ключа дедупа у отчёта без
     * блокировки. Пуст у отчёта с блокировкой.
     */
    String subjectExternalId;

    /**
     * Сколько подряд идущих тиков признак обязан держаться, прежде чем
     * поднимается ступень. Единица — реакция с первого наблюдения.
     */
    Integer hysteresisTicks;

    /**
     * Блокировки в составе реакции нет — находка заводит только строку
     * журнала.
     *
     * <p><b>Признак объявляется детектором явно, а не выводится из наличия
     * предмета:</b> кортеж «радиус × ступень» у журнальной находки и у
     * мягкой ступени один и тот же, и различает их только назначение
     * (docs/components/models/HoldSignal.md §Фабрики).
     */
    Boolean journalOnly;

    /**
     * Строки среза прохода по адресу находки — биржевое имя инструмента
     * плюс его позиции, заявки и условные заявки, какими их увидел проход
     * (docs/models/domain/other/AnomalyReport.md §Структура).
     *
     * <p><b>Срез уже добыт, и второй раз площадку не читают.</b> Внешний
     * снимок отчёта берёт эти строки, а не собственное чтение: оно стоило
     * бы двух вызовов на находку и показывало бы другой момент, чем тот,
     * на котором признак найден.
     *
     * <p><b>У отчёта с блокировкой это единственное место, где в данных
     * видно, ЧТО его вызвало:</b> предмета в ключе у него нет, а у счётного
     * детектора пуст и инструмент — биржевое имя едет здесь.
     */
    Map<String, Object> externalObservation;

    /** Реакция снимает принятый риск. */
    public Boolean tearsDownRisk() {
        return Objects.equals(HoldRung.HARD, rung);
    }
}
