package com.example.tradingcore.exception;

/**
 * Факт владельца определений, который не применится <b>никаким повтором</b>:
 * дефект лежит в самой записи, а не в состоянии читателя.
 *
 * <p><b>Признак механический — повторяемость отказа на той же записи при
 * любом состоянии базы ядра.</b> Сюда попадают содержимое, не разбираемое в
 * объявленную форму, пустое содержимое, активация без идентичности
 * определения и конверт без идентичности события либо без класса.
 * Нерезолвимая проекция счёта либо инструмента, недоступная
 * база и всякий неназванный отказ сюда НЕ попадают: их лечит время, и
 * применение такой записи откладывается, а не пропускается
 * (docs/architecture/data-ownership.md §«Копии чужих данных»).
 *
 * <p><b>Класс существует ради обработчика отказа приёма</b>
 * ({@code StrategyFactErrorHandler}): им одним отказ отличим от
 * отложенного применения, и другого признака у обработчика нет.
 */
public class PoisonStrategyFactException extends RuntimeException {

    public PoisonStrategyFactException(String message, Throwable cause) {
        super(message, cause);
    }

    public PoisonStrategyFactException(String message) {
        super(message);
    }
}
