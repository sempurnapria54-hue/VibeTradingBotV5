package com.example.tradingcore.domain.command.calc;

import java.math.BigDecimal;
import lombok.Value;

/**
 * Итог расчёта результата сделки: доступность числа и само число с его
 * валютой (docs/spec/deal-result.json).
 *
 * <p><b>Доступность отделена от числа намеренно:</b> пустое число при
 * доступном итоге означает совсем другое, чем пустое при недоступном.
 * Ноль здесь допустим только как результат расчёта — на тропе закрытия без
 * входа он и есть расчёт, во всех прочих случаях подстановка нуля была бы
 * благоприятным умолчанием.
 *
 * <p>Живёт только в памяти прохода — читателя за сериализацией у неё нет
 * (.claude/rules/codestyle.md §«Неизменяемое значение, пересекающее
 * сериализацию»).
 */
@Value
public class DealResult {

    /**
     * Итог доступен: граф предъявлен целиком, добыты все записи закрытия,
     * разбивка добыта и предъявлена целиком, ни одна строка чужой валюты
     * не ждёт курса.
     */
    Boolean available;

    /** Число; пусто ровно при недоступном итоге. */
    BigDecimal resultProfit;

    /** Валюта результата — расчётная валюта инструмента, один авторитет на все тропы. */
    String resultProfitCurrency;
}
