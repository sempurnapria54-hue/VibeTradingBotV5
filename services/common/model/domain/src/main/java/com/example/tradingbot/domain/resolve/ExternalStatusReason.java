package com.example.tradingbot.domain.resolve;

/**
 * Код проблемного внешнего статуса.
 *
 * <p><b>Общий перечень, а не внутренний для коннектора.</b> Причину
 * ПРОИЗВОДИТ коннектор (он единственный видит ответ площадки), а
 * ПОТРЕБЛЯЕТ ядро: она становится причиной закрытия сущности
 * ({@code docs/rules/controlled-exchange-exceptions.md}). Значит перечень
 * читают обе стороны, и жить он обязан там, где его видят обе.
 *
 * <p><b>Формой источник его не задаёт</b> — критерий границы Д633: это
 * не словарь статусов площадки, а наш разбор того, что этот статус для
 * нас значит; второй площадке он подойдёт без правки.
 */
public enum ExternalStatusReason {

    /** Внешний статус неизвестен — не маппится молча в UNKNOWN. */
    UNKNOWN_EXTERNAL_STATUS,

    /** Постановка algo-order на бирже не удалась. */
    ORDER_FAILED,

    /** Частичный отказ algo-order. */
    PARTIALLY_FAILED
}
