package com.example.tradingbot.domain.event;

/**
 * Классы событий, производимые торговым ядром
 * (docs/architecture/contracts.md §«У каждого класса события назван
 * писатель, и он же писатель решения»).
 *
 * <p><b>Все они — события-ПРОИСШЕСТВИЯ</b>, поэтому род темы у ядра один:
 * {@code facts}. Событий-состояний, чья истина есть последнее значение по
 * ключу, ядро не производит, и смешивать роды в одной теме нельзя —
 * компакция темы фактов теряет факты.
 *
 * <p><b>Перечень закрыт домом, а не этим классом:</b> он повторяет таблицу
 * привязки «класс события → писатель → момент» и новых классов не вводит.
 */
public enum CoreEventType {

    /** Решение о заявке — транзакция заведения её строки. */
    ORDER_DECIDED,

    /** Сделка создана — обе тропы создателя сделки. */
    DEAL_OPENED,

    /**
     * Сделка перестала вестись штатно — транзакция ребра, на котором
     * присвоена причина остановки.
     *
     * <p><b>У одной сделки таких событий бывает больше одного</b>, и это
     * свойство класса: причина, записанная на ребре в отложенный выход,
     * заменяется холдовой на ребре в ошибочное состояние
     * (docs/lifecycles/Deal.md §«Причина выхода из штатного ведения»).
     * Счётчик над классом обязан считать СДЕЛКИ, а не строки журнала
     * (docs/rules/statistics-aggregates.md).
     */
    DEAL_SHUTDOWN_INITIATED,

    /** Сделка закрыта — транзакция терминального ребра, обоих терминалов. */
    DEAL_CLOSED,

    /** Ступень радиуса поднята — транзакция подъёма. */
    HOLD_RAISED,

    /** Отчёт о происшествии заведён; при поглощении дедупом строки нет — и события тоже. */
    ANOMALY_REPORTED
}
