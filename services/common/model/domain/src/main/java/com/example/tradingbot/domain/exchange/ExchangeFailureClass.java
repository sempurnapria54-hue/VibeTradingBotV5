package com.example.tradingbot.domain.exchange;

/**
 * Класс отказа на границе с площадкой.
 *
 * <p><b>Общий перечень, а не внутренний для коннектора</b> — по тому же
 * доводу, по которому общим объявлен
 * {@code domain.resolve.ExternalStatusReason}: класс ПРОИЗВОДИТ коннектор
 * (он единственный видит ответ площадки), а ПОТРЕБЛЯЕТ ядро — по классу
 * оно выбирает реакцию ({@code docs/rules/controlled-exchange-exceptions.md},
 * {@code docs/rules/runtime-error-classification.md}). Значит значения
 * читают обе стороны, и жить они обязаны там, где их видят обе.
 *
 * <p><b>Форму ответа перечень не задаёт, и это разные вещи.</b> Форма
 * (тело отказа) принадлежит тому, кто её отдаёт, и каждая сторона держит
 * свою — зависимость на чужую api-модель сделала бы выкатку соседа
 * пересборкой ядра. Разойдись же ЗНАЧЕНИЯ — ядро молча не узнало бы класс
 * и выбрало бы реакцию по умолчанию, то есть не ту.
 *
 * <p><b>Дом перечня как ЗНАНИЯ — не здесь</b>, а в
 * {@code docs/components/IntegrationService.md} §«Классы отказа на границе
 * — дом здесь»: там сказано, что каждый класс означает и помогает ли
 * повтор. Этот enum — его исполнимая форма, и состав обязан совпадать.
 *
 * <p><b>Негодного входа тут нет намеренно.</b> Отказ вида «запрос не
 * разобран» — дефект вызывающего, а не отказ ПЛОЩАДКИ; перечень выше
 * его не называет, и значения ему здесь нет. Нераспознанный класс ядро
 * трактует как собственный дефект — тот же исход, ещё одного значения для
 * этого не нужно.
 */
public enum ExchangeFailureClass {

    /** Ключей счёта в хранилище нет: подписать нечем, повтор не поможет. */
    CREDENTIALS_UNAVAILABLE,

    /** Хранилище секретов не ответило: повтор осмыслен, как только оно вернётся. */
    SECRET_STORE_UNAVAILABLE,

    /** Площадка отвергла наши ключи: повтором не лечится, поднимает биржевую ступень. */
    EXCHANGE_CREDENTIALS_REJECTED,

    /** Площадка не ответила либо ответ не разобран: причина преходящая. */
    EXCHANGE_UNREACHABLE,

    /** Площадка ответила и объяснила отказ: повтор — по коду площадки. */
    EXCHANGE_ERROR,

    /** Статус получен, но неизвестен либо проблемный; причина едет отдельным полем. */
    EXTERNAL_STATUS,

    /** Ответ нарушает инвариант, на котором стои́т наша торговля. */
    EXTERNAL_INVARIANT_VIOLATION
}
