package com.example.tradingbot.domain.model.aggregate.strategy.action;

/**
 * Чем задан уровень действия. Признак ПОЛОЖИТЕЛЬНЫЙ и читается с
 * объявления действия, а не выводится из пустоты соседнего операнда:
 * пустота не отличала бы «уровень наблюдаемый» от «настройки забыли».
 *
 * <p>Резолв — по ОБЪЯВЛЕННОМУ БЛОКУ настроек
 * (docs/spec/strategy-reference.json, величина {@code actionLevelSource});
 * собственного поля в дереве стратегии не заводится — значение выводимо
 * из блока, а неоднозначность «объявлены оба блока» отвергается созданием.
 */
public enum StrategyLevelSource {

    /** Уровень объявлен способом расчёта (блок настроек стопа). */
    DECLARED,

    /** Уровень наблюдается после активации (блок настроек трейлинга). */
    OBSERVED
}
