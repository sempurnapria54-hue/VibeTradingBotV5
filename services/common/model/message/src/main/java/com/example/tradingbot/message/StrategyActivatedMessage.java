package com.example.tradingbot.message;

import com.example.tradingbot.domain.model.aggregate.strategy.Strategy;

/**
 * Содержимое события активации: <b>неизменяемый снимок определения</b>
 * целиком плюс идентичности его радиуса и актор
 * (docs/architecture/contracts.md §События).
 *
 * <p><b>Дерево едет полностью, и это не избыточность.</b> Потребитель —
 * торговое ядро — держит копию, по которой ведёт сделки при недоступном
 * владельце (docs/architecture/data-ownership.md §«Копии чужих данных»);
 * дочитать недостающее синхронно он не может по построению — ради
 * снятия этой зависимости копия и заведена.
 *
 * <p>Форма дерева — общий артефакт, поэтому вторым описанием она здесь не
 * повторяется: содержимое несёт саму доменную модель.
 *
 * <p><b>Три идентичности радиуса стоя́т РЯДОМ со снимком, а не только
 * внутри него, и это не дубль.</b> Есть потребитель, который форм
 * содержимого не знает по построению — журнал аудита: он кладёт содержимое
 * как доставлено и достаёт из него только одноимённые компоненты
 * ВЕРХНЕГО уровня (docs/models/domain/other/AuditRecord.md). Внутри снимка
 * две идентичности лежат на глубине, куда он не ходит, а третья зовётся
 * {@code internalId} и по имени колонки не находится вовсе — недоложенная
 * идентичность дала бы колонке радиуса не пробел, а пустоту, объявленную
 * значением (docs/architecture/contracts.md §«Производность меряется у
 * ЧИТАТЕЛЯ, а не у формы»).
 *
 * <p><b>Актор едет содержимым, потому что у класса есть ручная тропа:</b>
 * активацию запускает команда пользователя через периметр
 * (docs/spec/event-actor-presence.json). Область значений — та же, что у
 * полей аудита сущности: <b>класс</b>, а не идентификатор пользователя
 * (docs/models/domain/other/Auditable.md §«Область значений актора»).
 *
 * @param strategyInternalId        идентичность определения
 * @param exchangeAccountInternalId биржевой счёт, на котором определение торгует
 * @param instrumentInternalId      инструмент определения
 * @param actor                     кто инициировал переход: имя предъявленного
 *                                  принципала либо класс собственного прохода
 * @param definition                снимок определения на момент активации
 */
public record StrategyActivatedMessage(String strategyInternalId,
                                       String exchangeAccountInternalId,
                                       String instrumentInternalId,
                                       String actor,
                                       Strategy definition) {
}
