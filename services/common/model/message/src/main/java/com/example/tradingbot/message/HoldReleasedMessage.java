package com.example.tradingbot.message;

/**
 * Содержимое события «ступень снята»: пара подъёма «радиус × ступень» и
 * актор — без кода причины и без ступени, в которую объект пришёл
 * (docs/architecture/contracts.md §«Снятие ступени несёт пару подъёма, но без
 * кода причины»).
 *
 * <p><b>Пара та же, что у подъёма</b> ({@link HoldRaisedMessage}), поэтому
 * снятие сопоставимо с подъёмом без чтения ядра: читатель видит, какая
 * именно ступень ушла с объекта радиуса.
 *
 * <p><b>Кода причины нет:</b> основание снятия одно — ручная операция, —
 * направление несёт сам класс, а машинный код ручной тропы едет журнальной
 * строкой снятия той же транзакции (docs/rules/manual-halt.md). <b>Ступени,
 * в которую объект пришёл, нет тоже:</b> она выводится лестницей из радиуса
 * и снятой ступени, и второе поле разошлось бы с лестницей.
 *
 * <p><b>Актор едет содержимым, потому что ручная тропа у класса
 * единственная</b> (docs/spec/event-actor-presence.json). Область значений —
 * та же, что у полей аудита сущности: класс, а не идентификатор
 * пользователя (docs/models/domain/other/Auditable.md §«Область значений
 * актора»).
 *
 * <p>Запись, а не {@code @Value}: у значения есть ЧИТАТЕЛЬ за
 * сериализацией (.claude/rules/codestyle.md §«Неизменяемое значение,
 * пересекающее сериализацию»). Строит её маппер производителя, а не домен.
 *
 * @param exchangeAccountInternalId биржевой счёт радиуса
 * @param instrumentInternalId      инструмент радиуса; пусто у счётного
 *                                  радиуса
 * @param scope                     радиус снятия — имя значения
 *                                  {@code HoldScope}; область значений
 *                                  домовая
 *                                  (docs/components/models/HoldSignal.md),
 *                                  и здесь она не переписывается
 * @param rung                      СНЯТАЯ ступень — имя значения
 *                                  {@code HoldRung}; область значений
 *                                  домовая (там же)
 * @param actor                     кто снял ступень: имя предъявленного
 *                                  принципала
 */
public record HoldReleasedMessage(String exchangeAccountInternalId,
                                  String instrumentInternalId,
                                  String scope,
                                  String rung,
                                  String actor) {
}
