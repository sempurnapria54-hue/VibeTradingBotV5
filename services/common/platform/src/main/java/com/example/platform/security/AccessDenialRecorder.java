package com.example.platform.security;

/**
 * Писатель следа отвергнутого по правам вызова — <b>порт, а не
 * реализация</b>.
 *
 * <p><b>Реализация есть не у всякого сервиса, и это не пропуск.</b> Строку
 * заводит тот, у кого отказ произошёл <b>и</b> есть своя база
 * (docs/rules/api-access-policy.md §«След отказа пишет тот, у кого есть
 * база»); у периметра базы нет, и след отказа там — лог и метрика. Порт
 * поэтому необязателен: точки входа отказа спрашивают его через
 * {@code ObjectProvider} и при отсутствии реализации отвечают тем же
 * отказом, ничего не записывая.
 *
 * <p><b>Классы отказа выражены двумя методами, а не перечнем-параметром.</b>
 * Перечень исходов живёт доменной моделью сервиса-писателя
 * (docs/models/domain/other/AccessDenial.md), а доменные перечни
 * объявляются только в доменном слое (.claude/rules/codestyle.md §«Слои
 * моделей и enum'ы»): затащить его в общий артефакт периметра значило бы
 * завести второй дом. Метод на класс отказа границу сохраняет.
 *
 * <p><b>Отказ записи доступом не становится.</b> Реализация поглощает сбой
 * записи сама; вызывающий получает отказ в любом случае. Обратный порядок
 * был бы ошибкой в разрешающую сторону (docs/concept.md П1, следствие 3).
 */
public interface AccessDenialRecorder {

    /**
     * Принципал не предъявлен либо предъявленный не принят.
     *
     * <p>Принципал не передаётся намеренно: заявленное, но не
     * удостоверенное имя в строку не пишется — это была бы запись
     * непроверенного как факта.
     *
     * @param surface куда стучались: метод и путь
     */
    void recordPrincipalAbsent(String surface);

    /**
     * Принципал принят, но операция ему не разрешена.
     *
     * @param surface   куда стучались: метод и путь
     * @param principal <b>принятый</b> принципал: на этой тропе
     *                  аутентификация уже прошла
     */
    void recordOperationForbidden(String surface, String principal);
}
