package com.example.platform.util;

import lombok.experimental.UtilityClass;

/**
 * Константы периметра: величины, осмысленные больше чем в одном сервисе.
 * Один класс-дом с вложенными по теме
 * (.claude/rules/codestyle.md §Константы).
 */
@UtilityClass
public class Constants {

    /** Аудит записи: кто инициировал ход. */
    @UtilityClass
    public class Audit {

        /**
         * Класс собственного прохода контура: расписание, реакция
         * обработчика, исполнитель команды — ход без предъявленного
         * принципала.
         *
         * <p><b>Значение отвечает на «который из двух КЛАССОВ», а не «какой
         * сервис»</b> (docs/models/domain/other/Auditable.md §«Область
         * значений актора»). Имя сервиса в этой роли было бы неотличимо от
         * имени принципала, когда принципалы станут именованными, — а
         * область значений при втором субъекте поверхности разворачивается
         * именно в имена.
         *
         * <p><b>Дом у величины один, и здесь он по построению.</b> Пока
         * константа стояла копией у каждого сервиса, её расхождение было бы
         * не наблюдаемо: актор едет содержимым события в ЧУЖОЙ журнал, и
         * второе значение того же класса читалось бы там как второй класс.
         */
        public static final String SYSTEM_PRINCIPAL = "system";
    }
}
