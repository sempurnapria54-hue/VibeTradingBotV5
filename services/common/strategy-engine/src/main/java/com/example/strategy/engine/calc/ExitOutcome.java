package com.example.strategy.engine.calc;

/**
 * Исход округления объявленной доли reduce-only выхода. Форма ветвления и
 * примеры — docs/spec/order-sizing.json (величина {@code exitOutcome});
 * здесь — что значение означает
 * (docs/components/models/CalculatedSize.md §ExitOutcome).
 *
 * <p><b>Пола минимального размера у выхода нет:</b> подъём размера менял
 * бы объявленное действие — частичный выход стал бы бо́льшим, вплоть до
 * полного. Вместо пола — эти четыре исхода.
 */
public enum ExitOutcome {

    /** Штатный частичный выход объявленной доли; остаток жизнеспособен. */
    PARTIAL,

    /** Объявленная доля забрала экспозицию целиком; округление ни при чём. */
    FULL_BY_FRACTION,

    /**
     * «Частично» на этом размере невыразимо, поэтому выход целиком: либо
     * размер выхода ниже минимального торгового, либо ниже него остаток —
     * дробь, которую нечем ни защитить, ни закрыть
     * (docs/rules/no-partial-close.md).
     */
    FULL,

    /** Размер ниже минимального, а остаток достаточен: действие не исполняется. */
    SKIPPED
}
