package com.example.strategy.engine.calc;

/**
 * Тип контролируемой ошибки расчёта. Разделяет временную нехватку данных
 * и постоянную невыразимость: первая повторяется бюджетом действия,
 * вторая исполнения не получает
 * (docs/components/models/CalculationError.md).
 */
public enum CalculationErrorType {

    /** Данные задержались либо источник временно недоступен — повторяемо. */
    TEMPORARY,

    /** Действие невозможно рассчитать в текущей конфигурации — не повторяемо. */
    PERMANENT
}
