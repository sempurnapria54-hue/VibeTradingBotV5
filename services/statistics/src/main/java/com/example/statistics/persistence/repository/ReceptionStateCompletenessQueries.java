package com.example.statistics.persistence.repository;

import java.time.OffsetDateTime;
import org.springframework.data.jpa.repository.Query;
import org.springframework.data.repository.query.Param;

/**
 * Три операнда полноты, читаемые по строкам состояния приёма
 * (docs/spec/durable-reception.json, {@code pairsObservedSince},
 * {@code pairsObserved}, {@code pairContinuityClaimable}).
 *
 * <p><b>Объявления вынесены в общего родителя, а наследник у него один.</b>
 * Прежде наследников было два — по одному на подключение к базе журнала:
 * владельца и кросс-подключение модуля статистики. Раздел сервиса снял
 * второе вместе с его предметом: у каждой стороны теперь своя строка
 * состояния в своей базе (.claude/decisions/audit-statistics-split.md).
 *
 * <p><b>Форма пережила снятие второго читателя намеренно.</b> Текст
 * запроса — тот же предмет, что и величина, которую он считает: у неё одна
 * исполнимая форма, и вторая копия текста разошлась бы с первой молча.
 * Дом объявлений держит это свойство независимо от числа наследников.
 *
 * <p><b>Интерфейс НЕ наследует {@code Repository}, и это несущая
 * деталь:</b> не наследуя, он не попадает под сканирование ни одного из
 * трёх объявлений репозиториев — бином не становится и области их не
 * пересекает. Лежит он в пакете-родителе трёх сканируемых, который сам не
 * сканируется ни одним.
 *
 * <p><b>Пишущих методов здесь нет ни одного</b> — у читателя чужой базы их
 * не бывает вовсе, а объявленные тут достались бы и ему.
 */
public interface ReceptionStateCompletenessQueries {

    /**
     * Второй операнд нижней границы полноты: ПОЗДНЕЙШИЙ из моментов, с
     * которых группа наблюдает свои темы (docs/spec/durable-reception.json,
     * {@code pairsObservedSince}).
     *
     * <p><b>Область — ВСЕ строки группы, включая снятые с подписки.</b>
     * Строки журнала снятой темы из журнала не исчезают, и исключение её
     * из максимума опустило бы границу — ошибка в разрешающую сторону.
     *
     * <p>Строк у группы нет вовсе — отдаётся пустое значение: границы нет,
     * и это значение, а не ноль.
     *
     * <p><b>Запрос по отображению, а не нативный</b> — по тому же доводу,
     * что и первый операнд границы: у нативного скалярного чтения тип
     * результата выводится из метаданных JDBC, и драйвер отдаёт по
     * {@code max(timestamptz)} {@code java.sql.Timestamp} (замер захода
     * K5). Объявленный {@code OffsetDateTime} тогда держался бы на
     * преобразовании, которого никто не назначал, а ошибка пришла бы
     * СМЕЩЕНИЕМ времени, то есть тихо.
     */
    @Query("""
            select max(state.observedSince)
              from ReceptionStateEntity state
             where state.consumerGroup = :consumerGroup
            """)
    OffsetDateTime latestObservedSince(@Param("consumerGroup") String consumerGroup);

    /**
     * Область квантора обоих предикатов группы: сколько пар она
     * наблюдает СЕЙЧАС (docs/spec/durable-reception.json,
     * {@code pairsObserved}).
     *
     * <p><b>Считаются только ПОДПИСАННЫЕ пары, и это не сужение ради
     * удобства.</b> Величина заведена ради самой области: свёртка «все» по
     * пустой коллекции истинна, и без сравнения с нулём предикат
     * непрерывности при отсутствии подписки говорил бы «дыры нет» — ошибка
     * в разрешающую сторону и неразличение «не проверяли» с «проверили,
     * всё в порядке» (docs/concept.md, П1).
     *
     * <p><b>Область здесь ДРУГАЯ, чем у второго операнда границы</b>
     * ({@link #latestObservedSince}), и разведение несущее: граница
     * считается по всем строкам, включая снятые с подписки, — их строки
     * журнала из журнала не исчезли; непрерывность — только по
     * подписанным, иначе неопрашиваемая строка делала бы предикат ложным
     * навсегда.
     */
    @Query("""
            select count(state)
              from ReceptionStateEntity state
             where state.consumerGroup = :consumerGroup
               and state.subscribed = true
            """)
    Long countSubscribedPairs(@Param("consumerGroup") String consumerGroup);

    /**
     * Сколько подписанных пар группы <b>не</b> утверждают непрерывность
     * (docs/spec/durable-reception.json, {@code pairContinuityClaimable} —
     * здесь его отрицание).
     *
     * <p><b>Считается отрицание, а не сама свёртка «все», и это ровно
     * она:</b> «ни на одной паре дыры нет» истинно тогда и только тогда,
     * когда пар с дырой ноль. Читать все строки ради того же ответа
     * значило бы тащить сущности ради предиката
     * (.claude/rules/codestyle.md §«Выборка данных»).
     *
     * <p><b>Конъюнктов у предиката три, и здесь стоя́т все три их
     * отрицания.</b> Первые два — ветви разрыва: приём остановлен на
     * неполном конверте и отставание достигло срока хранения темы (лежит
     * МОМЕНТОМ: пусто = разрыва не было). Третий — <b>свежесть самой
     * строки состояния</b>: оба первых операнда производит сам
     * потребитель, и когда его нет как процесса, старая строка утверждала
     * бы непрерывность в состоянии, о котором ничего не известно
     * (docs/rules/durable-consumer-reception.md §«Предикат непрерывности»).
     *
     * <p><b>Сравнение с моментом устаревания нестрогое, и это ровно
     * отрицание строгого.</b> Свежесть объявлена как «возраст МЕНЬШЕ
     * допустимого», значит строка возрастом ровно в допустимый свежей уже
     * не является.
     *
     * @param staleBefore момент, раньше которого обновлённая строка
     *                    состояния считается устаревшей: момент выдачи за
     *                    вычетом допустимого возраста
     */
    @Query("""
            select count(state)
              from ReceptionStateEntity state
             where state.consumerGroup = :consumerGroup
               and state.subscribed = true
               and (state.receptionHalted = true
                     or state.lagGapAt is not null
                     or state.updatedAt <= :staleBefore)
            """)
    Long countSubscribedPairsWithBreak(@Param("consumerGroup") String consumerGroup,
                                       @Param("staleBefore") OffsetDateTime staleBefore);
}
