package com.example.statistics.domain.model;

import java.time.OffsetDateTime;
import lombok.Value;

/**
 * Что журнал объявляет читателю о своей полноте: нижняя граница и
 * предикат непрерывности
 * (docs/spec/durable-reception.json, величины {@code receptionLowerBound},
 * {@code continuityClaimable}).
 *
 * <p><b>Величин две, и они отвечают на РАЗНЫЕ вопросы.</b> Граница
 * выражает <b>начало</b> ряда — «журнал полон по событиям, произведённым
 * после X», — предикат выражает <b>отсутствие дыры</b> в нём. Порознь ни
 * одна из них читателю не достаточна, поэтому они и собраны в одну форму:
 * выдача, отдающая одну без другой, была бы выразима
 * (docs/rules/durable-consumer-reception.md §«Полнота — две величины, а не одна»).
 *
 * <p><b>Граница может ОТСУТСТВОВАТЬ, и отсутствие есть значение, а не
 * ноль</b> (docs/rules/absent-value-semantics.md): группа, не наблюдающая
 * ни одной темы, полноты не обещает вовсе. На том же состоянии предикат
 * непрерывности ложен — обе величины едут одной выдачей и обязаны
 * говорить об одном состоянии одно и то же.
 */
@Value
public class ReceptionCompleteness {

    /**
     * С какого момента журнал полон; пусто — не обещается ничего.
     *
     * <p><b>Клейм высказывается о моменте ПРОИЗВОДСТВА события, а
     * величина считается по моментам приёма и наблюдения.</b> Расхождение
     * сознательно и консервативно в одну сторону: журнал несёт не меньше
     * обещанного (там же, §«Граница мерится приёмом, а клейм говорит о
     * производстве»).
     */
    OffsetDateTime lowerBound;

    /**
     * Непрерывность журнала после нижней границы утверждаема.
     *
     * <p>Ложь означает «не утверждаема», а не «дыра есть»: у величины два
     * повода стать ложной — найденная дыра и пустая область квантора.
     */
    Boolean continuityClaimable;
}
