-- строки сделочного агрегата (docs/rules/statistics-aggregates.md, раздел о
-- проскоке выхода по стопу и §«Персистентность»; форма величин —
-- docs/spec/statistics-aggregates.json, меры одной сделки —
-- docs/spec/stop-exit-slippage.json).
--
-- ПОЧЕМУ НОВАЯ МИГРАЦИЯ, А НЕ ПРАВКА V1. Применённая миграция не правится ни
-- в одном байте (.claude/rules/codestyle.md §«Применённая миграция
-- неизменяема — включая комментарии»).
--
-- Проект до прод-рубежа: таблицы пусты, бэкфилла не требуется, и
-- обязательные колонки агрегата вводятся напрямую, без умолчания «на время
-- миграции» (.claude/rules/pre-launch-schema-changes.md). Строку агрегата
-- пишет только upsert пересчёта, и он называет все три колонки; строки
-- агрегатов восполнимы из фактов повторным пересчётом.

-- ---------------------------------------------------------------------
-- Сделочный факт: два операнда
-- ---------------------------------------------------------------------

-- ОБА ОПЕРАНДА NULLABLE, и пустота у них — значение, а не пробел входа:
-- причина закрытия пуста только до терминала, а проскок пуст у всякой
-- сделки, у которой мера неприменима либо неизмерима
-- (docs/rules/absent-value-semantics.md). Нулём пустота не подменяется.
alter table deal_facts add column close_reason varchar(32);

alter table deal_facts add column stop_exit_slippage numeric(36, 18);

comment on column deal_facts.close_reason is
    'Причина закрытия сделки — имя значения Deal.CloseReason. Свёртка читает '
    'одно её значение — STOP_LOSS, признак популяции проскока выхода по стопу. '
    'Аварийный терминал пишет EMERGENCY_CLOSE безусловно и в популяцию не входит';

comment on column deal_facts.stop_exit_slippage is
    'Проскок выхода по стопу — деньги расчётной валюты, неблагоприятный '
    'положителен, знак не нормализуется. Хранится деньгами: долю R считает '
    'свёртка делением на плановый риск той же строки. Пусто = мера '
    'неприменима либо неизмерима (docs/spec/stop-exit-slippage.json)';

-- ---------------------------------------------------------------------
-- Сделочное зерно: пара счётчиков и сумма долей R
-- ---------------------------------------------------------------------

-- ПАРА СЧЁТЧИКОВ, А НЕ ОДИН: популяция — сделки, закрытые стопом, а не сделки
-- с непустой мерой. Неизмеренные иначе выпадали бы молча, и выборка
-- калибровки читалась бы полной; их число — разность двух счётчиков, вторым
-- носителем она не заводится.
alter table deal_aggregates add column stop_exit_deals integer not null;

alter table deal_aggregates add column stop_exit_slippage_deals integer not null;

-- СУММА ДОЛЕЙ R, А НЕ ДЕНЕГ — тем же доводом, что у r_sum: запас назначается
-- долей R, а частное денежных сумм взвешивало бы сделки их риском.
alter table deal_aggregates add column stop_exit_slippage_r_sum numeric(36, 18) not null;

comment on column deal_aggregates.stop_exit_deals is
    'Из вошедших в отношение к риску — закрытые стопом. Пара к '
    'stop_exit_slippage_deals: разность двух счётчиков — закрытые стопом с '
    'неизмеримым проскоком. Аварийный терминал сюда не входит';

comment on column deal_aggregates.stop_exit_slippage_deals is
    'Из закрытых стопом — с измеренным проскоком: знаменатель среднего '
    'проскока в долях R';

comment on column deal_aggregates.stop_exit_slippage_r_sum is
    'Сумма проскока выхода по стопу в долях планового риска сделки; средний '
    'проскок есть stop_exit_slippage_r_sum / stop_exit_slippage_deals. Знак не '
    'нормализуется: исполнение лучше уровня входит отрицательным слагаемым';
