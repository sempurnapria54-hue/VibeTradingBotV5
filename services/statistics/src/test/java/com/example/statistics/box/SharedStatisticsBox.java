package com.example.statistics.box;

import java.util.Map;
import org.springframework.test.context.DynamicPropertyRegistry;
import org.springframework.test.context.DynamicPropertySource;

/**
 * Ящик со штатным положением осей конфигурации: тик приёма включён, такт — до
 * которого прогон не доживает, подписка на единственную тему производителя
 * несомых классов, тик пересчёта включён с выражением такта, до которого
 * прогон не доживает, контур доступа настроен на стаб провайдера
 * идентичности.
 *
 * <p><b>Контекст у наследников этого класса ОДИН.</b> Ключ кэша контекста
 * несёт набор методов {@code @DynamicPropertySource}, и у всех наследников он
 * один и тот же — объявленный здесь; свой метод заводит ровно тот класс
 * кейсов, у которого положение осей другое, и платит за это своим подъёмом.
 *
 * <p><b>Своя группа потребителя у такого класса обязательна, и это не
 * удобство.</b> Контексты прогона не закрываются — их кэширует каркас теста,
 * — а группа есть состояние на брокере: два контекста с одним именем группы
 * делят партии темы, и партия достаётся ОДНОМУ из них. Своя группа читает
 * тему с начала, поэтому вместе с ней берётся и своя тема: иначе одиночка
 * переигрывала бы всё, что положили соседние классы прогона, и писала бы их
 * строки в базу параллельно чужой клетке.
 */
abstract class SharedStatisticsBox extends StatisticsBox {

    @DynamicPropertySource
    static void substrate(DynamicPropertyRegistry registry) {
        StatisticsSubstrate.register(registry, Map.of());
    }
}
