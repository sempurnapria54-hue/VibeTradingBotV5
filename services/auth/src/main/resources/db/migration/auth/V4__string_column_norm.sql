-- Строковые колонки членства и тенанта — к норме строковых колонок либо к
-- объявленному исключению (docs/rules/persistence-representation.md
-- §«Конвенции колонок»; исключения — docs/models/domain/other/Membership.md,
-- docs/models/domain/core/Tenant.md).
--
-- ПОЧЕМУ ДОБОР, А НЕ ПРАВКА V1. Применённая миграция не правится ни в
-- одном байте (.claude/rules/codestyle.md §«Применённая миграция
-- неизменяема — включая комментарии»).
--
-- К НОРМЕ. Роль членства — строка значения перечня, и её длина — норма
-- varchar(64), а не подобранная под сегодняшние значения: расширение
-- безопасно и строк не переписывает.
--
-- ИСКЛЮЧЕНИЕ — ШИРИНУ НАЗНАЧИЛ ЧУЖОЙ КОНТРАКТ. Идентификатор пользователя
-- — claim sub провайдера идентичности, и его длину задаёт не наша схема,
-- а контракт OIDC: не длиннее 255 ASCII-символов. Имя тенанта при
-- отсутствии preferred_username заводится из того же sub, поэтому у́же
-- его границы быть не может. Норма 64 отказывала бы в заведении тенанта
-- тому, чей идентификатор у провайдера длиннее, — то есть отказ пришёл бы
-- при первом входе человека, а не при сборке. Объявленной границы у
-- preferred_username контракт OIDC не даёт, и имя длиннее 255 отказ
-- по-прежнему получает: это названный остаток, а не граница.
--
-- Бэкфилла нет и не требуется: до прод-рубежа таблицы пусты
-- (.claude/rules/pre-launch-schema-changes.md).

alter table memberships alter column role type varchar(64);

alter table memberships alter column user_id type varchar(255);

alter table tenants alter column name type varchar(255);
