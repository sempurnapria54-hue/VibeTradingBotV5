-- Комментарий колонки момента разрыва — к действующей семантике.
--
-- ПОЧЕМУ НОВАЯ МИГРАЦИЯ, А НЕ ПРАВКА V1. Применённая миграция не правится ни
-- в одном байте (.claude/rules/codestyle.md §«Применённая миграция
-- неизменяема — включая комментарии»), а комментарий колонки живёт в базе и
-- правится своим оператором.
--
-- Комментарий V1 говорил, что момент гасит чистка непроизводственного
-- окружения, когда разрыв уходит за нижнюю границу. Гашения больше нет ни в
-- одном окружении: момент только ставится, позднейший разрыв пары переписывает
-- прежний, а лежит ли разрыв внутри обещаемого ряда, решает чтение — конъюнкт
-- разрыва сравнивает момент с нижней границей полноты
-- (docs/rules/durable-consumer-reception.md, таблица писателей;
-- docs/models/domain/other/AuditRecord.md, раздел о строке состояния приёма).
--
-- Прочие комментарии V1, живущие в базе, о гашении не говорят и остаются.
comment on column reception_states.lag_gap_at is
    'Момент обнаружения разрыва по сроку хранения; пусто = разрыва не было. '
