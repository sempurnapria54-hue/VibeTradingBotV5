package com.example.audit.box;

import java.util.Map;
import org.springframework.test.context.DynamicPropertyRegistry;
import org.springframework.test.context.DynamicPropertySource;

/**
 * Ящик со штатным положением осей конфигурации: тик включён, такт — до
 * которого прогон не доживает, подписка на обе темы производителей, контур
 * доступа настроен на стаб провайдера идентичности, профиль хранения —
 * чистящий.
 *
 * <p><b>Контекст у наследников этого класса ОДИН.</b> Ключ кэша контекста
 * несёт набор методов {@code @DynamicPropertySource}, и у всех
 * наследников он один и тот же — объявленный здесь; свой метод заводит
 * ровно тот класс кейсов, у которого положение осей другое, и платит за
 * это своим подъёмом.
 *
 * <p><b>Своя группа потребителя у такого класса обязательна, и это не
 * удобство.</b> Контексты прогона не закрываются — их кэширует каркас
 * теста, — а группа есть состояние на брокере: два контекста с одним
 * именем группы делят партии темы, и партия достаётся ОДНОМУ из них.
 * Своя группа читает тему с начала, поэтому вместе с ней берётся и своя
 * тема: иначе одиночка переигрывала бы всё, что положили соседние классы
 * прогона, и писала бы их строки в базу параллельно чужой клетке.
 */
abstract class SharedAuditBox extends AuditBox {

    @DynamicPropertySource
    static void substrate(DynamicPropertyRegistry registry) {
        AuditSubstrate.register(registry, Map.of());
    }
}
