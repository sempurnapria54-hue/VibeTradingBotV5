package com.example.auditstatistics.domain.model;

import static java.util.Objects.isNull;

import java.time.OffsetDateTime;
import lombok.Value;

/**
 * Два durable-момента строки состояния приёма пары, из которых выводится
 * возраст последнего принятого события
 * (docs/spec/audit-journal.json, операнд {@code lastEventAgeMs}).
 *
 * <p><b>Доменная форма у этой строки заведена, а у строк зерна — нет, и
 * различает их предикат.</b> Строка зерна не несёт ни одного вопроса к
 * себе и потому едет проекцией
 * ({@code DealGrainRow}); здесь вопрос есть — какой из двух моментов
 * является основанием возраста, — и жить он обязан на модели, а не в
 * вызывающем коде (.claude/rules/codestyle.md §«Вложенность и
 * rich-модели»).
 *
 * <p><b>Оба момента durable, и это несущее свойство.</b> Возраст,
 * отсчитываемый от старта процесса, у пода, перезапускаемого чаще порога,
 * не дорастал бы до порога никогда — алерт молчал бы бесконечно ровно
 * там, где заведён.
 */
@Value
public class ReceptionPairMoments {

    /** Тема пары — вторая половина её ключа. */
    String topic;

    /** Момент происшествия последнего принятого события; пусто — не принято ещё ничего. */
    OffsetDateTime lastAcceptedOccurredAt;

    /** Момент, с которого группа наблюдает тему непрерывно. */
    OffsetDateTime observedSince;

    /**
     * Момент, от которого считается возраст последнего принятого
     * события.
     *
     * <p><b>До первого приёма величина ОПРЕДЕЛЕНА и берётся от момента
     * наблюдения</b> (docs/spec/audit-journal.json, {@code lastEventAgeMs}).
     * Иначе у здоровой пары, которой производитель ещё ничего не
     * присылал, ряда возраста не существовало бы вовсе — и правило на
     * пропажу ряда поднимало бы алерт на паре, с которой всё в порядке,
     * то есть первым же ложным срабатыванием обесценивало бы алерт,
     * заведённый против бесшумной потери.
     */
    public OffsetDateTime lastEventMoment() {
        if (isNull(lastAcceptedOccurredAt)) {
            return observedSince;
        }
        return lastAcceptedOccurredAt;
    }
}
