package com.example.auditstatistics.domain.model;

/**
 * Профиль хранения журнала аудита в этом окружении — значение оси
 * {@code journalRetentionProfile}
 * (docs/architecture/platform.md §«Чем различаются окружения»).
 *
 * <p><b>Ось несёт профиль, а не число суток, и это разведение
 * объявлено:</b> профиль отвечает «чистить ли», глубина в сутках —
 * величина конфигурации сервиса, потому что она <b>назначается</b>, а не
 * выводится из профиля (docs/models/domain/other/AuditRecord.md
 * §«Глубина хранения»). Перевод «профиль → сутки», положенный сюда, стал
 * бы константой кода у калибровочного числа.
 *
 * <p><b>Перечень закрыт значениями оси</b>, а не удобством читателя: его
 * члены — те же слова, что стоят в {@code deploy/<окружение>/env.yaml}, и
 * второго их носителя не заводится.
 */
public enum JournalRetentionProfile {

    /** Журнал чистится по назначенной глубине — непроизводственные окружения. */
    REDUCED,

    /** Журнал не чистится вовсе: у чистки в этом окружении нет предмета. */
    UNBOUNDED;

    /**
     * Есть ли у чистки предмет в этом окружении.
     *
     * <p><b>Предикат живёт на модели, а не в исполнителе</b>
     * (.claude/rules/codestyle.md §«Вложенность и rich-модели»): вопрос
     * опирается только на само значение оси, и сравнение с членом перечня,
     * разложенное по джобе, размазало бы его по слоям.
     *
     * <p><b>Пустого профиля этот вопрос не разбирает</b>, и разбирать не
     * может: пустое значение означает «ось не доехала», а не член перечня
     * (docs/rules/absent-value-semantics.md). Ветвь пустоты держит
     * исполнитель — там же, где названо, что он на ней делает
     * (docs/components/JournalCleanupJob.md §«Ось не доехала — проход не
     * идёт, и это не то же самое, что `UNBOUNDED`»).
     */
    public Boolean isCleanupApplicable() {
        return REDUCED.equals(this);
    }
}
