package com.example.auditstatistics.domain.model;

import java.util.List;
import lombok.Builder;
import lombok.Value;

/**
 * Страница агрегатной выборки: строки выбранного зерна, позиция
 * продолжения и то, что журнал объявляет о своей полноте
 * (docs/rules/statistics-aggregates.md §«Что это за числа и кто их
 * читает»).
 *
 * <p><b>Перечня два, а заполнен ровно один — тот, чьё зерно названо.</b>
 * Формы строк у зёрен разные: наборы величин непересекающиеся, а ключи
 * зерна различаются. Один перечень с общей формой строки склеил бы две
 * разные строки в одну и заставил бы читателя различать их по пустотам.
 *
 * <p><b>ПУСТОЙ перечень и ОТСУТСТВУЮЩИЙ перечень различаются, и различие
 * несущее:</b> пустой означает «зерно выбрано, строк в окне нет»,
 * отсутствующий — «спрошено не это зерно». Сведённые в одно, они дали бы
 * пустоте два смысла (docs/rules/absent-value-semantics.md).
 *
 * <p><b>Полнота едет ВМЕСТЕ со строками, а не отдельным запросом:</b>
 * читатель суточной строки без предиката не отличает «за сутки было три
 * сделки» от «за сутки принято три события, а приём стои́т с 10:00»
 * (docs/models/domain/other/AuditRecord.md §«Как журнал читается»).
 */
@Value
@Builder
public class AggregatePage {

    /** Зерно, о котором спрошено: им же выбран заполненный перечень. */
    AggregateGrain grain;

    /** Строки сделочного зерна; пусто (не пустой перечень) — спрошено другое зерно. */
    List<DealAggregate> dealRows;

    /** Строки зерна происшествий; пусто (не пустой перечень) — спрошено другое зерно. */
    List<IncidentAggregate> incidentRows;

    /**
     * Позиция, с которой читается следующая страница; пусто — окно
     * дочитано до конца.
     */
    AggregateCursor nextCursor;

    /** Нижняя граница полноты журнала и предикат непрерывности. */
    JournalCompleteness completeness;
}
