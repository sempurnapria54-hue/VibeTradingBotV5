package com.example.auditstatistics.domain.model;

import java.time.OffsetDateTime;
import lombok.Value;

/**
 * Позиция курсорной страницы журнала — пара «момент происшествия,
 * идентичность события»
 * (docs/models/domain/other/AuditRecord.md §«Как журнал читается»).
 *
 * <p><b>Пара, а не смещение, и это не вкус.</b> Смещение на растущей
 * таблице пропускает и дублирует строки: вставка между двумя запросами
 * сдвигает нумерацию всего, что читатель ещё не прочёл.
 *
 * <p><b>Пара уникальна на любом подмножестве строк</b>, потому что вторая
 * её половина — ключ дедупа доставки. Отсюда курсор не зависит от набора
 * необязательных отборов: он остаётся верным, когда читатель добирает
 * страницу с другим их составом.
 *
 * <p><b>Читателя из JSON у этой формы нет:</b> наружу курсор уходит своей
 * api-моделью, а домен собирает его на границе и держит в памяти прохода —
 * поэтому {@code @Value}, а не запись
 * (.claude/rules/codestyle.md §«Неизменяемое значение, пересекающее
 * сериализацию»).
 */
@Value
public class JournalCursor {

    /** Момент происшествия последней отданной строки. */
    OffsetDateTime occurredAt;

    /** Идентичность последней отданной строки — вторая половина пары. */
    String eventId;
}
