package com.example.auditstatistics.config;

import lombok.Getter;
import lombok.Setter;
import org.springframework.boot.context.properties.ConfigurationProperties;

/**
 * Учётные данные владельцев данных сервиса
 * (docs/architecture/data-ownership.md §Раскладка).
 *
 * <p><b>Владельцев два, поэтому и комплектов два</b> — журнал и агрегаты.
 * Роль — на владельца данных, а не на сервис: у процесса с двумя
 * владельцами ролей тоже две, и этим обеспечен инвариант «один пишущий», а
 * не только объявлен.
 *
 * <p><b>Третьего комплекта здесь нет намеренно.</b> Подключений у процесса
 * три: журнал модуль статистики читает <b>под своей ролью</b>, а не под
 * ролью журнала. Третье подключение собирается из этих двух —
 * адрес базы журнала плюс учётные данные роли агрегатов
 * ({@link PersistenceConfig}), — и своей настройки не имеет: заданный
 * отдельно адрес разошёлся бы с адресом журнала молча, и «читаем журнал»
 * оказалось бы клеймом, который никто не мерит.
 */
@Getter
@Setter
@ConfigurationProperties(prefix = "audit-statistics.persistence")
public class PersistenceProperties {

    /** Подключение под ролью-владельцем журнала: `audit`. */
    private DatabaseConnectionProperties journal = new DatabaseConnectionProperties();

    /** Подключение под ролью-владельцем агрегатов: `statistics`. */
    private DatabaseConnectionProperties aggregates = new DatabaseConnectionProperties();

    /**
     * Верхняя граница пула КРОСС-подключения — базы журнала под ролью
     * агрегатов.
     *
     * <p><b>Скаляром, а не третьим комплектом, и это следует из того же
     * довода.</b> Адреса и учётных данных своих у кросс-подключения нет
     * намеренно: заданные отдельно, они разошлись бы с половинами, из
     * которых оно собрано. <b>Пул — не половина адреса, а собственный
     * ресурс</b>: соединения этого подключения держит своя реплика, и
     * калибруется он отдельно от обоих владельцев.
     *
     * <p>Дефолт — тот же, что у комплектов, и по тому же доводу
     * ({@link DatabaseConnectionProperties}): читателей у журнала со
     * стороны статистики два — джоба пересчёта и агрегатная выборка, — и
     * работают они не параллельнее самого процесса.
     */
    private Integer journalReadMaxPoolSize = 5;
}
