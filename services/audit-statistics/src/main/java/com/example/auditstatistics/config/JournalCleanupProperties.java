package com.example.auditstatistics.config;

import lombok.Getter;
import lombok.Setter;
import org.springframework.boot.context.properties.ConfigurationProperties;

/**
 * Чистка журнала в непроизводственном окружении: выключатель и глубина
 * хранения (docs/components/JournalCleanupJob.md).
 *
 * <p><b>Операндов у прохода два, и здесь лежит только один.</b>
 * Применимость — ось окружения {@code journalRetentionProfile}
 * ({@link EnvironmentProperties}): она отвечает «чистить ли», и в
 * {@code prod} предмета у прохода нет вовсе. Глубина в сутках —
 * <b>величина конфигурации сервиса</b>, потому что она НАЗНАЧАЕТСЯ, а не
 * выводится из профиля; перевод «профиль → сутки», положенный внутрь
 * исполнителя, стал бы константой кода у калибровочного числа
 * (docs/models/domain/other/AuditRecord.md §«Глубина хранения»).
 *
 * <p><b>Размера порции удаления здесь нет, и это не пропуск.</b> Исход
 * прохода от него не зависит: сколько бы строк ни удалила порция, проход
 * идёт, пока старее глубины ничего не остаётся, — и ни глубины, ни нижней
 * границы полноты он не двигает. Это локальная техническая константа
 * исполнителя (.claude/rules/codestyle.md §Константы), а не калибровочное
 * число, у которого были бы владелец и якорь калибровки. Тем она и
 * отличается от окна реле outbox у соседнего сервиса: там окно ограничивает
 * ОБЪЁМ работы тика, здесь порция — только объём одного запроса.
 */
@Getter
@Setter
@ConfigurationProperties(prefix = "jobs.journal-cleanup")
public class JournalCleanupProperties {

    /** Чистка включена — выключатель, как у всякой джобы. */
    private Boolean enabled = Boolean.TRUE;

    /**
     * Глубина хранения журнала в сутках: строки, принятые раньше, проход
     * удаляет.
     *
     * <p><b>Отсчёт идёт по моменту ПРИЁМА, а не происшествия</b>
     * (docs/models/domain/other/AuditRecord.md §«Глубина хранения»): на
     * этом стои́т отбор пересчёта агрегатов, и на оси происшествия его
     * клейм был бы ложен.
     *
     * <p><b>Дефолт кладёт этот шаг, калибрует владелец журнала</b> по
     * наблюдаемому объёму. Направление консервативности — в сторону
     * БО́ЛЬШЕЙ глубины: удаление необратимо, а рост тома в
     * непроизводственном окружении наблюдаем и ограничен размером тома.
     * Месяц выбран как окно, в котором непроизводственный разбор ещё
     * происходит; риск-аппетитом число не является
     * (.claude/processes/question-delegation.md §«Число: риск-аппетит
     * против калибровки наблюдения»).
     */
    private Integer depthDays = 30;
}
