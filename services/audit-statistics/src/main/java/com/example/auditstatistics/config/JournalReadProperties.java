package com.example.auditstatistics.config;

import java.time.Duration;
import lombok.Getter;
import lombok.Setter;
import org.springframework.boot.context.properties.ConfigurationProperties;

/**
 * Ограничения журнальной выборки чтения: предел ширины окна и размер
 * курсорной страницы
 * (docs/models/domain/other/AuditRecord.md §«Как журнал читается»).
 *
 * <p><b>Предел объявлен величиной конфигурации, а не константой кода</b> —
 * так говорит дом: он калибруется владельцем журнала по наблюдаемой
 * плотности строк, и зашитый в код потребовал бы сборки на всякую
 * перекалибровку. Риск-аппетитом число не является — это калибровка
 * наблюдения (.claude/processes/question-delegation.md §«Число:
 * риск-аппетит против калибровки наблюдения»).
 *
 * <p><b>Пределов ширины окна у сервиса ДВА, и здесь лежит только один.</b>
 * Журнальный меряется <b>моментом происшествия</b>, агрегатный — сутками
 * зерна, и одним числом они не выражаются: у агрегатной выборки будет своя
 * форма (docs/rules/statistics-aggregates.md §«Что это за числа и кто их
 * читает»). Ни один из них не является копией окна пересчёта: то назначает
 * объём собственной работы прохода и консервативно в сторону
 * <b>большего</b> ({@link AggregateRecomputeProperties}), эти ограничивают
 * запрошенное читателем и консервативны в сторону <b>меньшего</b>.
 *
 * <p><b>Направление консервативности названо и оно не симметрично:</b>
 * слишком узкое окно обратимо самим читателем — он добирает страницами;
 * слишком широкое необратимо для соседей по процессу, потому что тяжёлый
 * скан идёт по таблице, которая в {@code prod} не чистится вовсе.
 */
@Getter
@Setter
@ConfigurationProperties(prefix = "surface.journal-read")
public class JournalReadProperties {

    /**
     * Предельная ширина окна по моменту происшествия.
     *
     * <p><b>Запрос без окна и запрос с окном шире предела ОТВЕРГАЮТСЯ, а
     * не сужаются молча</b> (docs/models/domain/other/AuditRecord.md §«Как
     * журнал читается»): молчаливое сужение отдало бы неполный ряд под
     * видом запрошенного (docs/concept.md, П1 — умолчание не бывает
     * благоприятным).
     *
     * <p><b>Дефолт кладёт этот шаг, калибрует владелец журнала</b> по
     * наблюдаемой плотности строк у тенанта. Неделя выбрана как окно, за
     * которое разбор происшествия ещё держится в одном взгляде, а число
     * строк одного тенанта в нём наблюдаемо: индекс
     * {@code ix_audit_record_tenant_occurred} обслуживает ровно этот
     * отбор — свой тенант в обратном хронологическом порядке.
     */
    private Duration maxWindow = Duration.ofDays(7);

    /**
     * Размер курсорной страницы.
     *
     * <p><b>Операндом вызова размер не является, и это решение с
     * причиной.</b> Второй операнд-предел завёл бы вторую ветвь
     * отвержения («страница шире дозволенного») при одном и том же
     * исходе — а состав экранных срезов шаг не заводит вовсе, он приезжает
     * с потребителем (.claude/work/backlog.md §«Состав экранных операций
     * чтения `audit-statistics` — по появлению их потребителя»). Пока
     * потребителя нет, выбирать размер некому.
     */
    private Integer pageSize = 200;
}
