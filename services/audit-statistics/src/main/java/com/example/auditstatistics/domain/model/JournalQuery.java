package com.example.auditstatistics.domain.model;

import static java.util.Objects.isNull;
import static java.util.Objects.nonNull;
import static org.apache.commons.lang3.BooleanUtils.isFalse;

import java.time.Duration;
import java.time.OffsetDateTime;
import lombok.Builder;
import lombok.Value;

/**
 * Запрошенный отбор строк журнала — доменная форма вопроса читателя
 * (docs/models/domain/other/AuditRecord.md §«Как журнал читается»).
 *
 * <p><b>Радиус тенанта обязателен и НЕ СВЕРЯЕТСЯ.</b> Значение приезжает
 * операндом вызова — заголовком контекста, который ставит периметр, — и
 * доверие к нему добывается не здесь: чем держится радиус вместо сверки и
 * какова названная цена, говорит дом контекста
 * (docs/architecture/contracts.md §«Контекст тенанта в вызове»). Отбор по
 * полученному тенанту — третье звено этой тропы, и его держит выборка.
 *
 * <p><b>Окно по моменту происшествия обязательно и ограничено сверху.</b>
 * Предикаты ниже отвечают на вопросы раздельно: окна нет вовсе, окно
 * перевёрнуто и окно шире дозволенного — разные дефекты вопроса, и
 * читателю они говорят разное.
 *
 * <p><b>Курсор лежит ДВУМЯ половинами, а не собранной парой.</b> Так его
 * и задаёт читатель, и так же он уходит в запрос; собранная пара
 * появляется только в ОТВЕТЕ — как позиция продолжения
 * ({@link JournalCursor}). Форма выбрана затем, чтобы «половина курсора»
 * оставалась выразимым состоянием вопроса: собранная пара с пустой
 * половиной была бы неотличима от отсутствия курсора.
 *
 * <p><b>Четыре отбора по радиусам конъюнктивны и необязательны.</b> Они
 * не заменяют ни тенанта, ни окна и друг друга не требуют; строки БЕЗ
 * значения колонки этим входом не запрашиваются — пустота колонки
 * означает «содержимое идентичности не несёт», и запрос «строки, у
 * которых радиуса нет» есть экранный срез, отложенный вместе с прочими
 * (.claude/work/backlog.md §«Состав экранных операций чтения
 * `audit-statistics` — по появлению их потребителя»).
 */
@Value
@Builder
public class JournalQuery {

    /** Тенант-владелец строк: радиус отбора, операнд вызова. */
    String tenantId;

    /** Левая граница окна по моменту происшествия, включающая. */
    OffsetDateTime from;

    /** Правая граница окна по моменту происшествия, включающая. */
    OffsetDateTime to;

    /** Первая половина позиции продолжения; пусто — читается первая страница окна. */
    OffsetDateTime cursorOccurredAt;

    /** Вторая половина позиции продолжения — она разводит строки одного момента. */
    String cursorEventId;

    /** Необязательный отбор: биржевой счёт. */
    String exchangeAccountInternalId;

    /** Необязательный отбор: инструмент. */
    String instrumentInternalId;

    /** Необязательный отбор: сделка. */
    String dealInternalId;

    /** Необязательный отбор: определение стратегии. */
    String strategyInternalId;

    /**
     * Окно названо обеими границами.
     *
     * <p>Одна половина окна окном не является: запрос с открытым концом
     * читает ряд без предела ровно так же, как запрос без окна вовсе.
     */
    public Boolean hasWindow() {
        return nonNull(from) && nonNull(to);
    }

    /**
     * Границы окна стоя́т в порядке: правая не раньше левой.
     *
     * <p><b>Перевёрнутое окно — отказ, а не пустая выдача.</b> Пустая
     * выдача на перевёрнутых границах читалась бы как «за этот период
     * ничего не происходило», то есть отвечала бы на вопрос, которого
     * читатель не задавал (docs/concept.md, П1).
     */
    public Boolean isWindowOrdered() {
        if (isNull(from) || isNull(to)) {
            return Boolean.FALSE;
        }
        return isFalse(to.isBefore(from));
    }

    /**
     * Окно шире названного предела.
     *
     * <p>Сравнение строгое: окно, равное пределу, дозволено — предел есть
     * наибольшее допустимое, а не первое запрещённое.
     */
    public Boolean isWindowWiderThan(Duration limit) {
        if (isNull(from) || isNull(to)) {
            return Boolean.FALSE;
        }
        return Duration.between(from, to).compareTo(limit) > 0;
    }

    /**
     * Курсор назван наполовину: одна половина пары есть, другой нет.
     *
     * <p><b>Половина курсора — отказ, а не чтение с начала окна.</b>
     * Позиция задаётся ПАРОЙ, и по одной её половине продолжить чтение
     * нельзя: строки одного момента происшествия разводит только вторая.
     * Молчаливое чтение с начала отдало бы читателю уже прочитанную
     * страницу под видом следующей.
     */
    public Boolean hasPartialCursor() {
        if (isNull(cursorOccurredAt) && isNull(cursorEventId)) {
            return Boolean.FALSE;
        }
        return isNull(cursorOccurredAt) || isNull(cursorEventId);
    }
}
