package com.example.auditstatistics.domain.service;

import java.time.OffsetDateTime;

/**
 * Откуда берутся операнды полноты журнала
 * (docs/spec/audit-journal.json, {@code journalLowerBound},
 * {@code continuityClaimable}).
 *
 * <p><b>Источник вынесен формой, потому что подключений к базе журнала у
 * процесса ДВА, а свёртка одна.</b> Свои читатели модуля аудита — чистка и
 * журнальная выборка — берут операнды под ролью журнала; агрегатная
 * выборка обязана брать их <b>третьим подключением</b>, под ролью
 * агрегатов, потому что журнал для модуля статистики — чужая база
 * (docs/architecture/data-ownership.md §Раскладка).
 *
 * <p><b>Что этим предотвращено.</b> Вторая реализация свёртки — по одной
 * на подключение — расходилась бы с первой молча: у величин одна
 * исполнимая форма и один дом
 * (.claude/rules/policy-home.md). Вторая тропа чтения без формы источника
 * потребовала бы у свёртки знать, чьи репозитории ей внедрены, — то есть
 * ровно того выбора, который дом раскладки называет остатком.
 *
 * <p><b>Источник приезжает ОПЕРАНДОМ вызова, а не внедряется в свёртку.</b>
 * Так подключение читателя видно на месте вызова и держится <b>типом</b>:
 * читатель, объявивший чужой источник, не собирается. Внедрённый в
 * свёртку, он был бы одним на всех её читателей, и второй пришлось бы
 * различать квалификатором — то есть строкой, а не типом.
 *
 * <p><b>Область каждого операнда названа у него, а не здесь</b>, и области
 * у них РАЗНЫЕ намеренно: граница считается по всем строкам состояния,
 * непрерывность — только по подписанным
 * (docs/models/domain/other/AuditRecord.md §«Позиция чтения и с какого
 * момента журнал полон»).
 */
public interface JournalCompletenessSource {

    /**
     * Самый ранний момент приёма среди сохранившихся строк журнала; пусто
     * — журнал пуст (docs/spec/audit-journal.json,
     * {@code journalMinRecordedAt}).
     */
    OffsetDateTime earliestRecordedAt();

    /**
     * Позднейший момент наблюдения по строкам группы — включая снятые с
     * подписки; пусто — строк у группы нет
     * (docs/spec/audit-journal.json, {@code pairsObservedSince}).
     */
    OffsetDateTime latestObservedSince(String consumerGroup);

    /**
     * Сколько пар группа наблюдает сейчас — область квантора обоих её
     * предикатов; считаются только ПОДПИСАННЫЕ пары
     * (docs/spec/audit-journal.json, {@code pairsObserved}).
     */
    Long countSubscribedPairs(String consumerGroup);

    /**
     * Сколько подписанных пар группы <b>не</b> утверждают непрерывность:
     * ноль означает, что дыры нет ни на одной
     * (docs/spec/audit-journal.json, {@code pairContinuityClaimable} —
     * здесь его отрицание).
     *
     * @param staleBefore момент, раньше которого строка состояния приёма
     *                    считается устаревшей
     */
    Long countSubscribedPairsWithBreak(String consumerGroup, OffsetDateTime staleBefore);
}
