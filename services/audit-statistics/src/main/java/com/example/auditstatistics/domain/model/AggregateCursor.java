package com.example.auditstatistics.domain.model;

import java.time.LocalDate;
import lombok.Value;

/**
 * Позиция курсорной страницы агрегатов — ключ зерна последней отданной
 * строки (docs/rules/statistics-aggregates.md §«Что это за числа и кто их
 * читает»).
 *
 * <p><b>Ключ зерна, а не смещение, и не пара с суррогатным ключом.</b>
 * Смещение на таблице, куда каждые сутки добавляется строка, пропускает и
 * дублирует при вставке между запросами; ключ зерна уникален по
 * построению — {@code uk_deal_aggregate_grain} и
 * {@code uk_incident_aggregate_grain}, — поэтому второго операнда позиции
 * не заводится.
 *
 * <p><b>Компонентов четыре, а несёт их зерно.</b> У сделочного зерна
 * значимы все четыре; у зерна происшествий последние два пусты по
 * построению — в его ключе таких колонок нет вовсе. Тенант компонентом не
 * является: он радиус вопроса и один на всю выдачу.
 *
 * <p><b>Читателя из JSON у этой формы нет:</b> наружу позиция уходит своей
 * api-моделью, а домен собирает её на границе и держит в памяти прохода —
 * поэтому {@code @Value}, а не запись
 * (.claude/rules/codestyle.md §«Неизменяемое значение, пересекающее
 * сериализацию»).
 */
@Value
public class AggregateCursor {

    /** Сутки зерна последней отданной строки. */
    LocalDate bucketDate;

    /** Биржевой счёт последней отданной строки. */
    String exchangeAccountInternalId;

    /**
     * Определение стратегии последней отданной строки; пусто законно.
     *
     * <p>У сделочного зерна пустота означает строку «сделка стратегии не
     * имеет», у зерна происшествий — что компонента в ключе нет.
     */
    String strategyInternalId;

    /**
     * Расчётная валюта последней отданной строки; пусто законно.
     *
     * <p>У сделочного зерна пустота означает строку «валюта результата не
     * резолвилась», у зерна происшествий — что компонента в ключе нет.
     */
    String resultCurrency;
}
