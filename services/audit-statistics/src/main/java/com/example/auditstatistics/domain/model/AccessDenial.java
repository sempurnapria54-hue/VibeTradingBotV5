package com.example.auditstatistics.domain.model;

import static org.apache.commons.lang3.StringUtils.isBlank;
import static org.apache.commons.lang3.StringUtils.isNotBlank;

import com.example.tradingbot.domain.model.Auditable;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

/**
 * Журнальная строка <b>отвергнутого по правам вызова</b> к поверхности
 * этого сервиса: попытка обратиться к закрытой точке, у которой принципал
 * не предъявлен либо предъявленный не принят, — а также попытка под
 * принятым принципалом, которому операция не разрешена
 * (docs/models/domain/other/AccessDenial.md).
 *
 * <p><b>Носитель наблюдаемости</b> (docs/concept.md, П3): персистентная
 * запись, по которой держатель видит интерес к поверхности. Лог этой роли
 * не исполняет — он не запрашивается, не агрегируется и не переживает
 * ротацию.
 *
 * <p><b>Природа факта — происшествие:</b> у каждой попытки свой момент,
 * дедупа нет по построению, счётность обязательна. Схлопывание попыток
 * занижало бы частоту — единственную величину, ради которой строка и
 * заводится.
 *
 * <p><b>Строка лежит в базе ЖУРНАЛА, а не агрегатов</b>
 * (docs/models/domain/other/AccessDenial.md §Персистентность): отказ
 * доступа есть факт наблюдаемости, а не число отчёта.
 *
 * <p><b>Модель ничего не решает и ни на что не влияет.</b> Её
 * единственный потребитель — разбор человеком; читающих выборок у неё нет
 * и превентивно не заводится.
 */
@Getter
@Setter
@NoArgsConstructor
public class AccessDenial extends Auditable {

    /** Внутренний идентификатор строки. */
    private Long id;

    /** Внешний идентификатор строки: наружу сервис отдаёт его, а не ключ базы. */
    private String internalId;

    /** Поверхность, к которой обратились: HTTP-метод и путь. */
    private String surface;

    /** Класс отказа. */
    private Outcome outcome;

    /**
     * <b>Принятый</b> принципал — тот, чью личность контур удостоверил.
     * Пусто ⟺ {@link Outcome#PRINCIPAL_ABSENT}; пустота покрывает обе
     * тропы — принципал не предъявлен и предъявленный не принят.
     * Заявленное, но не удостоверенное имя сюда не пишется: это была бы
     * запись непроверенного как факта.
     */
    private String principal;

    /**
     * Согласованы ли класс отказа и принципал.
     *
     * <p>Инвариант модели: пустота {@link #principal} и
     * {@link Outcome#PRINCIPAL_ABSENT} — одно и то же состояние,
     * выраженное дважды, и расхождение между ними означает дефект
     * писателя, а не законное состояние строки.
     */
    public Boolean isConsistent() {
        return Outcome.PRINCIPAL_ABSENT.equals(outcome) ? isBlank(principal) : isNotBlank(principal);
    }

    /** Класс отказа: чем именно вызов отвергнут. */
    public enum Outcome {

        /**
         * Принципал не предъявлен <b>либо предъявленный не принят</b>.
         *
         * <p>Разделяет значения то, <b>известен ли субъект</b>: у
         * непринятых кредов он неизвестен ровно так же, как у
         * непредъявленных, — записать заявленное имя значило бы записать
         * непроверенное как факт. Третье значение различало бы то, чего мы
         * не знаем.
         */
        PRINCIPAL_ABSENT,

        /**
         * Принципал предъявлен и принят, но операция ему не разрешена.
         *
         * <p><b>Сегодня не достижим ни одной тропой</b>: пер-операционных
         * проверок права у контура нет — при одном субъекте поверхности
         * различать некого (docs/rules/api-access-policy.md). Значение
         * заведено вместе с первым, потому что это часть контракта внешней
         * поверхности: слить исходы дешевле сейчас и дороже потом
         * (docs/rules/error-handling-policy.md). Писатель у него назван и
         * достижим — недостижима сегодня сама популяция, а не актор.
         */
        OPERATION_FORBIDDEN
    }
}
