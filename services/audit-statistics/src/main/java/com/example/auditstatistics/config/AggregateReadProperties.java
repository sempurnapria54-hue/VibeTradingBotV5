package com.example.auditstatistics.config;

import lombok.Getter;
import lombok.Setter;
import org.springframework.boot.context.properties.ConfigurationProperties;

/**
 * Ограничения агрегатной выборки чтения: предел ширины окна в сутках зерна
 * и размер курсорной страницы
 * (docs/rules/statistics-aggregates.md §«Что это за числа и кто их
 * читает»).
 *
 * <p><b>Предел здесь СВОЙ, а не копия журнального, и это сказано домом.</b>
 * Журнальный меряется <b>моментом происшествия</b>, этот — <b>сутками
 * зерна</b>, и одним числом они не выражаются
 * ({@link JournalReadProperties}). Ни один из них не является копией окна
 * пересчёта: то назначает объём собственной работы прохода и консервативно
 * в сторону <b>большего</b> ({@link AggregateRecomputeProperties}), эти
 * ограничивают запрошенное читателем и консервативны в сторону
 * <b>меньшего</b>.
 *
 * <p><b>Направление консервативности то же, что у журнального:</b> узкое
 * окно обратимо самим читателем — он добирает страницами; широкое
 * необратимо для соседей по процессу.
 *
 * <p>Риск-аппетитом ни одно из чисел не является — это калибровка
 * наблюдения (.claude/processes/question-delegation.md §«Число:
 * риск-аппетит против калибровки наблюдения»).
 */
@Getter
@Setter
@ConfigurationProperties(prefix = "surface.aggregate-read")
public class AggregateReadProperties {

    /**
     * Предельная ширина окна в сутках зерна — ВКЛЮЧАЮЩИМ числом суток.
     *
     * <p><b>Запрос без окна и запрос с окном шире предела ОТВЕРГАЮТСЯ, а
     * не сужаются молча</b> (docs/rules/statistics-aggregates.md §«Что это
     * за числа и кто их читает»): молчаливое сужение отдало бы неполный ряд
     * под видом запрошенного (docs/concept.md, П1).
     *
     * <p><b>Дефолт кладёт этот шаг, калибрует владелец агрегатов</b> по
     * наблюдаемому числу зёрен у тенанта. Якорь — <b>квартал</b>: период, за
     * который держатель сравнивает определения стратегий между собой, и при
     * этом ряд суток ещё обозрим страницами. Число суток здесь заметно
     * больше журнального предела, и это не разнобой: строк у агрегата по
     * строке на зерно в сутки, а у журнала — по строке на событие, и
     * тяжесть скана у них разная на порядки.
     */
    private Integer maxWindowDays = 92;

    /**
     * Размер курсорной страницы.
     *
     * <p><b>Операндом вызова размер не является</b> — по тому же доводу,
     * что и у журнальной выборки: второй операнд-предел завёл бы вторую
     * ветвь отвержения при том же исходе, а состав экранных срезов шаг не
     * заводит вовсе — он приезжает с потребителем
     * (.claude/work/backlog.md §«Состав экранных операций чтения
     * `audit-statistics` — по появлению их потребителя»).
     */
    private Integer pageSize = 200;
}
