package com.example.auditstatistics.domain.service;

/**
 * Вопрос читателя не принят — обеими выборками чтения сервиса
 * (docs/models/domain/other/AuditRecord.md §«Как журнал читается»;
 * docs/rules/statistics-aggregates.md §«Что это за числа и кто их
 * читает»).
 *
 * <p><b>Класс один на две выборки, и это не обобщение задним числом.</b>
 * Исход у отказа один — вопрос не принят, — и наружу он идёт одним кодом
 * одного error-DTO. Второй класс потребовал бы второй записи в едином
 * обработчике при том же ответе, то есть завёл бы второй носитель одного
 * исхода (.claude/rules/policy-home.md). Поводы у отказа при этом разные, и
 * различает их <b>текст</b>: он говорит вызывающему, чем именно вопрос не
 * принят.
 *
 * <p><b>Отказ, а не молчаливое сужение.</b> Урезанное до предела окно
 * отдало бы неполный ряд под видом запрошенного, и читатель принял бы
 * тишину за отсутствие событий (docs/concept.md, П1 — умолчание не бывает
 * благоприятным).
 *
 * <p><b>Текст поясняет, ЧТО именно не принято, и секретов не несёт:</b>
 * он говорит о вопросе вызывающего, а не об устройстве сервиса
 * (docs/rules/error-handling-policy.md §«Что отказ НЕ сообщает»).
 */
public class ReadQueryRejectedException extends RuntimeException {

    public ReadQueryRejectedException(String message) {
        super(message);
    }
}
