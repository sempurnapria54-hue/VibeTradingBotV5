package com.example.auditstatistics.config;

import lombok.Getter;
import lombok.Setter;

/**
 * Учётные данные одного подключения к базе.
 *
 * <p><b>Форма отдельным типом, а не вложенным классом</b>
 * (.claude/rules/codestyle.md §«Строгие правила»): подключений у сервиса
 * три, и все три описываются одной формой — второй её копии не заводится.
 *
 * <p><b>Умолчаний здесь нет:</b> незаданное значение приезжает пустым и
 * означает отказ, а не разрешение — форма и умолчания живут в
 * {@code application.yaml}.
 */
@Getter
@Setter
public class DatabaseConnectionProperties {

    /** JDBC-адрес базы. */
    private String url;

    /** Имя роли, которой идёт подключение (docs/architecture/data-ownership.md §Раскладка). */
    private String username;

    /** Пароль роли; приезжает из секрета кластера, в репозиторий не попадает. */
    private String password;

    /**
     * Верхняя граница пула соединений этого подключения.
     *
     * <p><b>Величина конфигурации, а не умолчание библиотеки.</b>
     * Подключения собираются здесь явно, минуя {@code spring.datasource},
     * и свойства {@code spring.datasource.hikari.*} этими бинами не
     * читаются: без собственной формы перекалибровка размера потребовала
     * бы сборки, а не правки конфигурации.
     *
     * <p><b>Дефолт вдвое меньше умолчания библиотеки, и это выведено, а не
     * выбрано.</b> Процесс не параллелит работу шире: приём идёт одним
     * слушателем, планировщик у джоб один, а читатель поверхности —
     * держатель. Умножать это на три подключения означало бы взять до
     * тридцати соединений одной репликой у кластера, чей
     * {@code max_connections} никем не назначен
     * (deploy/base/data/postgres-cluster.yaml).
     *
     * <p><b>Пишет её владелец, разворачивающий сервис</b> — ключом
     * манифеста окружения, как и прочие величины его конфигурации; дефолт
     * кладёт шаг, калибровка идёт по наблюдённому числу занятых
     * соединений. Доменного дома у величины нет и не заводится: ни одного
     * клейма о данных она не двигает.
     */
    private Integer maxPoolSize = 5;
}
