package com.example.auditstatistics.domain.model;

import static java.util.Objects.nonNull;

import java.time.OffsetDateTime;
import lombok.Builder;
import lombok.Value;

/**
 * Строка журнала событий по тенанту — доменная форма
 * (docs/models/domain/other/AuditRecord.md).
 *
 * <p><b>Неизменяема по построению:</b> событие произошло однажды, и правки
 * записи о нём не бывает.
 *
 * <p><b>Читателя из JSON у неё нет:</b> она собирается из сообщения на
 * границе приёма и живёт только внутри прохода, поэтому форма значения —
 * {@code @Value}, а не запись или бин
 * (.claude/rules/codestyle.md §«Неизменяемое значение, пересекающее
 * сериализацию»).
 *
 * <p><b>Содержимое несёт строкой, а не разобранным деревом.</b> Журнал
 * хранит факт, а не его интерпретацию: форму содержимого знает только
 * производитель класса, и в базу оно ложится как доставлено.
 */
@Value
@Builder
public class AuditRecord {

    /**
     * Идентичность принятого события. Она же ключ дедупа доставки и
     * внешняя идентичность строки: наружу журнал отдаёт её, а не ключ
     * базы.
     */
    String eventId;

    /**
     * Тенант-владелец события. Радиус отбора по умолчанию; на проводе
     * приезжает <b>ключом записи</b>, а не заголовком
     * (docs/architecture/contracts.md §«Как конверт лежит на проводе —
     * поимённо»).
     */
    String tenantId;

    /** Класс события — дискриминатор содержимого, имя из перечня производителя. */
    String eventType;

    /** Момент происшествия из конверта. Время UTC. */
    OffsetDateTime occurredAt;

    /**
     * Момент приёма события журналом. Его ставит сторона приёма, а не
     * конверт, — поэтому в перечень обязательного входа он не входит.
     */
    OffsetDateTime recordedAt;

    /** Версия формы содержимого из конверта. */
    Integer version;

    /**
     * Контекст трассировки из конверта. <b>Пусто законно</b> и означает
     * «трассировки не было», а не «потеряна».
     */
    String traceContext;

    /** Биржевой счёт, если содержимое его несёт; иначе пусто. */
    String exchangeAccountInternalId;

    /** Инструмент, если содержимое его несёт; иначе пусто. */
    String instrumentInternalId;

    /** Сделка, если содержимое её несёт; иначе пусто. */
    String dealInternalId;

    /** Определение стратегии, если содержимое его несёт; иначе пусто. */
    String strategyInternalId;

    /** Содержимое события целиком, как доставлено. */
    String content;

    /**
     * Вход полон: присутствуют все шесть обязательных значений — пять
     * полей конверта и само содержимое
     * (docs/models/domain/other/AuditRecord.md §«Единственная ветвь, на
     * которой строки не будет, — неполный вход»).
     *
     * <p><b>Перечень равен множеству колонок {@code not null} схемы за
     * вычетом тех, которые производит сама сторона приёма:</b> ключ
     * присваивает база, момент приёма ставит код приёма. Вычет не
     * послабление — он называет ровно те колонки, которых во входящем
     * сообщении нет по построению.
     *
     * <p><b>Контекст трассировки сюда не входит:</b> он законно пуст, и
     * требование его присутствия останавливало бы приём у всякого
     * производителя, чьё инструментирование ещё не подключено.
     */
    public Boolean hasCompleteInput() {
        return nonNull(eventId)
                && nonNull(tenantId)
                && nonNull(eventType)
                && nonNull(occurredAt)
                && nonNull(version)
                && nonNull(content);
    }
}
