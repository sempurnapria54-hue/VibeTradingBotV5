package com.example.auditstatistics.config;

import lombok.Getter;
import lombok.Setter;
import org.springframework.boot.context.properties.ConfigurationProperties;

/**
 * Пересчёт агрегатов: выключатель, такт и окно суток
 * (docs/rules/statistics-aggregates.md §«Пересчёт — проекция, а не
 * накопитель»).
 *
 * <p><b>Число суток окна — СВОЯ величина конфигурации сервиса, а не копия
 * пределов выдачи.</b> Те ограничивают запрошенное читателем и
 * консервативны в сторону <b>меньшего</b> окна; эта назначает объём
 * собственной работы прохода и консервативна в сторону <b>большего</b>:
 * лишний пересчёт стоит запроса, пропущенный — неверного числа у
 * человека.
 *
 * <p><b>«Полный пересчёт» — значение этой величины, а не вторая форма.</b>
 * Окно, назначенное шире прожитого журналом времени, накрывает его
 * целиком; отдельной джобы, отдельного момента и отдельного писателя у
 * полного пересчёта нет. Догнать событие старше окна значит <b>расширить
 * окно</b>, и цена этого названа домом: реакция идёт сменой конфигурации и
 * её применением, а не нажатием.
 *
 * <p><b>Ручного триггера у прохода нет</b> — по доводу сервиса:
 * поверхность объявлена только читающей, и фасад завёл бы входящую точку
 * записи, которой инвентарь ей не даёт (docs/architecture/services.md).
 *
 * <p><b>Размера порции здесь нет, и это не пропуск:</b> порция у прохода —
 * <b>сутки</b>, то есть операнд зерна, а не настраиваемое число. Дробить
 * сутки нечем: ключ зерна их содержит, и половина суток дала бы строку
 * меньшего состава.
 */
@Getter
@Setter
@ConfigurationProperties(prefix = "jobs.aggregate-recompute")
public class AggregateRecomputeProperties {

    /** Пересчёт включён — выключатель, как у всякой джобы. */
    private Boolean enabled = Boolean.TRUE;

    /**
     * Сколько последних суток пересчитывается за тик.
     *
     * <p><b>Дефолт кладёт этот шаг, калибрует владелец агрегатов</b> по
     * наблюдённому опозданию событий: условие пересмотра — опоздание
     * больше окна (docs/rules/statistics-aggregates.md §«Названная цена
     * окна»). Риск-аппетитом число не является — это калибровка
     * наблюдения (.claude/processes/question-delegation.md §«Число:
     * риск-аппетит против калибровки наблюдения»).
     *
     * <p>Неделя выбрана как окно, в котором опоздание доставки ещё
     * правдоподобно: срок хранения темы у брокера — того же порядка, а
     * событие, отставшее дольше него, до журнала не доезжает вовсе и
     * пересчётом не догоняется.
     */
    private Integer windowDays = 7;
}
