package com.example.auditstatistics.config;

import java.time.Duration;
import lombok.Getter;
import lombok.Setter;
import org.springframework.boot.context.properties.ConfigurationProperties;

/**
 * Подписка группы журнала: её имя, адрес брокера и величины приёма
 * (docs/components/AuditEventListener.md).
 *
 * <p><b>Имя группы — не свойство транспорта, а операнд durable-строки:</b>
 * ключ состояния приёма есть пара «группа × тема», и та же строка отвечает,
 * с какого момента журнал полон. Поэтому имя объявлено здесь, а не в
 * настройках клиента брокера.
 *
 * <p><b>Тем подписки здесь НЕТ, и это не пропуск.</b> Их читатель один —
 * выражение в {@code @KafkaListener}, разбирающее ключ конфигурации само
 * ({@code AuditEventListener}); объявленное здесь поле не потребил бы
 * никто, а его тип {@code List<String>} приглашал бы написать ключ
 * перечнем YAML — формой, при которой одиночный плейсхолдер выражения не
 * разрешается вовсе (.claude/rules/codestyle.md §«Неиспользуемый код»).
 * Сколько тем и почему — у самого слушателя и в
 * {@code application.yaml}.
 */
@Getter
@Setter
@ConfigurationProperties(prefix = "reception")
public class ReceptionProperties {

    /**
     * Адрес брокера.
     *
     * <p><b>Форма своя, а не {@code spring.kafka.*}</b>, и это не вкус:
     * автоконфигурации Kafka в дереве нет вовсе — Boot 4 разнёс её по
     * модулям {@code spring-boot-<технология>}, и {@code spring-kafka} сам
     * по себе ничего не настраивает. Клиент брокера здесь объявлен целиком
     * явно ({@code ReceptionKafkaConfig}), поэтому и свойства свои.
     *
     * <p>Пустое означает, что тропа приёма не настроена: контейнер не
     * поднимется, и это отказ, а не тихий простой.
     */
    private String bootstrapServers;

    /** Имя группы потребителей журнала — первая половина ключа пары. */
    private String groupId;

    /**
     * Пауза между повторами отравленного сообщения.
     *
     * <p>Числа попыток рядом с ней нет и не будет: обработчик группы
     * журнала идёт <b>без ограничения</b> их числа
     * ({@code JournalReceptionErrorHandler}). Пауза управляет только тем,
     * как часто повтор бьётся в базу, — не тем, сдастся ли он.
     */
    private Duration retryInterval = Duration.ofSeconds(5);

    /**
     * Выключатель тика состояния приёма — как у всякой джобы
     * (.claude/rules/codestyle.md §Джобы).
     *
     * <p>При снятом выключателе строк состояния не заводит никто: величины
     * приёма пишутся <b>обновлением</b> существующей строки, и обновление
     * не находит цели. Предикат непрерывности тогда отвечает «не
     * утверждаема» — область квантора пуста, — а не «дыры нет»
     * (docs/spec/audit-journal.json, {@code pairsObserved}).
     */
    private Boolean stateTickEnabled = Boolean.TRUE;

    /**
     * Такт тика состояния приёма.
     *
     * <p><b>Калибруется в паре с допустимым возрастом строки состояния</b>
     * ({@code receptionStateMaxAgeMs}, docs/spec/audit-journal.json): порог
     * обязан быть заметно больше такта — один пропущенный такт есть
     * штатная задержка, — и заметно меньше срока, за который дыра
     * становится потерей. Оба числа назначает владелец, разворачивающий
     * сервис (docs/components/ReceptionStateJob.md).
     *
     * <p>Поле объявлено ради формы и умолчания; сам {@code @Scheduled}
     * читает ту же тропу конфигурации напрямую — иначе такт пришлось бы
     * разрешать до создания бина.
     */
    private Duration stateTickInterval = Duration.ofSeconds(30);

    /**
     * Допустимый возраст строки состояния приёма
     * (docs/spec/audit-journal.json, {@code receptionStateMaxAgeMs}).
     *
     * <p><b>Это третий конъюнкт попарного предиката непрерывности, а не
     * настройка отчётности.</b> Оба первых операнда разрыва производит сам
     * потребитель; когда он не работает как процесс, он не производит
     * ничего, и старая строка утверждала бы непрерывность в состоянии, о
     * котором ничего не известно — молчание было бы неотличимо от здоровья
     * (docs/models/domain/other/AuditRecord.md §«Позиция чтения и с какого
     * момента журнал полон»).
     *
     * <p><b>Величина групповая — порог один на все пары:</b> он выражает
     * такт тика {@code ReceptionStateJob}, а тик у группы один.
     *
     * <p><b>Калибруется в паре с тактом тика</b> ({@link
     * #stateTickInterval}): заметно больше такта — один пропущенный такт
     * есть штатная задержка, — и заметно меньше срока, за который дыра
     * становится потерей. Дефолт кладёт этот шаг: десять тактов
     * умолчания — предел, за которым пропуск перестаёт быть задержкой и
     * становится отсутствием потребителя.
     */
    private Duration stateMaxAge = Duration.ofMinutes(5);

    /**
     * Доля срока хранения темы, из которой выводится порог алерта на лаг
     * пары.
     *
     * <p><b>Величина конфигурации сервиса-потребителя, а не константа
     * кода</b>: назначенная внутри исполнителя, она перестала бы быть
     * калибруемой ровно там, где калибровка и нужна
     * (docs/architecture/data-ownership.md §«Outbox и доставка»). Она же —
     * <b>операнд</b> исполнимой формы, а не литерал выражения
     * (docs/spec/audit-journal.json, {@code lagAlertThresholdFraction}).
     *
     * <p>Доля групповая — одна на все пары: она выражает «сколько времени
     * оставить на реакцию», а не свойство темы. Дефолт — половина:
     * гарантия ломается, когда лаг достигает срока, и половина оставляет
     * на реакцию столько же времени, сколько ушло на накопление.
     */
    private Double lagAlertThresholdFraction = 0.5;
}
