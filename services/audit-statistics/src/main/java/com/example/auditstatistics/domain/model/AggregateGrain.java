package com.example.auditstatistics.domain.model;

import static org.apache.commons.lang3.StringUtils.isBlank;

import java.util.Arrays;
import java.util.Objects;

/**
 * Зерно строки агрегатов
 * (docs/rules/statistics-aggregates.md §«Зерно строки»).
 *
 * <p><b>Зерно — обязательный операнд вопроса с закрытым перечнем из двух
 * значений, а не разрез внутри одной страницы</b>
 * (docs/rules/statistics-aggregates.md §«Что это за числа и кто их
 * читает»): ключи у зёрен разные, наборы величин непересекающиеся, ряды
 * суток независимые. Одной страницей они не проходятся — курсор перестал
 * бы быть однозначным, а строка ответа однородной.
 *
 * <p><b>Выборка при этом ОДНА.</b> Предмет у неё один — строки агрегатов,
 * — а зерно есть их разрез; второй выборки зерно не заводит, и клейм
 * владельца журнала «выборок две — по одной на предмет» остаётся верен
 * (docs/models/domain/other/AuditRecord.md §«Как журнал читается»).
 *
 * <p><b>Перечень живёт в ДОМЕННОМ слое, и это конвенция, а не вкус:</b>
 * enum'ы объявляются только здесь, а на границах (api, персистентность)
 * соответствующее поле — строка
 * (.claude/rules/codestyle.md §«Слои моделей и enum'ы»).
 */
public enum AggregateGrain {

    /**
     * Сделочное зерно: «тенант × биржевой счёт × определение стратегии ×
     * сутки UTC × расчётная валюта».
     *
     * <p>Две колонки его ключа законно пусты — определение стратегии
     * («сделка стратегии не имеет») и расчётная валюта («валюта результата
     * не резолвилась»).
     */
    DEAL,

    /**
     * Зерно происшествий: «тенант × биржевой счёт × сутки UTC».
     *
     * <p>Расчётной валюты в ключе нет, потому что её не несёт ни одно из
     * событий этого зерна; пустых колонок в ключе нет ни одной.
     */
    INCIDENT;

    /**
     * Разобрать названное читателем зерно; пусто — не названо либо названо
     * вне перечня.
     *
     * <p><b>Разбор отдаёт ПУСТОТУ, а не бросает, и это несущий выбор.</b>
     * Отказ вопросу принадлежит выборке — там он один класс с прочими
     * поводами и одним текстом, — а исключение, брошенное на границе
     * маппинга, дало бы тому же отказу второй код и второй текст
     * (docs/rules/error-handling-policy.md).
     *
     * <p><b>«Не названо» и «названо чужое» сведены в одно значение</b>
     * намеренно: исход у них один — читатель обязан назвать одно из двух,
     * — и перечень оба раза называется ему целиком. Различать их значило бы
     * различать поводы, по которым читатель делает одно и то же.
     */
    public static AggregateGrain resolve(String name) {
        if (isBlank(name)) {
            return null;
        }
        return Arrays.stream(values())
                .filter(grain -> Objects.equals(grain.name(), name))
                .findFirst()
                .orElse(null);
    }
}
