package com.example.auditstatistics.domain.model;

import java.time.OffsetDateTime;
import lombok.Value;

/**
 * Операнды алерта на лаг по одной паре «группа × тема», как их измерил
 * последний такт тика состояния приёма
 * (docs/architecture/data-ownership.md §«Outbox и доставка»).
 *
 * <p><b>Величины ПОТЕМНЫЕ, а не групповые.</b> Сумма по группе маскирует
 * остановку на одной теме молчанием другой — тем самым механизмом,
 * против которого введён второй конъюнкт предиката
 * (docs/spec/audit-journal.json, {@code unconsumedRecords}).
 *
 * <p><b>Пустыми законно бывают две из трёх, и пустота у них означает
 * «неизвестно», а не ноль</b> (docs/rules/absent-value-semantics.md).
 * Каждая пустая величина уносит СВОЙ ряд экспорта, а не подставляет
 * значение: ноль на пороге кричал бы всегда, ноль на остатке гасил бы
 * алерт ровно там, где измеритель не мерит.
 *
 * <p><b>Момент, а не готовый возраст.</b> Возраст считается в момент
 * съёма — иначе, замороженный тактом, он перестал бы расти вместе с
 * умершим тиком, и алерт молчал бы при мёртвом измерителе
 * (docs/concept.md, П1 — умолчание не бывает благоприятным).
 */
@Value
public class PairLagOperands {

    /** Тема пары — вторая половина её ключа и метка ряда. */
    String topic;

    /** Момент, от которого считается возраст последнего принятого события. */
    OffsetDateTime lastEventMoment;

    /** Порог алерта в миллисекундах; пусто — срок хранения темы не добыт. */
    Long lagAlertThresholdMs;

    /** Остаток непринятого в смещениях; пусто — клиент лага не отдал. */
    Long unconsumedRecords;
}
