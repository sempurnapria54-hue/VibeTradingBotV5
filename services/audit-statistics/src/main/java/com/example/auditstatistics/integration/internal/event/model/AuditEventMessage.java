package com.example.auditstatistics.integration.internal.event.model;

import java.time.OffsetDateTime;
import lombok.Builder;
import lombok.Value;

/**
 * Событие внутренней шины в форме, в которой его прочитала граница
 * (.claude/rules/codestyle.md §«Слой сообщения: внутренняя шина»).
 *
 * <p><b>Это форма ПРОЧИТАННОГО, а не доменная строка журнала.</b> Прежде
 * граница собирала доменную модель прямо из записи брокера, и слой
 * сообщения у сервиса отсутствовал вовсе: разбор конверта и перевод в
 * домен были одним ходом, а значит момент приёма, инвариант полноты и
 * чтение заголовков жили в одном классе.
 *
 * <p><b>Момента приёма здесь нет намеренно.</b> Он не приезжает
 * сообщением — его ставит приём, и ставит он его при переводе в доменную
 * строку (docs/models/domain/other/AuditRecord.md). Поле, которого на
 * проводе не было, в форме прочитанного было бы ложью о содержимом
 * записи.
 *
 * <p><b>Идентичности радиуса — часть прочитанного, а не вывод из него.</b>
 * Они лежат одноимёнными компонентами верхнего уровня содержимого
 * (docs/architecture/contracts.md §«Производность меряется у ЧИТАТЕЛЯ, а
 * не у формы»), и граница достаёт их тем же ходом, что и заголовки.
 */
@Value
@Builder
public class AuditEventMessage {

    /** Идентичность события из заголовка конверта; ключ дедупа у читателя. */
    String eventId;

    /** Тенант-владелец — ключ записи, он же ключ партиции. */
    String tenantId;

    /** Класс события из заголовка конверта; дискриминатор содержимого. */
    String eventType;

    /** Момент происшествия из заголовка конверта, UTC. */
    OffsetDateTime occurredAt;

    /** Версия формы содержимого из заголовка конверта. */
    Integer version;

    /**
     * Контекст трассировки W3C из заголовка конверта. Пустое значение
     * законно и означает «трассировки не было»
     * (docs/rules/absent-value-semantics.md).
     */
    String traceContext;

    /** Биржевой счёт радиуса, если содержимое несёт одноимённый компонент. */
    String exchangeAccountInternalId;

    /** Инструмент радиуса, если содержимое несёт одноимённый компонент. */
    String instrumentInternalId;

    /** Сделка радиуса, если содержимое несёт одноимённый компонент. */
    String dealInternalId;

    /** Определение стратегии радиуса, если содержимое несёт компонент. */
    String strategyInternalId;

    /**
     * Содержимое <b>как доставлено</b>: граница его не интерпретирует и не
     * переписывает (docs/models/domain/other/AuditRecord.md).
     */
    String content;
}
