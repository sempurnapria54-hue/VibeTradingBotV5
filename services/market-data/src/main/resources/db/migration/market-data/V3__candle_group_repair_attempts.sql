-- Счётчик попыток докачки дыр — колонка единицы сбора, а не память процесса.
--
-- Гарантия «исчерпаны попытки — ERROR» обязана пережить рестарт: пока счётчик
-- жил в памяти загрузчика, группа с неустранимой дырой, чей цикл пересекал
-- перезапуск, начинала отсчёт заново и до терминала не доходила никогда
-- (docs/models/domain/other/CandleGroup.md §Персистентность;
-- docs/lifecycles/CandleGroup.md §«Докачка дыр (`REPAIR`)»).
--
-- Умолчание 0 — не подпорка миграции, а смысл величины: заведённая группа
-- не израсходовала ни одной попытки. Та же форма, что у count (V1).
alter table candle_groups
    add column repair_attempts integer not null default 0;

comment on column candle_groups.repair_attempts is 'Попытки докачки дыр с последнего подтверждения плотности; превышение предела конфигурации переводит группу в ERROR';
