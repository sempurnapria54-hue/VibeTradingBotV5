#!/usr/bin/env bash
# Продвижение образа сервиса в окружение: правка ЕДИНСТВЕННОГО места тега.
#
# ПРЕДМЕТ. Это та самая правка, которую делает CI хостинга репозитория и
# которую потом применяет Argo CD (docs/architecture/platform.md
# §Развёртывание). Тег НЕИЗМЕНЯЕМ: сборка происходит один раз на коммит, а
# дальше тег только переезжает из окружения в окружение — эта команда и
# есть переезд. Пересборки на окружение не бывает: в prod уехал бы другой
# образ, чем проверялся на stage.
#
# ПОЧЕМУ КОМАНДА, А НЕ `.yml` ОДНОЙ CI-СИСТЕМЫ. Система не выбрана
# (ARCH-Q1 в остатке: хостинг кода и облако выбираются вместе). Шаг строит
# ФОРМУ: место тега в манифесте окружения плюс команда, которая его правит.
# Любой из кандидатов зовёт её одной строкой; выбор системы эту строку не
# меняет.
#
# ОСИ, КОТОРЫЕ КОМАНДА ОБЪЯВЛЯЕТ (доказаны прогоном, перечень — в отчёте
# шага):
#   1. подвижная метка отвергается (код 1);
#   2. сервис, которого нет в services/, отвергается (код 1);
#   3. окружение, которого нет в deploy/, — ПРАВКА НЕ ПРОВОДИЛАСЬ (код 2);
#   4. рабочий путь проставляет тег в единственное место и повторный
#      прогон с другим тегом его ЗАМЕНЯЕТ, а не добавляет второй.
#
# Запуск:
#   bash tools/deploy-set-image-tag.sh <окружение> <сервис> <тег> [<реестр>]
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ENVIRONMENT="${1:-}"
SERVICE="${2:-}"
TAG="${3:-}"
REGISTRY="${4:-registry.invalid/vibetrading}"

if [ -z "$ENVIRONMENT" ] || [ -z "$SERVICE" ] || [ -z "$TAG" ]; then
  echo "ВХОД ОТВЕРГНУТ: нужны окружение, сервис и тег" >&2
  exit 1
fi

# Неизменяемость тега проверяется формой, а не обещанием: подвижная метка
# («latest», «main», имя окружения) означала бы, что в prod уедет не то, что
# проверялось на stage, — то есть ровно отменяла бы продвижение.
#
# Проверка стои́т ПЕРЕД проверкой сервиса намеренно: иначе ось «подвижная
# метка» неотличима от оси «нет сервиса» — обе давали бы один отказ, и
# доказать поимённо можно было бы только вторую.
case "$TAG" in
  latest|main|master|dev|stage|prod)
    echo "ВХОД ОТВЕРГНУТ: «$TAG» — подвижная метка, а тег обязан быть неизменяемым" >&2
    exit 1
    ;;
esac

MANIFEST="$ROOT/deploy/$ENVIRONMENT/kustomization.yaml"
if [ ! -f "$MANIFEST" ]; then
  echo "ПРАВКА НЕ ПРОВОДИЛАСЬ: нет $MANIFEST — окружения «$ENVIRONMENT» не существует" >&2
  exit 2
fi

if [ ! -d "$ROOT/services/$SERVICE" ]; then
  echo "ВХОД ОТВЕРГНУТ: services/$SERVICE не существует — тег несуществующего сервиса Argo применил бы молча" >&2
  exit 1
fi

# Лаунчер Python объявленной среды — `py -3`; `python3` там заглушка,
# печатающая «Python» и не исполняющая кода
# (.claude/tests/source-api/okx/code-preconditions.md). Поэтому лаунчер
# выбирается по ИСПОЛНЕНИЮ пробы, а не по наличию имени в PATH.
if py -3 -c "pass" >/dev/null 2>&1; then
  PY=(py -3)
elif python3 -c "pass" >/dev/null 2>&1; then
  PY=(python3)
else
  echo "ПРАВКА НЕ ПРОВОДИЛАСЬ: рабочего лаунчера Python не найдено" >&2
  exit 2
fi

exec "${PY[@]}" "$ROOT/tools/deploy_set_image_tag.py" \
  "$MANIFEST" "$REGISTRY/$SERVICE" "$TAG"
