#!/usr/bin/env bash
# Снятие локального стенда.
#
# ЧТО ИСЧЕЗАЕТ: кластер целиком вместе со всеми данными — базой, рядами
# рыночных данных, темами Kafka, хранилищем Vault. Это НЕ остановка: у
# стенда нет состояния вне кластера, кроме файла распечатывания Vault.
# Остановить машину, не потеряв данные, можно иначе — остановкой
# контейнера узла (см. .claude/skills/local-stand.md §«Остановка без
# потери данных»).
#
# Файл распечатывания Vault команда НЕ удаляет: хранилище пересоздаётся
# вместе с кластером, и старый ключ к новому не подойдёт, но удалять
# ключевой материал молча — не её дело. Убирает его держатель.
#
# Запуск:  bash tools/stand/down.sh
set -euo pipefail

CLUSTER="vibetrading"
KIND="${KIND:-$LOCALAPPDATA/kind/kind.exe}"
[ -x "$KIND" ] || KIND="kind"

if "$KIND" get clusters 2>/dev/null | grep -qx "$CLUSTER"; then
  "$KIND" delete cluster --name "$CLUSTER"
  echo "кластер $CLUSTER снят; файл распечатывания Vault остался у держателя"
else
  echo "кластера $CLUSTER нет — снимать нечего"
fi
