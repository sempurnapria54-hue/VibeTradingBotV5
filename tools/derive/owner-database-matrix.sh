#!/usr/bin/env bash
# Члены популяции «роль × база» процесса с несколькими владельцами данных —
# полным произведением.
#
# ПРЕДМЕТ. Перечень выводится из таблицы дома раскладки
# (docs/architecture/data-ownership.md, раздел раскладки): берутся строки,
# чей ПИСАТЕЛЬ — audit-statistics, из них имя базы (первая ячейка). Роль —
# на ВЛАДЕЛЬЦА ДАННЫХ, и владельцев ровно столько же, сколько баз, поэтому
# перечень ролей равен перечню баз. Произведение берётся полным, а не по
# списку объявленных грантов: список объявленных молчит о паре, которой в
# нём нет, — то есть ровно о том состоянии, ради которого правило и
# заведено.
#
# LC_ALL=C.UTF-8 обязателен у grep -P на объявленной среде (дом ловушки —
# .claude/processes/roadmap-step-execution.md §«`grep -P` в этой среде
# требует `LC_ALL=C.UTF-8`»). Классы символов здесь ASCII-only намеренно:
# `\w` в PCRE кириллицу не берёт, и шаблон по русскому слову молча дал бы
# ноль (та же §, клауза о кириллице).
#
# Разделитель кортежа — ТАБУЛЯЦИЯ: сверщик режет строку по ней
# (tools/population-derive-check.py, функция derive).
set -uo pipefail

DOC="${1:-docs/architecture/data-ownership.md}"

# Строки таблицы раскладки, чей писатель — audit-statistics; имя базы —
# первая ячейка строки, в обратных кавычках. `set -e` здесь НЕ включён
# намеренно: под ним пустая выдача grep уронила бы скрипт кодом 1 — то есть
# «расхождение» вместо «мерить нечего», — и объявленная ниже ветвь отказа
# (код 2) была бы недостижима.
rows=$(LC_ALL=C.UTF-8 grep -P '^\| `[a-z_]+` \| `audit-statistics`' "$DOC")
databases=$(printf '%s\n' "$rows" | LC_ALL=C.UTF-8 grep -oP '^\| `\K[a-z_]+(?=`)')

if [ -z "$databases" ]; then
  echo "ВЫВОД НЕ СОСТОЯЛСЯ: в $DOC не найдено ни одной строки раскладки с писателем audit-statistics" >&2
  exit 2
fi

# Роль — на владельца данных, а владелец у каждой из этих баз свой, поэтому
# перечень ролей равен перечню баз.
for role in $databases; do
  for database in $databases; do
    printf '%s\t%s\n' "$role" "$database"
  done
done
