#!/usr/bin/env bash
# Члены популяции «класс события» — из таблицы производителей, а не из
# перечня, встреченного в примерах.
#
# ПРЕДМЕТ. Правило «актор едет содержимым у классов с ручной тропой»
# обязано иметь исход на КАЖДОМ объявленном классе события, включая те,
# у которых производителя ещё нет: перечень, собранный из классов,
# встреченных в примерах, молчит ровно о том классе, которого в нём нет.
# Источник перечня — таблица `docs/architecture/contracts.md` §События
# («Событие | Производитель | Потребители»), то есть дом привязки класса к
# производителю.
#
# КОМАНДА ЧИТАЕТ ОБЕ СТОРОНЫ. Перечень выводится из таблицы, а объявления
# `CoreEventType` / `StrategyEventType` читаются ради СВЕРКИ: расхождение
# двух домов и есть частый дефект (`.claude/skills/closure-population.md`).
# Стороны неравноправны намеренно: таблица ШИРЕ перечней — класс
# объявляется ею раньше, чем появляется его производитель, — поэтому
# отсутствие значения перечня в таблице есть дефект, а отсутствие класса
# таблицы в перечне есть штатное «производителя ещё нет».
#
# LC_ALL=C.UTF-8 обязателен у grep -P на объявленной среде (дом ловушки —
# .claude/processes/roadmap-step-execution.md §«`grep -P` в этой среде
# требует `LC_ALL=C.UTF-8`»). Классы символов здесь ASCII-only намеренно:
# имена классов событий латиницей, а `\w` в PCRE кириллицу не берёт и на
# русском тексте молча дал бы ноль (та же §, клауза о кириллице).
#
# Кортеж одноключевой, поэтому разделителя не требуется; сверщик режет
# строку по табуляции (tools/population-derive-check.py, функция derive).
#
# КЛЮЧ --built ПЕЧАТАЕТ ВТОРУЮ СТОРОНУ, И ЭТО НЕ ВТОРОЙ ПРЕДМЕТ. Обе стороны
# команда и так читает — сверка выше на них и стои́т; ключ лишь ПОКАЗЫВАЕТ
# сверенное. Печатается оно в той же нотации, что и первая сторона
# (PascalCase, нормализация ниже), потому что разность двух множеств,
# напечатанных разными нотациями, машиной не берётся, и обещание «обе стороны
# разности читатель получает прогоном» на них не держится: считать пришлось бы
# руками (A11 DOCS_CHECK_4 шага 10 фазы 2). Разность непостроенных классов:
#   comm -23 <(bash tools/derive/event-class-manual-path.sh) \
#            <(bash tools/derive/event-class-manual-path.sh --built)
# Без ключа поведение прежнее — его зовёт tools/population-derive-check.py.
set -euo pipefail

BUILT_SIDE=0
if [ "${1:-}" = "--built" ]; then
  BUILT_SIDE=1
  shift
fi

DOC="${1:-docs/architecture/contracts.md}"
ENUM_DIR="${2:-services/common/model/domain/src/main/java/com/example/tradingbot/domain/event}"

if [ ! -f "$DOC" ]; then
  echo "ВЫВОД НЕ СОСТОЯЛСЯ: нет файла $DOC" >&2
  exit 2
fi

# Тело таблицы §События: от заголовка секции до строки, закрывающей таблицу.
table=$(LC_ALL=C.UTF-8 sed -n '/^## События/,/^Перечень открыт/p' "$DOC" | grep '^| `' || true)

if [ -z "$table" ]; then
  echo "ВЫВОД НЕ СОСТОЯЛСЯ: в $DOC не найдена таблица классов §События" >&2
  exit 2
fi

# Имена классов — обратными кавычками в первой колонке. Первая колонка
# отрезается по второму разделителю столбца: производитель и потребители
# несут собственные имена в кавычках (`trading-core`, `bff`), и без
# отрезания они попали бы в перечень классов.
classes=$(printf '%s\n' "$table" \
  | LC_ALL=C.UTF-8 awk -F'|' '{print $2}' \
  | LC_ALL=C.UTF-8 grep -oP '`\K[A-Z][A-Za-z]+(?=`)' \
  | sort -u)

if [ -z "$classes" ]; then
  echo "ВЫВОД НЕ СОСТОЯЛСЯ: в таблице $DOC не распознано ни одного имени класса" >&2
  exit 2
fi

# Вторая сторона: значения перечней общей библиотеки. Отсутствие каталога —
# не молчаливый пропуск, а отказ: сверка объявлена, и не проведя её, команда
# клейма о согласии двух домов не даёт.
if [ ! -d "$ENUM_DIR" ]; then
  echo "ВЫВОД НЕ СОСТОЯЛСЯ: нет каталога перечней $ENUM_DIR — сверка двух сторон не проведена" >&2
  exit 2
fi

enum_values=$(LC_ALL=C.UTF-8 grep -hoP '^\s{4}\K[A-Z][A-Z_]+(?=,?$)' \
    "$ENUM_DIR/CoreEventType.java" "$ENUM_DIR/StrategyEventType.java" 2>/dev/null | sort -u || true)

if [ -z "$enum_values" ]; then
  echo "ВЫВОД НЕ СОСТОЯЛСЯ: в $ENUM_DIR не распознано ни одного значения перечня" >&2
  exit 2
fi

# Имя значения перечня — SCREAMING_SNAKE, имя класса — PascalCase; сверка
# идёт по нормализованной форме. Она же — форма второй стороны при --built:
# нормализация одна на сверку и на печать, второй её копии не заводится.
missing=""
built_norm=""
for v in $enum_values; do
  norm=$(printf '%s' "$v" | LC_ALL=C.UTF-8 awk -F_ '{s="";for(i=1;i<=NF;i++){s=s toupper(substr($i,1,1)) tolower(substr($i,2))};print s}')
  built_norm="$built_norm$norm"$'\n'
  if ! printf '%s\n' "$classes" | grep -qx "$norm"; then
    missing="$missing $v"
  fi
done

if [ -n "$missing" ]; then
  echo "ВЫВОД НЕ СОСТОЯЛСЯ: значение перечня есть, строки таблицы нет:$missing" >&2
  exit 2
fi

if [ "$BUILT_SIDE" -eq 1 ]; then
  printf '%s' "$built_norm" | sort -u
  exit 0
fi

printf '%s\n' "$classes"
