#!/usr/bin/env bash
# Вывод членов популяции «рёбра статусной машины сделки».
#
# ПРЕДМЕТ ВЫВОДА. Пространство рёбер задаёт ПЕРЕЧЕНЬ СТАТУСОВ сделки —
# таблица §Статусы в docs/lifecycles/Deal.md, — а не список рёбер, который
# кто-то написал. Печатается полное произведение статусов без петель; какие
# из рёбер объявлены, а какие исключены инвариантом, решает сама популяция
# (объявленный недостижимым член предъявляет контрпример с названной
# причиной исключения).
#
# Печатает по строке на ребро: «из» TAB «в».
set -euo pipefail
statuses=$(sed -n '/^## Статусы/,/^## Группы/p' docs/lifecycles/Deal.md \
           | grep -oP '^\| `\K[A-Z_]+(?=`)')
for from in $statuses; do
  for to in $statuses; do
    [ "$from" = "$to" ] || printf '%s\t%s\n' "$from" "$to"
  done
done
