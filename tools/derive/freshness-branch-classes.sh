#!/usr/bin/env bash
# Вывод членов популяции «состояния, различимые дискриминатором ветви реакции
# на устаревание данных».
#
# ПРЕДМЕТ ВЫВОДА — ДОМ ОСЕЙ, а не формула спеки. Прежняя редакция читала
# выражение величины protectionBranch из той же спеки, которую популяция и
# проверяет: перечень выводился из проверяемого текста, и дефект области
# дискриминатора этой популяцией был непойма́ем по построению (B9
# DOCS_CHECK_34). Теперь оси берутся из таблицы дома
# docs/rules/market-data-freshness.md §«Оси дискриминатора ветви»; формула
# обязана стоять на них же, и расхождение видно сверкой перечней.
#
# Печатает по строке на член, значения осей через TAB, в порядке строк
# таблицы дома (он же — порядок ключей популяции).
set -euo pipefail
# LC_ALL=C.UTF-8 обязателен у grep -P на объявленной среде (дом ловушки —
# .claude/processes/roadmap-step-execution.md §«`grep -P` в этой среде
# требует `LC_ALL=C.UTF-8`»).
axes=$(sed -n '/^### Оси дискриминатора ветви/,/^Первые две оси/p' \
           docs/rules/market-data-freshness.md \
       | LC_ALL=C.UTF-8 grep -oP '^\| [^|]+ \| `\K[A-Za-z][A-Za-z0-9_]*(?=`)')
count=$(printf '%s\n' "$axes" | grep -c .)
if [ "$count" -eq 0 ]; then
  echo "оси не выведены из дома: таблица §«Оси дискриминатора ветви» не разобрана" >&2
  exit 2
fi
# Полное произведение по числу осей: перечень выводится из предмета, а не
# переписывается с кортежей наличных примеров.
total=$((1 << count))
for ((mask = 0; mask < total; mask++)); do
  line=""
  for ((bit = 0; bit < count; bit++)); do
    shifted=$(( (total / 2) >> bit ))
    if (( mask & shifted )); then value="false"; else value="true"; fi
    line+="${value}"
    if (( bit < count - 1 )); then line+=$'\t'; fi
  done
  printf '%s\n' "$line"
done
