#!/usr/bin/env bash
# Вывод членов популяции «значения причины закрытия сделки, резолвимые
# старшинством причин траншей».
#
# ПРЕДМЕТ ВЫВОДА — область значений резолва, а она складывается из двух
# частей, и обе выводятся, а не переписываются с наличных примеров:
#
#   1) закрытый упорядоченный перечень старшинства — пассаж §«Причина
#      закрытия — значение по маршруту» дока-дома docs/lifecycles/Deal.md;
#   2) ПУСТОЙ резолв — член по построению самой операции: резолв есть
#      минимум по множеству причин траншей, а у минимума по ПУСТОМУ
#      множеству значения нет. Пустота выводится из формы агрегата, а не из
#      того, что кто-то её упомянул; исключена она или достижима — вопрос
#      популяции, а не этой команды.
#
# Печатает по строке на значение: перечень старшинства, затем «null».
set -euo pipefail
sed -n '/^\*\*Старшинство причин — закрытый упорядоченный перечень\*\*/,/далёкий от плана/p' \
    docs/lifecycles/Deal.md \
  | tr '\n' ' ' \
  | grep -oP '`\K[A-Z_]+(?=`)'
echo null
