#!/usr/bin/env bash
# Члены популяции «ветвь разрыва непрерывности журнала» — полным
# произведением объявленных ветвей.
#
# ПРЕДМЕТ. Нижняя граница полноты выражает НАЧАЛО журнала, а не отсутствие
# дыры в середине. Ветвей, которыми дыра появляется, ровно две, и обе
# объявлены домом таблицей §«Позиция чтения и с какого момента журнал
# полон». Перечень выводится ПРОИЗВЕДЕНИЕМ этих ветвей, а не списком
# состояний, встреченных в примерах: список встреченного молчит ровно о том
# состоянии, которого в нём нет, — а обе ветви независимы, и затянувшаяся
# остановка приёма приводит ко второй, не отменяя первой.
#
# LC_ALL=C.UTF-8 обязателен у grep -P на объявленной среде (дом ловушки —
# .claude/processes/roadmap-step-execution.md §«`grep -P` в этой среде
# требует `LC_ALL=C.UTF-8`»). Коды ветвей латиницей намеренно: `\w` в PCRE
# кириллицу не берёт, и шаблон по русскому слову молча дал бы ноль.
#
# Разделитель кортежа — ТАБУЛЯЦИЯ: сверщик режет строку по ней
# (tools/population-derive-check.py, функция derive).
set -euo pipefail

DOC="${1:-docs/models/domain/other/AuditRecord.md}"

if [ ! -f "$DOC" ]; then
  echo "ВЫВОД НЕ СОСТОЯЛСЯ: нет файла $DOC" >&2
  exit 2
fi

# Коды ветвей — из первой колонки таблицы ветвей разрыва. Строка таблицы
# опознаётся по маркеру-коду в обратных кавычках: RECEPTION_HALTED и
# LAG_EXCEEDED_RETENTION. Первая колонка отрезается по разделителю столбца,
# чтобы прочие кавычки строки в перечень не попали.
# `|| true` НЕСУЩИЙ, а не косметика: при `set -euo pipefail` пустая выдача
# любого звена конвейера (нет секции, нет строк таблицы, нет кодов) есть
# ненулевой код `grep`, и скрипт умер бы ЗДЕСЬ — кодом 1, то есть «есть
# расхождения», молча, не дойдя до собственной охраны ниже. Отличие кода 1
# от кода 2 несущее: сверщик читает 2 как «замер не проводился» и изолирует
# популяцию, а 1 — как расхождение, и уводит в отказ ВЕСЬ корпусный прогон.
branches=$(LC_ALL=C.UTF-8 sed -n '/^## Позиция чтения/,/^## /p' "$DOC" \
  | LC_ALL=C.UTF-8 grep '^| `' \
  | LC_ALL=C.UTF-8 awk -F'|' '{print $2}' \
  | LC_ALL=C.UTF-8 grep -oP '`\K[A-Z][A-Z_]+(?=`)' \
  | sort -u || true)

count=$(printf '%s\n' "$branches" | grep -c . || true)

if [ "$count" -ne 2 ]; then
  echo "ВЫВОД НЕ СОСТОЯЛСЯ: в $DOC ожидались ДВЕ ветви разрыва, найдено: $count" >&2
  exit 2
fi

# Третья ось выводится из того же дока: пассаж, объявляющий свежесть строки
# состояния приёма третьим операндом предиката. Не найден — вывод не
# состоялся: ось, взятая из головы сверщика, а не из предмета, есть ровно
# тот самореферентный перечень, против которого команда и заведена.
freshness=$(LC_ALL=C.UTF-8 grep -c 'Третий операнд предиката' "$DOC" || true)

if [ "$freshness" -lt 1 ]; then
  echo "ВЫВОД НЕ СОСТОЯЛСЯ: в $DOC не объявлен третий операнд предиката (свежесть строки состояния приёма)" >&2
  exit 2
fi

# Произведение трёх булевых осей. Порядок ключей — тот же, что у популяции:
# receptionHalted, lagExceededRetention, receptionStateFresh. Третья ось
# перечисляется от true: свежая строка — штатное состояние измерителя.
for a in false true; do
  for b in false true; do
    for c in true false; do
      printf '%s\t%s\t%s\n' "$a" "$b" "$c"
    done
  done
done
