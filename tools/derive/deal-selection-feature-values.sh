#!/usr/bin/env bash
# Члены популяции «значения признака отбора закрытой сделки» — из объявления
# перечня общей библиотеки, а не из значений, встреченных в примерах.
#
# ПРЕДМЕТ. Правило «каждое значение признака отбора отнесено — счётчиком,
# выводимым остатком либо объявленной недостижимостью» обязано иметь исход на
# КАЖДОМ значении перечня, включая те, у которых счётчика нет: перечень,
# собранный из значений, встреченных в примерах, молчит ровно о том значении,
# которого в нём нет. Источник перечня — объявление enum'а в общей доменной
# модели, то есть дом самого признака.
#
# КОМАНДА ЧИТАЕТ ОБЕ СТОРОНЫ. Перечень выводится из объявления перечня, а
# описание одноимённого операнда спеки читается ради СВЕРКИ: операнд называет
# тип и его значения прозой, и расхождение двух домов — частый дефект
# (.claude/skills/closure-population.md). Стороны здесь равноправны: операнд
# обязан называть ровно те значения, которые объявлены перечнем, — поэтому
# расхождение в любую сторону есть отказ вывода, а не штатное «ещё не
# построено».
#
# LC_ALL=C.UTF-8 обязателен у grep -P на объявленной среде (дом ловушки —
# .claude/processes/roadmap-step-execution.md §«`grep -P` в этой среде
# требует `LC_ALL=C.UTF-8`»). Классы символов ASCII-only намеренно: значения
# перечня латиницей, а `\w` в PCRE кириллицу не берёт и на русском тексте
# молча дал бы ноль (та же §, клауза о кириллице).
#
# Кортеж одноключевой, поэтому разделителя не требуется; сверщик режет строку
# по табуляции (tools/population-derive-check.py, функция derive).
#
# Запуск:  bash tools/derive/deal-selection-feature-values.sh <ИмяПеречня>
set -euo pipefail

ENUM="${1:-}"
SRC="${2:-libs/domain-model/src/main/java/com/example/tradingbot/domain/model/aggregate/deal/Deal.java}"
SPEC="${3:-docs/spec/statistics-aggregates.json}"

if [ -z "$ENUM" ]; then
  echo "ВЫВОД НЕ СОСТОЯЛСЯ: не назван перечень (первым аргументом)" >&2
  exit 2
fi

if [ ! -f "$SRC" ]; then
  echo "ВЫВОД НЕ СОСТОЯЛСЯ: нет файла объявления перечня $SRC" >&2
  exit 2
fi

# Тело перечня: от строки объявления до первой закрывающей скобки его уровня.
declared=$(LC_ALL=C.UTF-8 awk -v e="$ENUM" '
  $0 ~ ("enum[ \t]+" e "[ \t]*\\{") { inside = 1; next }
  inside && /^[ \t]*\}/ { exit }
  inside && match($0, /^[ \t]*[A-Z][A-Z_]+[,;]?[ \t]*$/) {
    gsub(/[ \t,;]/, "", $0); print
  }
' "$SRC")

if [ -z "$declared" ]; then
  echo "ВЫВОД НЕ СОСТОЯЛСЯ: в $SRC не найдено значений перечня $ENUM" >&2
  exit 2
fi

# Вторая сторона: проза операнда спеки, называющая тип и его значения.
if [ ! -f "$SPEC" ]; then
  echo "ВЫВОД НЕ СОСТОЯЛСЯ: нет спеки $SPEC — сверка двух сторон не проведена" >&2
  exit 2
fi

prose=$(LC_ALL=C.UTF-8 grep -m1 -oP "тип ${ENUM}: \K[A-Z_, ]+" "$SPEC" || true)

if [ -z "$prose" ]; then
  echo "ВЫВОД НЕ СОСТОЯЛСЯ: в $SPEC нет операнда, называющего тип $ENUM" >&2
  exit 2
fi

prose_values=$(printf '%s' "$prose" | tr ',' '\n' | tr -d ' ' | grep -v '^$' | sort -u)
declared_sorted=$(printf '%s\n' "$declared" | sort -u)

if [ "$prose_values" != "$declared_sorted" ]; then
  echo "ВЫВОД НЕ СОСТОЯЛСЯ: перечень $ENUM и проза операнда спеки расходятся" >&2
  echo "  перечень: $(printf '%s' "$declared_sorted" | tr '\n' ' ')" >&2
  echo "  спека:    $(printf '%s' "$prose_values" | tr '\n' ' ')" >&2
  exit 2
fi

printf '%s\n' "$declared"
