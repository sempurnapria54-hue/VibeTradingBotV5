#!/usr/bin/env bash
# Вывод членов популяции «состояния допустимости шага лестницы сопровождения».
#
# ПРЕДМЕТ ВЫВОДА. Оси правила объявлены таблицей дома
# docs/rules/strategy-step-once-per-episode.md §«Оси допустимости шага»;
# перечень значений оси «состояние пакета» — таблицей §«Пакет исполняется по
# действию за проход». Прежняя редакция знала ДВЕ оси при трёх конъюнктах
# правила: гейт повтора внутри члена не различался, и состояния «шаг ждёт
# снятия ступени» и «шаг допустим» лежали в одном классе (B4 DOCS_CHECK_34).
#
# Перечень — полное произведение осей: класс, которого в переборе нет,
# молчаливо считался бы невозможным.
#
# Печатает по строке на член: условие TAB класс пакета TAB гейт повтора.
set -euo pipefail
# LC_ALL=C.UTF-8 обязателен у grep -P на объявленной среде (дом ловушки —
# .claude/processes/roadmap-step-execution.md §«`grep -P` в этой среде
# требует `LC_ALL=C.UTF-8`»).
home=docs/rules/strategy-step-once-per-episode.md
classes=$(sed -n '/^### Пакет исполняется по действию за проход/,/^\*\*Применённым шаг делает/p' "$home" \
          | LC_ALL=C.UTF-8 grep -oP '^\| `\K[A-Z_А-Я_]+(?=`)')
axes=$(sed -n '/^### Оси допустимости шага/,/^\*\*Осей три/p' "$home" \
       | LC_ALL=C.UTF-8 grep -oP '^\| [^|]+ \| `\K[A-Za-z][A-Za-z0-9_]*(?=`)')
if [ -z "$classes" ] || [ -z "$axes" ]; then
  echo "оси не выведены из дома: таблицы §«Оси допустимости шага» / §«Пакет исполняется…» не разобраны" >&2
  exit 2
fi
for condition in true false; do
  for class in $classes; do
    for gated in true false; do
      printf '%s\t%s\t%s\n' "$condition" "$class" "$gated"
    done
  done
done
