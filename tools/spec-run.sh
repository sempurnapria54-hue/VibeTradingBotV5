#!/usr/bin/env bash
# Прогон исполнимых спецификаций против их примеров.
#
# ПРЕДМЕТ. Сходятся ли объявленные величины с ожиданиями примеров И покрыты
# ли примерами объявленные ПОПУЛЯЦИИ (ключ populations: перечни состояний, на
# которых правило спеки обязано выполняться). Что примеры при этом ЧТО-ТО
# ПРОВЕРЯЮТ — предмет соседней команды (tools/spec-mutation-check.sh); оси
# самой популяции доказаны батареей той же соседней команды (18-22).
#
# Штатно то же самое делает mvn -Dtest=SpecRunnerTest test; здесь —
# автономный прогон без Maven.
#
# Запуск (из корня репозитория):  bash tools/spec-run.sh
# Каталог переопределяется переменной SPEC_DIR (по умолчанию docs/spec).
#
# Код возврата: 0 — примеры сошлись; 1 — есть расхождения; 2 — ПРОГОН НЕ
# СОСТОЯЛСЯ (нет каталога, нет спецификаций, файл не разобран, состояние
# примера не собрано, раннер не собрался). Третий код заведён затем, чтобы
# «прогонять было нечего» не читалось как «расхождений нет».
set -euo pipefail

# shellcheck source=tools/spec-runner-env.sh
source "$(dirname "$0")/spec-runner-env.sh"

cd "$SPEC_ROOT"
exec "${JAVA[@]}" com.example.tradingbot.spec.Spec "${SPEC_DIR:-docs/spec}"
