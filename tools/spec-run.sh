#!/usr/bin/env bash
# Прогон исполнимых спецификаций против их примеров.
#
# ПРЕДМЕТ. Сходятся ли объявленные величины с ожиданиями примеров И покрыты
# ли примерами объявленные ПОПУЛЯЦИИ (ключ populations: перечни состояний, на
# которых правило спеки обязано выполняться), ПЛЮС препятствия базового гейта
# (дубль ключа строгим разбором, спека в подкаталоге, структурные дефекты) —
# прежде они исполнялись только мутационной командой, и правка примера с
# таким дефектом проходила штатный прогон зелёным (E4 DOCS_CHECK_33). Что
# примеры при этом ЧТО-ТО ПРОВЕРЯЮТ — предмет соседней команды
# (tools/spec-mutation-check.sh); популяционный слой доказан батареей той
# же соседней команды: оси 18-24 (член/пример/перечень/ключи/where) и
# 25-32 (rule/derive/excludes).
#
# Штатно то же самое делает mvn -Dtest=SpecRunnerTest test; здесь —
# автономный прогон без Maven.
#
# Запуск (из корня репозитория):  bash tools/spec-run.sh
# Каталог переопределяется переменной SPEC_DIR (по умолчанию docs/spec).
#
# Код возврата: 0 — примеры сошлись; 1 — есть расхождения; 2 — ПРОГОН НЕ
# СОСТОЯЛСЯ (нет каталога, нет спецификаций, файл не разобран, состояние
# примера не собрано, раннер не собрался, JVM не запустила раннер). Третий
# код заведён затем, чтобы «прогонять было нечего» не читалось как
# «расхождений нет»; незапуск JVM («Could not find or load main class»)
# маппится в него же — прежде он приезжал кодом 1 «есть расхождения»
# (E1 `DOCS_CHECK_33`).
set -euo pipefail

# shellcheck source=tools/spec-runner-env.sh
source "$(dirname "$0")/spec-runner-env.sh"

cd "$SPEC_ROOT"
err_log="$SPEC_CLASSES/stderr.log"
set +e
"${JAVA[@]}" com.example.tradingbot.spec.Spec "${SPEC_DIR:-docs/spec}" 2>"$err_log"
rc=$?
set -e
cat "$err_log" >&2
if [ "$rc" -ne 0 ] && grep -q 'Could not find or load main class' "$err_log"; then
  echo "ПРОГОН НЕ СОСТОЯЛСЯ: JVM не запустила раннер (системный отказ, не расхождение)" >&2
  exit 2
fi
exit "$rc"
