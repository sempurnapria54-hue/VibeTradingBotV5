package com.example.tradingbot.domain.event;

/**
 * Содержимое события «ступень поднята»: радиус, ступень, машинный код
 * причины и актор — ровно то, чем в данных различаются основания одной и
 * той же ступени.
 *
 * <p><b>Актор едет содержимым, потому что у класса есть ручная тропа:</b>
 * держатель ставит ту же ступень тем же механизмом
 * (docs/rules/manual-halt.md, docs/spec/event-actor-presence.json). Область
 * значений — та же, что у полей аудита сущности: <b>класс</b>, а не
 * идентификатор пользователя (docs/models/domain/other/Auditable.md
 * §«Область значений актора»); второй области не заводится.
 *
 * <p><b>Актора и код тропы не смешивать.</b> Разрез отчёта по ручной тропе
 * идёт по КОДУ: у джобы, запущенной ручным триггером, актор равен
 * принципалу, и автоматическая остановка, найденная в ручном прогоне,
 * попала бы в число ручных (docs/rules/statistics-aggregates.md §«Разрез
 * зовётся по тропе и различает её КОДОМ, а не актором строки»).
 *
 * <p><b>Ступень содержимого — ступень СИГНАЛА, а не статус объекта
 * радиуса.</b> Значение приезжает именем перечня {@code HoldRung} — того,
 * что отвечает на «судьба принятого риска»; область значений домовая
 * (docs/components/models/HoldSignal.md §«Енум HoldRung»), и здесь она не
 * переписывается. Различение несущее: словом «ступень» корпус называет и
 * лестницы объектов радиуса, а подставленное оттуда значение потребитель
 * прочитал бы МОЛЧА — его предикат не совпал бы ни с одной строкой, и ноль
 * от «таких остановок не было» не отличается ничем.
 *
 * @param exchangeAccountInternalId биржевой счёт радиуса
 * @param instrumentInternalId      инструмент радиуса; пусто у счётного
 *                                  сигнала
 * @param scope                     радиус блокировки — имя значения
 *                                  {@code HoldScope}; область значений
 *                                  домовая
 *                                  (docs/components/models/HoldSignal.md),
 *                                  и здесь она не переписывается
 * @param rung                      поднятая ступень — имя значения
 *                                  {@code HoldRung}
 * @param code                      машинный код причины
 * @param actor                     кто инициировал ход: имя предъявленного
 *                                  принципала либо класс собственного
 *                                  прохода
 */
public record HoldRaisedContent(String exchangeAccountInternalId,
                                String instrumentInternalId,
                                String scope,
                                String rung,
                                String code,
                                String actor) {
}
