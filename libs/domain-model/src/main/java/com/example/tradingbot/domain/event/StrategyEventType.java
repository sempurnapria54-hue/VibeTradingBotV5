package com.example.tradingbot.domain.event;

/**
 * Классы событий, производимые владельцем определений
 * (docs/architecture/contracts.md §«У каждого класса события назван
 * писатель, и он же писатель решения»).
 *
 * <p><b>Все они — события-ПРОИСШЕСТВИЯ</b>, поэтому род темы один:
 * {@code facts}. Смешивать роды в одной теме нельзя — компакция темы
 * фактов теряет факты.
 *
 * <p><b>Писатель у всех трёх один и тот же — код перехода статуса</b>, и
 * момент один и тот же — транзакция этого перехода.
 *
 * <p>{@code BacktestCompleted} здесь нет намеренно: его предмет приезжает
 * фазой 4, и класс события заводит шаг его производителя.
 *
 * <p><b>Перечень живёт в общем артефакте, а не у производителя,</b>
 * потому что у этих классов есть ЧИТАТЕЛЬ — торговое ядро; форма,
 * известная только писателю, разошлась бы с чтением первой же правкой
 * (docs/architecture/contracts.md §«Формы событий и запросов»).
 */
public enum StrategyEventType {

    /** Определение активировано; содержимое несёт неизменяемый снимок дерева. */
    STRATEGY_ACTIVATED,

    /** Определение выведено из активных: новые сделки по нему не создаются. */
    STRATEGY_DEACTIVATED,

    /** Определение логически удалено: открытые сделки уводятся в координированный выход. */
    STRATEGY_DELETED
}
