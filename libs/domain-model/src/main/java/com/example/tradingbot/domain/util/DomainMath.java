package com.example.tradingbot.domain.util;

import java.math.MathContext;
import java.math.RoundingMode;
import lombok.experimental.UtilityClass;

/**
 * Арифметический контекст доменных расчётов.
 *
 * <p><b>Почему в общей библиотеке, а не в утилитах сервиса.</b> Точность
 * промежуточных делений — свойство доменной арифметики, а не сервиса,
 * который её выполняет: одно и то же число риска считают ядро (живая
 * сделка), движок стратегий (бэктест и теневой режим) и валидатор
 * стратегии. Разный контекст округления у них означал бы, что гейт
 * проверяет не то, что торгует.
 *
 * <p>Дом правила — {@code docs/rules/decimal-arithmetic.md}: там сказано,
 * почему точность именно такая и почему итоговое округление этим
 * контекстом не выполняется.
 *
 * <p>Прежде константа жила в утилитах донора, и доменная модель
 * {@code MarketPriceData} импортировала её оттуда — то есть форма
 * зависела от пакета, который в общий артефакт не входит. Переезд
 * обнаружен сборкой библиотеки, а не чтением.
 */
@UtilityClass
public class DomainMath {

    /**
     * Контекст округления промежуточных делений {@code BigDecimal}
     * (precision/HALF_UP).
     *
     * <p>Точность 34 — не калибровка, а запас: она заведомо больше
     * значимых разрядов любой биржевой величины, и промежуточное деление
     * не должно вносить ошибку, различимую в итоговом округлении по шагу
     * лота или тика. Округление итога — отдельная операция со своим
     * правилом (docs/components/SizeCalculator.md).
     */
    public static final MathContext CONTEXT = new MathContext(34, RoundingMode.HALF_UP);
}
