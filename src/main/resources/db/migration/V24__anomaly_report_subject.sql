-- Предмет журнального отчёта: сущность, о которой он.
--
-- У отчёта БЕЗ блокировки состояние держится не на объекте радиуса, а на
-- самой сущности — заявке либо algo-заявке, — поэтому ключ дедупа у него
-- четвёрка «объект радиуса + сущность-предмет + code + severity»
-- (docs/models/domain/other/AnomalyReport.md §«Ключ дедупа у STATE»).
-- Без этой колонки два разных расхождения учёта по одному инструменту
-- схлопывались бы в одну строку.
--
-- Колонка nullable: у отчёта С блокировкой предмета нет — его состояние
-- и есть стоящая ступень объекта радиуса.
alter table anomaly_reports add column subject_external_id varchar(64);

-- Счётчик подряд идущих НЕПОЛНЫХ проходов детекции.
--
-- Предел слепоты считается подряд идущими проходами, и носитель у счёта
-- durable по той же причине, что у гистерезиса: память инстанса
-- обнуляется ровно в аварии, когда рестарты и происходят. Образец —
-- consecutive_loss_count на этой же строке: тот же класс счётчика с тем
-- же радиусом (docs/components/AnomalyJob.md §«Гейт полноты среза»).
alter table exchanges add column blind_pass_count integer not null default 0;
