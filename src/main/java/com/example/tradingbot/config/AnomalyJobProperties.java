package com.example.tradingbot.config;

import java.time.Duration;
import lombok.Getter;
import lombok.Setter;
import org.springframework.boot.context.properties.ConfigurationProperties;

/**
 * Конфигурация детектора аномалий (AnomalyJob): включение, окно
 * подтверждения гистерезиса и предел слепоты. CRON читается
 * {@code @Scheduled} напрямую из {@code anomaly-job.cron}.
 *
 * <p><b>Числа провизорные и назначены владельцем как КАЛИБРОВКА
 * НАБЛЮДЕНИЯ, не как риск-аппетит:</b> их ошибка меряется парой «ложное
 * срабатывание против пропуска», а не размером потери. Якорь пересмотра —
 * первый период прогонов контура (.claude/work/backlog.md §«Гистерезис
 * детекторов аномалий — калибровка по первому периоду прогонов»).
 */
@Getter
@Setter
@ConfigurationProperties(prefix = "anomaly-job")
public class AnomalyJobProperties {

    /** Выключатель джоба: false — ни таймерный, ни ручной тик ничего не делают. */
    private Boolean enabled = true;

    /**
     * Окно, в котором наблюдательная строка прошлого тика считается
     * подтверждением. Берётся с запасом к такту (тик — минута): дрейф
     * расписания не должен читаться как «признак пропал».
     */
    private Duration observationWindow = Duration.ofMinutes(3);

    /**
     * Наименьший возраст наблюдательной строки, при котором она читается
     * подтверждением. Верхняя граница окна: строка, заведённая секундами
     * раньше — тем же или смежным проходом, — гонку чтения длиной в такт
     * не пережила, и подтверждением служить не может.
     */
    private Duration confirmationMinAge = Duration.ofSeconds(30);

    /**
     * Сколько подряд идущих НЕПОЛНЫХ проходов терпится, прежде чем
     * поднимается мягкая биржевая ступень. Единица сделала бы одиночный
     * упор в лимит частоты основанием остановки набора со снятием
     * вручную; цена трёх — три минуты ненаблюдаемости при работающей
     * биржевой защите (docs/components/AnomalyJob.md §«Гейт полноты среза»).
     */
    private Integer blindPassLimit = 3;
}
