package com.example.tradingbot.domain.security;

import static org.apache.commons.lang3.StringUtils.isBlank;
import static org.apache.commons.lang3.StringUtils.isNotBlank;

import com.example.tradingbot.domain.model.Auditable;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

/**
 * Журнальная строка отвергнутого по правам вызова к нашей поверхности:
 * попытка обратиться к закрытой точке, у которой принципал не предъявлен либо
 * предъявленный не принят, — а также попытка под принятым принципалом,
 * которому операция не разрешена
 * (docs/models/domain/other/AccessDenial.md).
 *
 * <p><b>Носитель наблюдаемости</b> (docs/concept.md, П3): персистентная
 * запись, по которой держатель видит интерес к поверхности. Лог этой роли не
 * исполняет — он не запрашивается, не агрегируется и не переживает ротацию.
 *
 * <p><b>Природа факта — происшествие:</b> у каждой попытки свой момент,
 * дедупа нет, счётность обязательна. Схлопывание попыток занижало бы частоту
 * — единственную величину, ради которой строка и заводится.
 *
 * <p><b>Отчётом об аномалии факт не выражается</b> ни структурно (у отчёта
 * биржа обязательна), ни по назначению (там расхождение с биржевым
 * состоянием, которого здесь не происходит).
 */
@Getter
@Setter
@NoArgsConstructor
public class AccessDenial extends Auditable {

    /** Внутренний идентификатор строки. */
    private Long id;

    /** Межсервисный идентификатор строки. */
    private String internalId;

    /** Поверхность, к которой обратились: HTTP-метод и путь. */
    private String surface;

    /** Класс отказа. */
    private Outcome outcome;

    /**
     * <b>Принятый</b> принципал — тот, чью личность контур удостоверил.
     * Пусто ⟺ {@link Outcome#PRINCIPAL_ABSENT}; пустота покрывает обе тропы —
     * принципал не предъявлен и предъявленный не принят. Заявленное, но не
     * удостоверенное имя сюда не пишется: это была бы запись непроверенного
     * как факта.
     */
    private String principal;

    /**
     * Согласованы ли класс отказа и принципал. Инвариант модели: пустота
     * {@link #principal} и {@link Outcome#PRINCIPAL_ABSENT} — одно и то же
     * состояние, выраженное дважды, и расхождение между ними означает дефект
     * писателя.
     */
    public Boolean isConsistent() {
        return Outcome.PRINCIPAL_ABSENT.equals(outcome) ? isBlank(principal) : isNotBlank(principal);
    }

    /** Класс отказа: чем именно вызов отвергнут. */
    public enum Outcome {

        /**
         * Принципал не предъявлен <b>либо предъявленный не принят</b>.
         * Разделяет значения то, известен ли субъект: у непринятых кредов он
         * неизвестен так же, как у непредъявленных, и третье значение
         * различало бы то, чего мы не знаем.
         */
        PRINCIPAL_ABSENT,

        /**
         * Принципал предъявлен и принят, но операция ему не разрешена.
         * <b>Не достижим при посылке фазы 1</b> «к поверхности обращается один
         * субъект» (docs/rules/api-access-policy.md): право у единственного
         * принципала на всё. Значение заведено вместе с первым, потому что оно
         * часть контракта внешней поверхности — слить исходы дешевле сейчас и
         * дороже потом; писатель у него назван и достижим, недостижима сегодня
         * сама популяция.
         */
        OPERATION_FORBIDDEN
    }
}
