package com.example.tradingbot.domain.deal.action;

/**
 * Готовность действия начать исполнение — ответ per-type исполнителя ДО
 * того, как заведена строка исполнения. Три исхода разведены потому, что
 * «подожди» и «делать нечего» ведут пакет шага в разные стороны:
 * первое его останавливает, второе пропускает действие и берёт следующее.
 *
 * <p>Гейт стои́т до строки намеренно: действие, чьё предусловие не
 * выполнено, исполнения НЕ начинает — строка не заводится, бюджет попыток
 * не расходуется, шаг остаётся неисполненным до следующего прохода
 * (docs/components/StrategyActionOrchestrator.md §«Порядок выбора
 * действия», docs/rules/live-risk-protection.md).
 */
public enum ActionReadiness {

    /** Предусловия выполнены: строку можно заводить, действие — планировать. */
    READY,

    /**
     * Предусловие не выполнено, но надобность жива — ждём следующего
     * прохода. Пакет шага дальше не идёт: обгонять отложенное действие
     * значило бы менять объявленный порядок пакета.
     */
    DEFERRED,

    /**
     * Действие неактуально: предмета у него больше нет (объявленной цели
     * снятия среди живых защит транша не осталось). Пакет берёт следующее
     * действие — ждать здесь нечего.
     */
    IRRELEVANT
}
