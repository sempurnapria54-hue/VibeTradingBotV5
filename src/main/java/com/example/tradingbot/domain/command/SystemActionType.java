package com.example.tradingbot.domain.command;

/**
 * Тип системного действия сделки — действия, у которого нет узла
 * стратегии, но есть своя строка исполнения: бюджет попыток, ревизия
 * живых исполнений и стадия, выводимая из подтверждённого факта.
 *
 * <p><b>Маркер уровня — суффикс {@code _ACTION}</b>, тот же, что у
 * {@link com.example.tradingbot.domain.model.aggregate.strategy.action.StrategyActionType}:
 * действие есть уровень абстракции НАД командой
 * ({@link ServiceCommandType}), и уровень читается по хвосту имени
 * (.claude/rules/naming.md §«Разведение уровней абстракции»).
 *
 * <p>См. docs/models/domain/other/DealActionState.md §Енумы,
 * docs/components/SystemActionExecutor.md.
 */
public enum SystemActionType {

    /**
     * Добыча свежих фактов с биржи: позиция, заявки, условные заявки,
     * баланс, движения средств. Дочистка звеном не является — отмены и
     * закрытие позиции эмитируются обработчиком напрямую, без анкера.
     */
    REFRESH_DEAL_CONTEXT_ACTION,

    /**
     * Консолидация результата входа ТРАНША; завершение пишет статус
     * подтверждённого входа транша той же транзакцией. Единственное
     * системное действие с непустым траншем.
     */
    FINALIZE_DEAL_ENTRY_ACTION,

    /** Число и чистый терминал: расчёт результата, затем терминальное ребро. */
    FINALIZE_DEAL_EXIT_ACTION,

    /**
     * Аварийная тропа: вход в ошибочное состояние и аварийный терминал —
     * два отдельных исполнения одного типа.
     */
    FINALIZE_DEAL_ERROR_ACTION
}
