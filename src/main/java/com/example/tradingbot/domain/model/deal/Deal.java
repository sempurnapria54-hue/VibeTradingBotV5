package com.example.tradingbot.domain.model.deal;

import com.example.tradingbot.domain.model.Auditable;
import com.example.tradingbot.domain.model.Order;
import com.example.tradingbot.domain.model.algo_order.AlgoOrder;
import com.example.tradingbot.domain.model.position.Position;
import lombok.Getter;
import lombok.Setter;

import java.math.BigDecimal;
import java.util.List;

@Getter
@Setter
public class Deal extends Auditable {

    /**
     * Внутренний идентификатор.
     */
    private Long id;

    /**
     * Межсервисный идентификатор.
     */
    private String internalId;

    /**
     * Идентификатор инструмента.
     */
    private Long instrumentId;

    /**
     * Текущий внутренний статус.
     */
    private Status status;

    /**
     * Причина закрытия.
     */
    private CloseReason closeReason;

    /**
     * Сколько принесла сделка. Если убыток, то отрицательное число.
     */
    private BigDecimal resultProfit;

    /**
     * Список ордеров.
     */
    private List<Order> orders;

    /**
     * Список алго-ордеров.
     */
    private List<AlgoOrder> algoOrders;

    /**
     * Список позиций.
     */
    private List<Position> positions;

    public enum Status {

        /**
         * Предварительная проверка перед входом в сделку.
         * <p>
         * В этом состоянии система:
         * - проверяет, что по инструменту нет открытой позиции;
         * - проверяет, что нет конфликтующих pending-ордеров;
         * - проверяет баланс/маржу и рассчитывает размер входа;
         * - подготавливает параметры attached Stop-Loss.
         * <p>
         * Переходы:
         * - в ENTRY_SUBMITTED, если вход разрешён;
         * - в CLOSED, если сделка отменена как "не торгуем";
         * - в ERROR, если обнаружена критическая аномалия.
         */
        PRECHECK,

        /**
         * Обычный entry-ордер отправлен на биржу.
         * <p>
         * В этом состоянии:
         * - бирже уже отправлен order на вход;
         * - вместе с ним отправлен attached Stop-Loss как страховка;
         * - в БД уже сохранены ordId/clOrdId и статус "ордер в процессе".
         * <p>
         * Переходы:
         * - в ENTRY_FINALIZED, когда ордер принят и его можно финализировать;
         * - в ERROR, если биржа отклонила ордер или возникла критическая ошибка.
         */
        ENTRY_SUBMITTED,

        /**
         * Финализация входа.
         * <p>
         * Это составное состояние, в котором должны быть подтверждены сразу три факта:
         * 1) entry-ордер дошёл до финального состояния;
         * 2) позиция реально появилась на бирже;
         * 3) attached Stop-Loss существует и подтверждён.
         * <p>
         * Важно:
         * - после этого состояния источником правды становится уже Position;
         * - сам entry-ордер остаётся исторической сущностью.
         * <p>
         * Переходы:
         * - в PROTECTION_SWITCHED, если можно ставить основную защиту;
         * - в ERROR, если ордер/позиция/защита не удаётся согласовать.
         */
        ENTRY_FINALIZED,

        /**
         * Переключение защиты.
         * <p>
         * Цель состояния:
         * - создать основные algo-ордера защиты (SL / TP / trailing);
         * - убедиться, что они реально активны;
         * - только после этого снять attached Stop-Loss.
         * <p>
         * Инвариант на выходе:
         * - основная защита активна;
         * - attached Stop-Loss снят;
         * - "окна без защиты" не было.
         * <p>
         * Переходы:
         * - в MANAGING, если защита успешно переключена;
         * - в ERROR, если не удалось гарантировать наличие защиты.
         */
        PROTECTION_SWITCHED,

        /**
         * Сопровождение открытой позиции.
         * <p>
         * В этом состоянии система:
         * - мониторит позицию;
         * - контролирует, что основной SL остаётся активным;
         * - по стратегии двигает защиту (например, trailing / breakeven);
         * - отслеживает факт закрытия позиции.
         * <p>
         * Переходы:
         * - в EXIT_PENDING, если позиция закрылась;
         * - в ERROR, если нарушены торговые инварианты
         * (например, позиция есть, а защиты нет).
         */
        MANAGING,

        /**
         * Финализация закрытия сделки.
         * <p>
         * Позиция на бирже уже закрыта, а система:
         * - снимает оставшиеся хвосты (pending orders / pending algos);
         * - собирает историю исполнений и историю algo-ордеров;
         * - определяет финальную причину закрытия сделки;
         * - завершает сделку для аналитики.
         * <p>
         * Переходы:
         * - в CLOSED, когда картина полностью восстановлена;
         * - в ERROR, если финализацию закрытия выполнить не удалось безопасно.
         */
        EXIT_PENDING,

        /**
         * Сделка полностью завершена.
         * <p>
         * Это терминальный "успешно завершённый" статус.
         * <p>
         * Инварианты:
         * - по инструменту нет позиции;
         * - нет pending-ордеров и pending algo-ордеров, относящихся к сделке;
         * - причина закрытия сделки определена и сохранена.
         */
        CLOSED,

        /**
         * Терминальный аварийный статус.
         * <p>
         * Это не "обычная ошибка", а специальный режим kill-switch по инструменту.
         * <p>
         * Попадание в ERROR означает:
         * - торговые инварианты нарушены, и продолжать сделку небезопасно;
         * - либо job реконсиляции обнаружила критическую аномалию по сущностям;
         * - система обязана закрыть риск по инструменту на бирже.
         * <p>
         * При обработке ERROR система должна:
         * - отменить все pending обычные ордера по инструменту;
         * - отменить все pending algo-ордера по инструменту;
         * - закрыть позицию, если она существует;
         * - убедиться, что инструмент "чист".
         * <p>
         * Важно:
         * - ERROR терминален;
         * - из него нет переходов в другие статусы.
         */
        ERROR
    }

    public enum CloseReason {

        /**
         * Сработал stop-loss (обычный или algo SL).
         */
        STOP_LOSS,

        /**
         * Сработал take-profit (если используешь TP).
         */
        TAKE_PROFIT,

        /**
         * Закрыли по сигналу стратегии (ручной выход по правилам, не SL/TP).
         */
        STRATEGY_EXIT,

        /**
         * Вышли по таймауту/времени удержания (time stop).
         */
        TIME_STOP,

        /**
         * Закрыли из-за риска/ограничений (маржа, плечо, лимиты, max positions, emergency risk rule).
         */
        RISK_CONTROL,

        /**
         * Экстренная остановка (kill switch): закрыли всё и/или отменили ордера.
         */
        EMERGENCY_STOP,

        /**
         * Ручное вмешательство пользователя (закрыто в UI/вручную через API).
         */
        MANUAL,

        /**
         * Закрытие в результате реконсиляции/восстановления после рестарта
         * (например, бот обнаружил, что позиции уже нет, и завершил сделку).
         */
        RECONCILIATION,

        /**
         * Невозможно обеспечить защиту (не удалось выставить/подтвердить SL),
         * поэтому позицию закрыли принудительно (fail-safe).
         */
        PROTECTION_FAILED,

        /**
         * Биржа ликвидировала позицию.
         */
        LIQUIDATION
    }

    public void toError(CloseReason reason) {
        setStatus(Status.ERROR);
        setCloseReason(reason);
    }
}
