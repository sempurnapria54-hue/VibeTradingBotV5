package com.example.tradingbot.domain.model.other;

import com.example.tradingbot.domain.model.Auditable;
import com.example.tradingbot.domain.model.trade.candle.TimeFrame;
import java.math.BigDecimal;
import java.time.OffsetDateTime;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

/**
 * Запись одного денежного движения по счёту, привязанная к сделке, —
 * носитель категорийной разбивки результата (сколько комиссии, сколько
 * финансирования, сколько штрафа) и операнд независимой сверки с правой
 * стороной пар (docs/rules/pnl-reconciliation.md). Заголовочное число
 * сделки составляется не отсюда — его состав у дома
 * (docs/models/domain/aggregate/Deal.md); слагаемое чужой валюты —
 * единственное, чем разбивка входит в само число. См.
 * docs/models/domain/other/DealCashFlow.md.
 *
 * <p><b>Время события источника</b> несёт унаследованное audit-поле
 * {@code externalCreatedAt} — событие источника называется конвенционным
 * именем, собственного поля модель не заводит.
 */
@Getter
@Setter
@NoArgsConstructor
public class DealCashFlow extends Auditable {

    /** Внутренний идентификатор в БД. */
    private Long id;

    /**
     * Сделка-владелец. Проставляется при сохранении предикатом линковки
     * (docs/spec/cash-flow-linkage.json); долгоживущая пустая ссылка —
     * форвард-слот под движения счёта вне периода жизни сделок.
     */
    private Long dealId;

    /** Категория движения. Резолвится из типа операции, а не из знака комиссии. */
    private CashFlowCategory category;

    /** Знаковая сумма движения по балансу счёта. Отвечает на вопрос «сходится ли сумма». */
    private BigDecimal amount;

    /**
     * Знаковое изменение маржи позиции записью (сырое, OKX posBalChg).
     * На isolated-марже несёт то, чего нет в балансе: расчёт
     * финансирования ложится сюда при нулевой сумме (наблюдение AG1.7
     * 2026-09-02 — значение равно fundingFee записи закрытия), у
     * торговых записей — перевод маржи. Как поле входит в пары сверки —
     * решает дом сверки (docs/rules/pnl-reconciliation.md), не строка.
     */
    private BigDecimal positionBalanceChange;

    /**
     * Знаковая комиссионная компонента записи, сырая, без нормализации
     * знака. Отвечает на вопрос «сколько комиссии»; взята явным полем, а
     * не выведена из знака суммы — комбинированная запись исказила бы
     * разбивку. Потребитель — композиция левых сторон сверки
     * (docs/spec/pnl-reconciliation.json §flowFeeComponent). Пустота
     * нулём не подменяется.
     */
    private BigDecimal externalFee;

    /**
     * Валюта движения. Сравнивается с расчётной валютой инструмента;
     * чужая валюта — нарушение инварианта, а не рабочий режим: строка
     * персистится, линкуется, пересчитывается и помечается отчётом.
     * Критерием матчинга к сделке не является.
     */
    private String ccy;

    /**
     * Курс пересчёта в расчётную валюту, взятый из свечи на момент
     * операции. Делает слагаемое чужой валюты воспроизводимым постфактум.
     */
    private BigDecimal appliedRate;

    /**
     * Состояние курса на строке. Явный признак, а не вывод из пустоты
     * курса: пустым курс бывает по трём разным причинам.
     */
    private RateStatus rateStatus;

    /** Ссылка на свечу курса: инструмент пары котировки. */
    private String appliedRateCandleInstrument;

    /**
     * Ссылка на свечу курса: таймфрейм. Фиксирует и разрешение —
     * секундное либо огрублённое деградацией
     * (docs/components/RefreshBillsExecutor.md §«Лестница огрубления
     * разрешения»).
     */
    private TimeFrame appliedRateCandleTimeframe;

    /** Ссылка на свечу курса: время открытия интервала. */
    private OffsetDateTime appliedRateCandleOpenTime;

    /**
     * Биржа-владелец движения. Входит в ключ уникальности: идентификатор
     * записи — номенклатура одной площадки, и при втором источнике
     * столкновение дало бы тихую потерю движения.
     */
    private Long exchangeId;

    /**
     * Сырой биржевой идентификатор инструмента — ось предиката линковки:
     * ответ источника аккаунт-широкий, и без инструментной оси предикат
     * подобрал бы движение чужого инструмента в том же окне.
     */
    private String externalInstrumentId;

    /** Идентификатор записи источника. */
    private String externalBillId;

    /** Сырой тип записи. */
    private String externalType;

    /** Сырой подтип записи. */
    private String externalSubType;

    /** Заявка, если движение с ней связано. */
    private String externalOrderId;

    /**
     * Категория движения: ось резолва — тип операции источника
     * (docs/models/mapping/DealCashFlow.md §«Резолв категории»).
     */
    public enum CashFlowCategory {

        /** Реализованный результат — торговое движение: исполнение заявки, закрытие позиции. */
        REALIZED_PNL,

        /** Отдельная запись списания торговой комиссии. */
        TRADE_FEE,

        /** Платёж финансирования. */
        FUNDING,

        /** Отдельная запись возврата комиссии. */
        REBATE,

        /** Запись штрафа ликвидации. */
        LIQ_PENALTY,

        /**
         * Принимающая корзина для нераспознанного типа: счётна, из
         * области сверки исключена, из блокировки итога по неполученному
         * курсу — нет.
         */
        OTHER
    }

    /**
     * Состояние курса пересчёта на строке. Все четыре значения производит
     * одна лестница — docs/components/RefreshBillsExecutor.md §«Лестница
     * огрубления разрешения»; пустота у курса перегружена тремя смыслами,
     * поэтому признак заведён значением.
     */
    public enum RateStatus {

        /** Движение в расчётной валюте — курс не нужен (ступень 1 лестницы). */
        NOT_REQUIRED,

        /** Курс получен и применён (ступени 2-3). */
        APPLIED,

        /** Курс требовался и не получен (ступень 4); строка ждёт догона. */
        RATE_UNAVAILABLE,

        /** Расчётная валюта инструмента не резолвилась — курс не искался вовсе (ступень 0). */
        SETTLE_CURRENCY_UNAVAILABLE
    }
}
