package com.example.tradingbot.domain.model.deal;

public enum DealEvent {

    /**
     * Проверить входные инварианты текущего статуса сделки.
     * <p>
     * Идея:
     * - один и тот же event используется во всех статусах;
     * - конкретный набор инвариантов определяется текущим DealStatus.
     * <p>
     * Примеры:
     * - PRECHECK: инструмент не на паузе, нет другой активной сделки по инструменту.
     * - ENTRY_SUBMITTED: есть рассчитанные параметры входа и clOrdId.
     * - MANAGING: позиция открыта и основная защита уже установлена.
     * <p>
     * Если входные инварианты не выполняются:
     * - либо делаем штатный отказ/блокировку (если это допустимо для данного статуса),
     * - либо переводим сделку в ERROR, если нарушение критично.
     */
    CHECK_ENTRY_INVARIANTS,

    /**
     * Выполнить основное действие текущего статуса сделки.
     * <p>
     * Это главный "рабочий" event FSM.
     * В зависимости от DealStatus может означать:
     * <p>
     * - PRECHECK:
     * прочитать позиции/баланс/pending-ордера и рассчитать параметры входа.
     * <p>
     * - ENTRY_SUBMITTED:
     * отправить обычный entry-ордер с attached Stop-Loss.
     * <p>
     * - ENTRY_FINALIZED:
     * дочитать финальное состояние entry-ордера,
     * подтвердить позицию,
     * подтвердить attached Stop-Loss.
     * <p>
     * - PROTECTION_SWITCHED:
     * создать основные algo-ордера защиты,
     * убедиться, что они активны,
     * снять attached Stop-Loss.
     * <p>
     * - MANAGING:
     * мониторить позицию и защиту,
     * при необходимости обновлять защитные algo-ордера.
     * <p>
     * - EXIT_PENDING:
     * убрать хвосты,
     * собрать fills/algo history,
     * определить причину закрытия сделки.
     * <p>
     * - ERROR:
     * выполнить kill-switch по инструменту:
     * отменить все pending ордера/алго и закрыть позицию.
     */
    PROCESS,

    /**
     * Проверить выходные инварианты текущего статуса сделки.
     * <p>
     * Этот event нужен, чтобы отделить:
     * - "мы сделали запросы/действия"
     * от
     * - "мы действительно достигли целевого результата состояния".
     * <p>
     * Примеры:
     * - ENTRY_FINALIZED:
     * ордер финализирован, позиция подтверждена, attached SL подтверждён.
     * <p>
     * - PROTECTION_SWITCHED:
     * основная защита активна, attached SL снят.
     * <p>
     * - MANAGING:
     * если позиция всё ещё открыта, основной SL обязан быть активен.
     * <p>
     * - EXIT_PENDING:
     * позиции нет, pending хвостов нет, причина закрытия сделки определена.
     * <p>
     * Если выходные инварианты не выполнены:
     * - можно повторить PROCESS/RETRY,
     * - либо перевести сделку в ERROR, если риск неконтролируем.
     */
    CHECK_EXIT_INVARIANTS,

    /**
     * Повторить текущий шаг после временной ошибки или неполного результата.
     * <p>
     * Используется, когда:
     * - API биржи временно недоступно,
     * - данные ещё не успели "дотечь" (eventual consistency),
     * - state уже корректный, но его не удалось подтвердить с первой попытки.
     * <p>
     * Важно:
     * - RETRY не должен ломать идемпотентность;
     * - все команды, порождаемые на RETRY, должны быть безопасны к повтору.
     */
    RETRY,

    /**
     * Принудительно завершить нормальный сценарий и перейти в аварийный.
     * <p>
     * Используется, когда:
     * - обнаружено критическое нарушение торговых инвариантов;
     * - получен внешний kill-switch сигнал;
     * - найден невалидный переход/состояние, продолжать опасно.
     * <p>
     * Обычно этот event ведёт сделку в терминальный статус ERROR,
     * в котором выполняется kill-switch по инструменту.
     */
    FAIL
}