package com.example.tradingbot.domain.model.position;

import com.example.tradingbot.domain.model.Auditable;
import lombok.AllArgsConstructor;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

import java.math.BigDecimal;

import static org.apache.commons.lang3.BooleanUtils.isFalse;

@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
public class Position extends Auditable {

    /**
     * Внутренний идентификатор.
     */
    private Long id;

    /**
     * Идентификатор сделки.
     */
    private Long dealId;

    /**
     * Межсервисный идентификатор.
     */
    private String internalId;

    /**
     * Идентификатор позиции на бирже.
     */
    private String externalId;

    /**
     * Текущий внутренний статус позиции.
     */
    private Status status;

    /**
     * Сторона позиции (long/short/net).
     */
    private Side side;

    /**
     * Причина закрытия.
     */
    private CloseReason closeReason;

    /**
     * Сторона позиции на бирже (long/short/net).
     */
    private String externalSide;

    /**
     * Размер позиции.
     */
    private BigDecimal size;

    /**
     * Средняя цена входа.
     */
    private BigDecimal averagePrice;

    /**
     * Текущая рыночная цена позиции.
     */
    private BigDecimal markPrice;

    /**
     * Оценочная цена ликвидации позиции.
     */
    private BigDecimal liquidationPrice;

    /**
     * Плечо позиции.
     */
    private Integer leverage;

    /**
     * Биржевой режим маржи (cross/isolated).
     */
    private String marginMode;

    /**
     * Нереализованный PnL по позиции.
     */
    private BigDecimal unrealizedProfit;

    public enum Status {

        /**
         * Позиция активна и существует на бирже.
         * Для неё можно получать актуальные цены, PnL и риск-параметры.
         */
        ACTIVE,

        /**
         * Позиция закрыта и больше не активна.
         * Историческая запись может храниться локально для аудита и анализа.
         */
        CLOSED,

        /**
         * Ошибочное состояние позиции.
         * Используется, если локальная модель не согласуется с биржей
         * или произошла ошибка обработки/реконсиляции.
         */
        ERROR
    }

    public enum Side {

        /**
         * Длинная позиция (long).
         * Зарабатываем при росте цены.
         */
        LONG,

        /**
         * Короткая позиция (short).
         * Зарабатываем при падении цены.
         */
        SHORT,

        /**
         * Net-позиция.
         * Используется в режиме net, когда направление задаётся суммарной позицией по инструменту.
         */
        NET
    }

    public enum CloseReason {

        /**
         * Позиция закрыта, потому что сработал Stop-Loss (SL).
         * <p>
         * Типичные признаки (в проекте):
         * - Был активный SL algo-ордер (или attached SL), и затем позиция стала size=0.
         * - В истории/статусах ордеров видно исполнение ордера, который логически соответствует SL.
         * <p>
         * Что важно для аналитики:
         * - Фиксировать "какой SL закрыл" (algoId/attachAlgoId), чтобы понимать качество трейлинга.
         * - Это базовый "негативный" исход сделки (но при трейлинге может закрывать в плюс).
         */
        STOP_LOSS,

        /**
         * Позиция закрыта, потому что сработал Take-Profit (TP).
         * <p>
         * Типичные признаки:
         * - Был активный TP algo-ордер (или attached TP), и затем позиция стала size=0.
         * - В истории/филлах виден ордер/сделка, соответствующая TP.
         * <p>
         * Что важно:
         * - В твоей текущей концепции TP/SL планируется через algo-ордера, поэтому
         * закрытие по TP почти всегда будет приходить из algo-слоя.
         * - Полезно фиксировать уровень (TP1/TP2/TP3), если появятся частичные тейки.
         */
        TAKE_PROFIT,

        /**
         * Позиция закрыта по трейлингу (Trailing Stop), то есть SL "подтягивался" и в итоге закрыл позицию.
         * <p>
         * Отличие от STOP_LOSS:
         * - Формально это тоже SL, но доменно полезно отличать:
         * "закрыло начальным защитным SL" vs "закрыло трейлингом (обычно в плюс)".
         * <p>
         * Типичные признаки:
         * - Использовался trailing algo-ордер или бот регулярно обновлял SL.
         * - Перед закрытием были события обновления SL/переноса в безубыток.
         */
        TRAILING_STOP,

        /**
         * Позиция закрыта по команде стратегии (досрочный выход), не по TP/SL.
         * <p>
         * Когда ставится:
         * - Стратегия решила выйти: смена режима/сигнала, ограничения по времени, фильтры, новости и т.п.
         * <p>
         * Типичные признаки:
         * - Бот инициировал закрытие (например, close-position или reduce-only market/IOC),
         * перед этим мог отменить все algo-ордера защиты.
         * <p>
         * Отличие от MANUAL_CLOSE:
         * - INITIATED_BY_STRATEGY — это автоматическое решение алгоритма.
         */
        STRATEGY_EXIT,

        /**
         * Позиция закрыта вручную пользователем (через UI биржи, мобильное приложение, другой терминал).
         * <p>
         * Когда ставится:
         * - Бот обнаружил, что позиции больше нет, но у него не было команды на закрытие.
         * - По источникам/логам видно, что закрытие не инициировал бот.
         * <p>
         * Что важно:
         * - Это частый кейс при отладке и ручных вмешательствах.
         * - Полезно записывать "кто/где" (если биржа отдаёт источник отмены/закрытия).
         */
        MANUAL_CLOSE,

        /**
         * Позиция закрыта в аварийном режиме (kill-switch / incident / safety policy).
         * <p>
         * Когда ставится:
         * - Сработала политика безопасности: CancelUnknownOrders=true,
         * рассинхрон состояния, критическая ошибка, ручной "STOP" в твоём сервисе и т.д.
         * <p>
         * Типичные признаки:
         * - Бот сначала отменяет все активные ордера и algo-ордера, затем форсированно закрывает позицию.
         * <p>
         * Отличие от STRATEGY_EXIT:
         * - EMERGENCY_CLOSE — это не торговое решение, а реакция на риск/инцидент.
         */
        EMERGENCY_CLOSE,

        /**
         * Позиция закрыта из-за принудительной ликвидации биржей.
         * <p>
         * Когда ставится:
         * - Биржа ликвидировала позицию из-за недостатка маржи/риска.
         * <p>
         * Типичные признаки:
         * - В данных биржи/филлах/истории появляется признак liquidation.
         * - Позиция закрылась без команды бота и без TP/SL, часто с резким ухудшением PnL.
         * <p>
         * Что важно:
         * - Это отдельная категория риска и метрик.
         */
        LIQUIDATION,

        /**
         * Позиция закрыта из-за автоматического снижения рисков биржей (ADL — auto-deleveraging).
         * <p>
         * Когда ставится:
         * - Биржа закрыла/урезала позицию из-за ADL механизма (редкий, но важный кейс для деривативов).
         * <p>
         * Примечание:
         * - Не все биржи явно отдают ADL как причину; иногда это будет "EXCHANGE_FORCED".
         */
        AUTO_DELEVERAGING,

        /**
         * Позиция закрыта биржей/системой по другой принудительной причине, не классифицированной выше.
         * <p>
         * Примеры:
         * - Делистинг/форс-мажор, риск-контроль биржи, техническое закрытие инструмента,
         * принудительное закрытие при смене режима аккаунта, прочие системные события.
         * <p>
         * Рекомендация:
         * - По возможности сохраняй "externalReason" строкой рядом, чтобы потом уточнить классификацию.
         */
        EXCHANGE_FORCED,

        /**
         * Позиция закрылась, но причину определить не удалось (не хватило данных, был рассинхрон,
         * потеря событий, нет истории/филлов, и т.п.).
         * <p>
         * Важно:
         * - Лучше иметь явный UNKNOWN, чем гадать и портить аналитику.
         * - При расследовании можно пересчитать/доклассифицировать позже.
         */
        UNKNOWN
    }

    public void toClose(CloseReason closeReason) {
        setStatus(Status.CLOSED);
        setCloseReason(closeReason);
    }

    public boolean isLive() {
        return status == Status.ACTIVE;
    }

    public boolean isNotLive() {
        return isFalse(isLive());
    }
}
