package com.example.tradingbot.domain.model.trade.market;

import lombok.AllArgsConstructor;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

/**
 * Снимок текущей рыночной фазы по инструменту.
 * <p>
 * Это не торговое действие и не сигнал на вход.
 * Это именно описание состояния рынка на текущий момент,
 * которое потом использует стратегия.
 */
@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
public class MarketPhase {

    /**
     * Инструмент, для которого определена фаза рынка.
     */
    private Long instrumentId;

    /**
     * Тип рыночной фазы.
     */
    private Type type;

    /**
     * Произвольный диагностический комментарий/обоснование,
     * почему сервис классифицировал рынок именно так.
     * <p>
     * Пример:
     * "EMA50 > EMA200, цена выше EMA50, ATR в норме"
     */
    private String comment;

    /**
     * Фазы рынка в доменных терминах.
     */
    public enum Type {

        /**
         * Восходящий тренд.
         * <p>
         * Обычно означает:
         * - приоритет для long-сценариев;
         * - short либо запрещён, либо ослаблен;
         * - стратегия использует bullish-настройки.
         */
        BULL_TREND,

        /**
         * Нисходящий тренд.
         * <p>
         * Обычно означает:
         * - приоритет для short-сценариев;
         * - long либо запрещён, либо ослаблен;
         * - стратегия использует bearish-настройки.
         */
        BEAR_TREND,

        /**
         * Боковой рынок / диапазон / флэт.
         * <p>
         * Обычно означает:
         * - трендовые входы ослабляются или запрещаются;
         * - стратегия может использовать отдельные правила для range-торговли
         * либо вообще не торговать.
         */
        RANGE,

        /**
         * Фаза не определена или определена недостаточно уверенно.
         * <p>
         * Обычно это безопасный fallback:
         * - не входить в сделку,
         * - либо использовать максимально консервативные правила.
         */
        UNKNOWN
    }

    public boolean isUnknown() {
        return type == Type.UNKNOWN;
    }
}
