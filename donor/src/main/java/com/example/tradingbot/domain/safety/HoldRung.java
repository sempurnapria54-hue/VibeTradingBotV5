package com.example.tradingbot.domain.safety;

/**
 * Ступень safety-реакции. Ось разведения одна — <b>судьба принятого
 * риска</b>, и она общая у обеих лестниц, инструментной и биржевой
 * (docs/rules/instrument-hold.md, docs/rules/exchange-hold.md). Второй оси
 * в модели нет: тип исключения резолвит РАДИУС реакции, ступень — только
 * эту ось.
 */
public enum HoldRung {

    /**
     * Мягкая: принятый риск ОСТАЁТСЯ жить под своей защитой, запрещается
     * только новый (и ослабление стоящей защиты). Kill-switch в составе
     * реакции нет, отчёт — {@code NON_CRITICAL}.
     */
    SOFT,

    /**
     * Жёсткая: принятый риск СНИМАЕТСЯ kill-switch'ем, активные сделки
     * радиуса уходят в ошибочное состояние. Отчёт — {@code CRITICAL}.
     */
    HARD
}
