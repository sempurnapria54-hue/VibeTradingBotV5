package com.example.tradingbot.domain.safety;

import com.example.tradingbot.domain.model.core.instrument.Instrument;
import lombok.Builder;
import lombok.Value;

/**
 * Наблюдение одного детектора: что найдено, на каком объекте и какой
 * ступенью на это отвечает лестница.
 *
 * <p><b>Ступень и радиус приходят СЮДА уже выведенными.</b> Детектор их
 * не назначает: они выводятся тремя ратифицированными осями, и дом
 * реакции у каждого кода уже существует (docs/components/AnomalyJob.md
 * §«Что ищет»). Находка — параметр вызова реакции, а не решение о ней.
 */
@Value
@Builder
public class AnomalyFinding {

    /** Радиус — выбирает исполнителя статуса. */
    HoldScope scope;

    /** Ступень — судьба принятого риска. */
    HoldRung rung;

    /** Машинный код причины; попадает в отчёт и в ключ его дедупа. */
    String code;

    /**
     * Инструмент радиуса; пуст у биржевых детекторов. У биржевого
     * детектора, нашедшего признак ПО инструменту (чужая заявка), он
     * тоже пуст: радиус реакции биржевой, а инструмент едет в предмет.
     */
    Instrument instrument;

    /**
     * Сущность-предмет — четвёртая величина ключа дедупа у отчёта без
     * блокировки. Пуст у отчёта с блокировкой.
     */
    String subjectExternalId;

    /**
     * Сколько подряд идущих тиков признак обязан держаться, прежде чем
     * поднимается ступень. Единица — реакция с первого наблюдения.
     */
    Integer hysteresisTicks;

    /**
     * Блокировки в составе реакции нет — находка заводит только строку
     * журнала. Признак объявляется детектором явно, а не выводится из
     * наличия предмета: кортеж «радиус × ступень» у журнальной находки и
     * у мягкой ступени один и тот же, и различает их только назначение
     * (docs/components/models/HoldSignal.md §Фабрики).
     */
    Boolean journalOnly;

    /** Реакция снимает принятый риск. */
    public Boolean tearsDownRisk() {
        return HoldRung.HARD.equals(rung);
    }
}
